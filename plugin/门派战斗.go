func init() {
	Register(&门派战斗{})
}

// 战场类型 一个战场类型：名称 + 点击区域 + 是否启用 + 处理方法（直接配好要调的方法）
type 战场类型 struct {
	名称     string
	区域     [4]int // 点击区域 x1,y1,x2,y2
	启用     bool   // 是否启用（未被启用的跳过）
	处理方法 func() // 该类型的处理方法（在变量里直接配好）
}

// 战场类型表 依次点击"已启用"的类型，调用各自配好的处理方法
var 战场类型表 = []战场类型{
	{名称: "罚神讨伐令", 区域: [4]int{58, 145, 138, 169}, 启用: true, 处理方法: 处理注册分身},
	{名称: "边疆防御", 区域: [4]int{60, 205, 142, 231}, 启用: true, 处理方法: 处理注册分身},
	{名称: "迷雾的花园", 区域: [4]int{52, 263, 142, 293}, 启用: true, 处理方法: 处理迷雾的花园},
	{名称: "神器争夺战", 区域: [4]int{70, 333, 124, 351}, 启用: true, 处理方法: 处理神器争夺战},
}

// 门派战斗 插件：循环点击"已启用"的战场类型，调用各自配好的处理方法。
type 门派战斗 struct{}

func (p *门派战斗) Name() string { return "门派战斗" }

func (p *门派战斗) Exec(ctx *Context) (string, error) {
	for _, 类型 := range 战场类型表 {
		if IsStopped() {
			return "no", nil
		}
		if !类型.启用 {
			continue
		}
		core.LogWithTimef("[门派战斗] 点击战场类型【%s】(%d,%d,%d,%d)",
			类型.名称, 类型.区域[0], 类型.区域[1], 类型.区域[2], 类型.区域[3])
		core.RandomClickInAreaWithDelay(类型.区域[0], 类型.区域[1], 类型.区域[2], 类型.区域[3])

		类型.处理方法() // 调用该类型在变量里配好的方法
	}
	return "ok", nil
}

// 处理注册分身 公共方法：罚神讨伐令 / 边疆防御 都走这里（注册分身 → 确认）
func 处理注册分身() {
	ClickRecog("注册分身")
	ClickRecog("确认")
}

