package zt

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 背包物品 —— 子任务（照 plugin/物品使用.go + assets/tasks/背包物品.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	背包 → 背包分类on → 按分类逐个点背包格子（28 格）
//	→ 每点开一个格子：扫一遍弹窗（使用/打开/选蓝色装备/选黄色武功/生命的精华/
//	  狙击强化书/铁矿/全部/确认/盒子列表/关闭/点击关闭），命中的就点
//	→ 连续 3 格点不出东西 → 下一个分类 → 自动装备 → 关闭
//
// ★ 不搞 plugin 的 ClickAdaptive 2 秒循环：格子点开后每轮扫一遍弹窗（命中的就点），
//   剩下的交给主循环下一轮（弹窗连锁靠"每轮都扫"自然消化）。
// ★ 背包会重排（用了的物品后面往前补位）：所以每轮【重新点当前格】，不往后走；
//   点不出东西才往后走一格（照 plugin 的 col-- 语义改成标志位）。
// ══════════════════════════════════════════════════════════════════════════

// 背包分类 需要遍历点击的分类（顺序即处理顺序）
var 背包分类 = []string{"消耗品"}

// 背包格子：区域起点 (933,175)，格子 63x62，左右间隔 6（X 步长 69），上下间隔 7（Y 步长 69），
// 一行 4 格，共 7 行 = 28 格。
const (
	格子起点X = 933
	格子起点Y = 175
	格子宽   = 63
	格子高   = 62
	格子步长X = 69
	格子步长Y = 69
	格子列数 = 4
	格子行数 = 7
)

// 连续空格子上限 连续这么多次格子都点不出东西 → 结束当前分类的循环（一旦有物品就清零重数）
const 连续空格子上限 = 3

// ── 背包物品自己的状态 ────────────────────────────────────────────────────
var (
	背第几类   = 0     // 当前第几个分类（背包分类 的下标）
	背包行     = 0     // 当前第几行（0 起）
	背包列     = 0     // 当前第几列（0 起）
	背包空格   = 0     // 连续多少个格子点不出东西（够了 → 下一个分类）
	背包已完成 = false // 分类全走完 + 面板已关（= 完成）
)

// 背包物品重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 背包物品重置() {
	背第几类 = 0
	背包行 = 0
	背包列 = 0
	背包空格 = 0
	背包已完成 = false
}

// 背包物品完成 = 分类全走完且面板已关（背包识别不到）
func 背包物品完成() bool { return 背包已完成 }

// 背包物品跑 子任务流程（每轮由 跑子任务() 调度，每轮只点该点的）
func 背包物品跑() {
	// 入口：背包 → 背包分类on（命中就点，不命中就过 → 下一轮再来）
	查找点击延时("背包")
	查找点击延时("背包分类on")

	// 入口还没点开 → 本轮不干活
	if _, _, ok := 识别("背包"); !ok {
		return
	}

	// 分类全走完 → 收尾：自动装备 → 关闭（照 JSON 步骤链，无"退出"）
	if 背第几类 >= len(背包分类) {
		core.LogWithTimef("[背包物品] 分类已全部处理 → 收尾（自动装备 → 关闭）")
		查找点击延时("自动装备")
		查找点击延时("关闭")
		if _, _, ok := 识别("背包"); !ok {
			背包已完成 = true // 背包面板已关 → 本子任务做完
		}
		return
	}

	// 切到当前分类（分类 tab 的识别引用就是分类名）
	分类 := 背包分类[背第几类]
	查找点击延时(分类)

	// 格子走完了（一行 4 格、共 7 行）→ 下一个分类
	if 背包行 >= 格子行数 {
		core.LogWithTimef("[背包物品] 分类【%s】格子已全部点过 → 下一个分类", 分类)
		背第几类++
		背包行 = 0
		背包列 = 0
		背包空格 = 0
		return
	}

	// 点当前格中心
	x1 := 格子起点X + 背包列*格子步长X
	y1 := 格子起点Y + 背包行*格子步长Y
	cx := x1 + 格子宽/2
	cy := y1 + 格子高/2
	core.LogWithTimef("[背包物品] 点格子(行%d,列%d) 中心(%d,%d)", 背包行+1, 背包列+1, cx, cy)
	core.RandomClickInAreaWithDelay(cx, cy, cx, cy)

	// 点开后扫一遍弹窗：命中的就点（本轮扫完即止，连锁的下一轮继续扫）
	if 扫弹窗([]string{
		"使用", "打开", "选蓝色装备", "选黄色武功", "生命的精华", "狙击强化书",
		"铁矿", "全部", "确认", "盒子列表", "关闭", "点击关闭", "山贼的戒指图案",
	}) {
		// 有东西 → 计数清零；【不往后走】（背包会重排，下一轮仍点这一格）
		背包空格 = 0
		return
	}

	// 空格子 → 往后走一格
	背包空格++
	core.LogWithTimef("[背包物品] 空格子，连续 %d 次", 背包空格)
	if 背包空格 >= 连续空格子上限 {
		core.LogWithTimef("[背包物品] 连续 %d 次空格子 → 结束当前分类【%s】", 连续空格子上限, 分类)
		背第几类++
		背包行 = 0
		背包列 = 0
		背包空格 = 0
		return
	}
	背包列++
	if 背包列 >= 格子列数 {
		背包列 = 0
		背包行++
	}
}
