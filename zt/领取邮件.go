package zt

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 领取邮件 —— 子任务（照 plugin/领取邮件.go + assets/tasks/领取邮件.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	点【邮件】开面板 → 红点多个(14,66,598,134) 逐个点
//	→ 每个点完紧跟扫一遍弹窗（完成对钩/点击关闭）→ 点【退出】收尾
// ══════════════════════════════════════════════════════════════════════════

// ── 领取邮件自己的状态 ────────────────────────────────────────────────────
var (
	领取邮件第几个 = 0    // ★ 状态：红点点到第几个（跨轮推进，被打断回来接着点）
	领取邮件已收  = false // 完成：红点全点完 + 退出点了
)

// 领取邮件重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 领取邮件重置() {
	领取邮件第几个 = 0
	领取邮件已收 = false
}

// 领取邮件完成 = 红点全领完（状态走到尽头）
func 领取邮件完成() bool { return 领取邮件已收 }

// 领取邮件跑 子任务流程（每轮由 跑子任务() 调度，每轮只点该点的）
func 领取邮件跑() {
	// 入口：点【邮件】开面板（命中就点，不命中就过 → 下一轮再来）
	查找点击延时("邮件")

	// 红点多个：每轮只点当前指到的那个，状态 +1（照 画册.go 外层红点）
	红点 := 识别多个("红点", 14, 66, 598, 134)
	if 领取邮件第几个 < len(红点) {
		点 := 红点[领取邮件第几个]
		core.LogWithTimef("[领取邮件] 红点(%d,%d) → 点击", 点.X, 点.Y)
		core.RandomClickInAreaWithDelay(点.X, 点.Y, 点.X+5, 点.Y+5)
		扫弹窗([]string{"完成对钩", "点击关闭"})
		领取邮件第几个++
		return
	}

	// 红点没了（状态走到尽头 = 真干完了）→ 才点退出 → 完成
	// ★ 退出不是判据（它永远都在），判据是"红点识别不到"
	core.LogWithTimef("[领取邮件] 红点已全部领取 → 点【退出】")
	查找点击延时("退出")
	领取邮件已收 = true
}
