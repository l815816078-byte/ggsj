// ══════════════════════════════════════════════════════════════════════════
// 成长 —— 子任务（照 plugin/成长.go + assets/tasks/成长.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	主菜单 → 成长 → 按 成长类型列表 依次切换类型/子分类：
//	  每个子分类：取【已装备】多个 → 逐个点开 →（可选：先点【可觉醒】）
//	  → 检测到【确定花钱】→ 点【棕色按钮】→ 点【确定花钱】（每件最多 3 次）
//	→ 退出
//
// ★ 不搞 plugin 的"for 已装备 { for 3 次 }"一次跑完：用标志位记
//   【第几个类型 → 第几个子分类 → 第几件装备 → 第几次花钱】，每轮只干一格，
//   剩下的交给主循环下一轮（照 买药.go 的标志位做法，不写步骤指针）。
// ══════════════════════════════════════════════════════════════════════════

// 成长子分类方法 无参无返回（参数用闭包固定）
type 成长子分类方法 func()

// 成长子分类 名称 + 识别引用（点击切到该子分类用；第一个子分类默认已选中，不点击）+ 方法
type 成长子分类 struct {
	名称 string
	识别 string
	方法 成长子分类方法
}

// 成长类型 名称 + 入口识别引用（空 = 默认就在该类型，不点击切换）+ 子分类列表
type 成长类型 struct {
	名称   string
	入口   string
	子分类 []成长子分类
}

// 成长类型列表 默认一进来就在【装备-强化】界面；切换成长分类后默认选中第一个子分类
var 成长类型列表 = []成长类型{
	{
		名称: "装备",
		入口: "", // 默认就在装备，无需点击
		子分类: []成长子分类{
			{名称: "强化", 识别: "强化", 方法: func() { 装备处理("装备-强化", "已装备", false) }}, // 默认选中
			{名称: "突破", 识别: "突破", 方法: func() { 装备处理("装备-突破", "已装备", false) }},
			{名称: "觉醒", 识别: "觉醒", 方法: func() { 装备处理("装备-觉醒", "已装备_可觉醒", true) }},
		},
	},
	{
		名称: "加护",
		入口: "成长加护",
		子分类: []成长子分类{
			{名称: "强化", 识别: "强化", 方法: func() { 装备处理("加护-强化", "已装备", false) }}, // 默认选中
			{名称: "觉醒", 识别: "觉醒", 方法: func() { 装备处理("加护-觉醒", "已装备", false) }}, // 共用同一方法
		},
	},
	{
		名称: "道术",
		入口: "成长道术",
		子分类: []成长子分类{
			{名称: "强化", 识别: "强化", 方法: func() { 道术强化("道术-强化") }}, // 默认选中
			{名称: "觉醒", 识别: "觉醒", 方法: nil},                              // 留空
		},
	},
}

// ── 成长自己的状态（第几个类型 → 第几个子分类 → 第几件 → 第几次花钱）──────────
var (
	成长第几类 = 0 // 成长类型列表 的下标
	成长第几子 = 0 // 当前类型的子分类下标
	成长第几件 = 0 // 【已装备】多个点到第几个
	成长第几次 = 0 // 当前这件第几次花钱（每件最多 3 次）
)

// 成长重置 由 跑子任务() 在【冷却到点、本趟重新开始】时调（= 各任务自己的重置）
func 成长重置() {
	成长第几类 = 0
	成长第几子 = 0
	成长第几件 = 0
	成长第几次 = 0
}

// 成长跑 子任务流程（每轮由 跑子任务() 调度，每轮只干一格）
func 成长跑() {
	// 入口：主菜单 → 成长（命中就点，不命中就过 → 下一轮再来）
	查找点击延时("主菜单")
	查找点击延时("成长")

	// 入口还没点开 → 本轮不干活
	if _, _, ok := 识别("成长"); !ok {
		return
	}

	// 类型表走完了 → 收工退出
	if 成长第几类 >= len(成长类型列表) {
		core.LogWithTimef("[成长] 类型表已走完 → 点【退出】")
		查找点击延时("退出")
		if _, _, ok := 识别("退出"); !ok {
			成长重置() // 退出也没了 → 面板已关，重置等下一趟
		}
		return
	}
	类型 := 成长类型列表[成长第几类]

	// 切到该成长类型（入口为空 = 默认就在该类型，不点击）；每个类型之间间隔 2-3 秒
	if 类型.入口 != "" {
		if 查找点击延时(类型.入口) {
			core.LogWithTimef("[成长] 已切到成长类型【%s】", 类型.名称)
			core.RandomSleep(2000, 3000)
		}
	}

	// 子分类走完了 → 下一个类型
	if 成长第几子 >= len(类型.子分类) {
		core.LogWithTimef("[成长] 类型【%s】子分类已全部处理 → 下一个类型", 类型.名称)
		成长第几类++
		成长第几子 = 0
		成长第几件 = 0
		成长第几次 = 0
		return
	}
	子 := 类型.子分类[成长第几子]

	// 切换成长分类后默认选中第一个子分类 → 第一个点击分类(59,139,97,163)【强行切换】；
	// 其余先点子分类再点【取消成长选中】
	if 成长第几子 > 0 {
		if 查找点击延时(子.识别) {
			查找点击延时("取消成长选中")
		}
	} else {
		core.LogWithTimef("[成长] 【%s】第一个子分类 → 强行切换，点击分类 59,139,97,163", 类型.名称)
		core.RandomClickInAreaWithDelay(59, 139, 97, 163)
	}

	// 方法未配置（道术-觉醒 留空）→ 下一个子分类
	if 子.方法 == nil {
		core.LogWithTimef("[成长] 【%s-%s】方法未配置 → 跳过", 类型.名称, 子.名称)
		成长第几子++
		成长第几件 = 0
		成长第几次 = 0
		return
	}

	core.LogWithTimef("[成长] 执行【%s-%s】（第 %d 件 / 第 %d 次）", 类型.名称, 子.名称, 成长第几件+1, 成长第几次+1)
	子.方法()
}

// ── 以下两个是 成长类型列表 里闭包调的方法（照 plugin/成长.go 搬） ──────────

// 装备处理 通用流程（装备/加护的强化、突破、觉醒共用）：
//
//	取【已装备】(区域在预设里) 多个 → 当前指到的那件点开
//	→（可选：先点【可觉醒】）→ 检测到【确定花钱】→ 点【棕色按钮】(区域 297,619,353,700) → 点【确定花钱】
//	每件最多 3 次；这件做完 → 下一件（标志位推进，不写循环）
//
// 标签 = 成长类型-子分类（仅用于日志，便于看出当前处理的是哪个分类）
func 装备处理(标签, 预设名 string, 需可觉醒 bool) {
	已装备 := 识别多个(预设名)
	if 成长第几件 >= len(已装备) {
		// 这件分类的装备全点完了 → 下一个子分类
		core.LogWithTimef("[成长] 【%s】装备已全部处理（%d 件）→ 下一个子分类", 标签, len(已装备))
		成长第几子++
		成长第几件 = 0
		成长第几次 = 0
		return
	}

	// 本件第一次进来 → 点开它（点开后不往后走，下一轮还是这件，直到 3 次花完钱）
	if 成长第几次 == 0 {
		点 := 已装备[成长第几件]
		core.LogWithTimef("[成长] 【%s】(需可觉醒=%v) 点击(%d,%d)", 标签, 需可觉醒, 点.X, 点.Y)
		core.RandomClickInAreaWithDelay(点.X, 点.Y, 点.X+5, 点.Y+5)

		// 点开后再点一下【可觉醒】
		if 需可觉醒 {
			if 查找点击延时("可觉醒") {
				core.LogWithTimef("[成长] 【%s】已点【可觉醒】", 标签)
			} else {
				core.LogWithTimef("[成长] 【%s】未找到【可觉醒】→ 跳过", 标签)
			}
		}
	}

	// 本件最多 3 次：检测到【确定花钱】→ 先点【棕色按钮】，再点【确定花钱】
	if x, y, ok := 识别("确定花钱"); ok {
		core.LogWithTimef("[成长] 【%s】第%d次 检测到【确定花钱】(%d,%d) → 点【棕色按钮】(区域 297,619,353,700)",
			标签, 成长第几次+1, x, y)
		查找点击延时("棕色按钮", 297, 619, 353, 700)
		core.RandomClickInAreaWithDelay(x, y, x, y)
		core.LogWithTimef("[成长] 【%s】第%d次 已点击【确定花钱】(%d,%d)", 标签, 成长第几次+1, x, y)
		成长第几次++

		// 需可觉醒时：确定花钱点完后 → 点一下【取消成长选中】
		if 需可觉醒 {
			core.LogWithTimef("[成长] 【%s】点【取消成长选中】", 标签)
			查找点击延时("取消成长选中")
		}

		// 3 次花完 → 下一件
		if 成长第几次 >= 3 {
			core.LogWithTimef("[成长] 【%s】本件 3 次已满 → 下一件", 标签)
			成长第几件++
			成长第几次 = 0
		}
		core.RandomSleep(300, 500)
		return
	}

	// 检测不到【确定花钱】→ 本件没啥可花的了 → 下一件
	core.LogWithTimef("[成长] 【%s】第%d次未检测到【确定花钱】→ 本件结束，下一件", 标签, 成长第几次+1)
	成长第几件++
	成长第几次 = 0
}

// 道术强化 道术-强化 子分类方法：红点多个(1198,103,1243,720) 数量8，
// 当前指到的那个点开 → 检测到【确定花钱】→ 点【棕色按钮】→ 点【确定花钱】（每件最多 3 次）
// → 点完从下往上滑一次（滑完下一轮会重取红点，位置可能变，靠 成长第几件 推进）
func 道术强化(标签 string) {
	红点 := 识别多个("红点8", 1198, 103, 1243, 720)
	if 成长第几件 >= len(红点) {
		core.LogWithTimef("[成长] 【%s】红点已全部处理（%d 个）→ 下一个子分类", 标签, len(红点))
		成长第几子++
		成长第几件 = 0
		成长第几次 = 0
		return
	}

	// 本件第一次进来 → 点开它
	if 成长第几次 == 0 {
		点 := 红点[成长第几件]
		core.LogWithTimef("[成长] 【%s】点击红点(%d,%d)", 标签, 点.X, 点.Y)
		core.RandomClickInAreaWithDelay(点.X, 点.Y, 点.X+5, 点.Y+5)
	}

	// 本件最多 3 次：检测到【确定花钱】→ 先点【棕色按钮】，再点【确定花钱】
	if x, y, ok := 识别("确定花钱"); ok {
		core.LogWithTimef("[成长] 【%s】第%d次 检测到【确定花钱】(%d,%d) → 点【棕色按钮】(区域 297,619,353,700)",
			标签, 成长第几次+1, x, y)
		查找点击延时("棕色按钮", 297, 619, 353, 700)
		core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
		core.LogWithTimef("[成长] 【%s】第%d次 已点击【确定花钱】(%d,%d)", 标签, 成长第几次+1, x, y)
		成长第几次++
		if 成长第几次 >= 3 {
			// 3 次花完 → 从下往上滑一次，再下一件
			cx := (1021 + 1082) / 2
			core.LogWithTimef("[成长] 【%s】从下往上滑动 (%d,%d)→(%d,%d)", 标签, cx, 589, cx, 263)
			core.RandomSwipe(cx, 589, cx, 263, 1500)
			成长第几件++
			成长第几次 = 0
		}
		core.RandomSleep(300, 500)
		return
	}

	// 检测不到【确定花钱】→ 本件结束，下一件
	core.LogWithTimef("[成长] 【%s】第%d次未检测到【确定花钱】→ 本件结束，下一件", 标签, 成长第几次+1)
	成长第几件++
	成长第几次 = 0
}
