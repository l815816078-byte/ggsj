package zt

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 支线任务（照 plugin/支线任务.go + assets/tasks/支线任务.json 搬）
//
// 老框架：点【支线任务】→ 点【组队】【任务入口】→ 自适应点 接受/确认/立即传送/绿色按钮/引导
//	→ 循环调【躲避技能】插件
//
// zt 写法：平铺，命中就点 + return。没有自适应点击，按 plugin 的按钮顺序从上往下扫。
//
// ★ 【组队】是点库里单独建的预设；【任务入口】不单独建 —— 它认的就是"任务"两个字，
//   直接用现成的"任务"预设 + 调用处传区域（1225,101,1252,128）。
// ══════════════════════════════════════════════════════════════════════════

// 支线面板已开 点过【支线任务】了没（点完面板标题不消失 → 标志位挡）
var 支线面板已开 = false

// 切换刷新（③）的两个标志位：
//
//	支线已点组队 = 点过【组队】；支线已刷新 = 【组队】→【任务】这一趟走完了
//	★ 它是"点一下组队再点一下任务"的切换刷新动作（把列表刷出来），不是"一直找到就一直点"，
//	  所以做完一趟就置位挡住，绝不再点第二次。
var (
	支线已点组队 = false
	支线已刷新  = false
)

// 支线任务重置 由 切下一个任务() / 重跑当前任务() 调
func 支线任务重置() {
	支线面板已开 = false
	支线已点组队 = false
	支线已刷新 = false
	躲避技能重置()
}

// 支线任务跑 一轮干一格
func 支线任务跑() {
	// ① 引导（照 plugin 的按钮表：引导提示 / 引导手势 排在接受类之后，这里照 JSON 放最前）
	当前状态 = "引导"
	if 查找点击延时("引导提示") {
		return
	}
	if 查找点击延时("引导手势") {
		return
	}

	// ② 支线进行中 → 躲技能（照 JSON：支线进行中 → 回 StartUp，进行中就是"在打")
	if _, _, ok := 识别("支线进行中"); ok {
		躲避技能跑()
		return
	}

	// ③ 切换刷新（照 plugin 的 点组队与任务入口()）：点【组队】→ 再点【任务】= 切一下页签把列表刷出来
	//    ★ 只做一趟：做完就置 支线已刷新（这是切换动作，不能一直点 —— 一直点等于来回切，永远进不去）
	//    ★ 找得到"下一步"就算成功：【支线任务】（面板入口）已经在屏幕上 → 刷新算完成，不用再切
	if !支线已刷新 {
		当前状态 = "刷新支线"
		if _, _, ok := 识别("支线任务"); ok {
			core.LogWithTimef("[支线任务] 已能看到【支线任务】→ 切换刷新算完成")
			支线已刷新 = true
			return
		}
		if !支线已点组队 {
			if 查找点击延时("组队") {
				支线已点组队 = true
			}
			return
		}
		// 【任务入口】= 右上角那个"任务"两个字 → 直接用现成的"任务"预设 + 这里传区域
		if 查找点击延时("任务", 1225, 101, 1252, 128) {
			core.LogWithTimef("[支线任务] 【组队】→【任务】切换刷新完成")
			支线已刷新 = true
		}
		return
	}

	// ④ 点【支线任务】开面板
	if !支线面板已开 {
		当前状态 = "开支线面板"
		if 查找点击延时("支线任务") {
			支线面板已开 = true
		}
		return
	}

	// ⑤ 接取链（照 plugin 的 ClickAdaptive 按钮顺序：接受 → 确认 → 立即传送 → 绿色按钮）
	当前状态 = "接取支线"
	if 查找点击延时("接受") {
		return
	}
	if 查找点击延时("确认") {
		return
	}
	if 查找点击延时("立即传送") {
		return
	}
	if 查找点击延时("绿色按钮") {
		return
	}
}
