package zt

// ══════════════════════════════════════════════════════════════════════════
// 支线任务（照 plugin/支线任务.go + assets/tasks/支线任务.json 搬）
//
// 老框架：点【支线任务】→ 点【组队】【任务入口】→ 自适应点 接受/确认/立即传送/绿色按钮/引导
//	→ 循环调【躲避技能】插件
//
// zt 写法：平铺，命中就点 + return。没有自适应点击，按 plugin 的按钮顺序从上往下扫。
//
// ★ 点库里【组队】【任务入口】两条预设还没有（只在 ziku.txt 有"组队"词条、recogs.json 没有），
//   补上才生效；没补之前这两行会打"配置缺失"日志，不影响其它步骤。
// ══════════════════════════════════════════════════════════════════════════

// 支线面板已开 点过【支线任务】了没（点完面板标题不消失 → 标志位挡）
var 支线面板已开 = false

// 支线任务重置 由 切下一个任务() / 重跑当前任务() 调
func 支线任务重置() {
	支线面板已开 = false
	躲避技能重置()
}

// 支线任务跑 一轮干一格
func 支线任务跑() {
	// ① 引导（照 plugin 的按钮表：引导提示 / 引导手势 排在接受类之后，这里照 JSON 放最前）
	if 查找点击延时("引导提示") {
		return
	}
	if 查找点击延时("引导手势") {
		return
	}

	// ② 支线进行中 → 躲技能（照 JSON：支线进行中 → 回 StartUp，进行中就是"在打")
	if _, _, ok := 识别("支线进行中"); ok {
		躲避技能跑()
		return
	}

	// ③ 接取前：先点【组队】【任务入口】（照 plugin 的 点组队与任务入口()）
	if 查找点击延时("组队") {
		return
	}
	if 查找点击延时("任务入口") {
		return
	}

	// ④ 点【支线任务】开面板
	if !支线面板已开 {
		if 查找点击延时("支线任务") {
			支线面板已开 = true
		}
		return
	}

	// ⑤ 接取链（照 plugin 的 ClickAdaptive 按钮顺序：接受 → 确认 → 立即传送 → 绿色按钮）
	if 查找点击延时("接受") {
		return
	}
	if 查找点击延时("确认") {
		return
	}
	if 查找点击延时("立即传送") {
		return
	}
	if 查找点击延时("绿色按钮") {
		return
	}
}
