package zt

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 主线任务（照 assets/tasks/主线任务.json 的步骤链搬）
//
// 老框架步骤链：StartUp → 引导手势 / 引导提示 / 躲避技能 / 主线进行中 / 主线任务 / 确认
//	主线任务(点击) → 确认(点击) → 主线进行中(检测) → 回 StartUp
//	躲避技能(插件) → 主线进行中
//	检测复活(点击【复活】) → #done
//
// zt 写法：一轮之内把 if 顺序过完，命中的就点 + return（下一轮再来）。
// 顺序照 JSON 的优先级：引导 → 复活 → 进行中(躲技能) → 接任务。
// ══════════════════════════════════════════════════════════════════════════

// 主线已点任务 点过【主线任务】了没（它点完不消失 → 标志位挡，否则每轮重复点）
var 主线已点任务 = false

// 主线任务重置 由 切下一个任务() / 重跑当前任务() 调
func 主线任务重置() {
	主线已点任务 = false
	躲避技能重置()
}

// 主线任务跑 一轮干一格
func 主线任务跑() {
	// ① 引导（照 JSON 开头的 引导手势 / 引导提示 两步）
	if 查找点击延时("引导手势") {
		return
	}
	if 查找点击延时("引导提示") {
		return
	}

	// ② 死了 → 点【复活】（照 JSON 的"检测复活"步骤：命中 → #done = 结束本任务）
	if 查找点击延时("复活") {
		core.LogWithTimef("[主线任务] 检测到【复活】→ 已点击，结束主线")
		切下一个任务()
		return
	}

	// ③ 主线进行中 → 打 BOSS 时躲技能（照 JSON 的"躲避技能"插件步骤）
	//    躲避技能跑() 自己会先检 BOSS：没 BOSS 直接返回，不影响正常跑主线
	if _, _, ok := 识别("主线进行中"); ok {
		躲避技能跑()
		return
	}

	// ④ 没在进行中 → 接主线：点【主线任务】
	if !主线已点任务 {
		if 查找点击延时("主线任务") {
			主线已点任务 = true
		}
		return
	}

	// ⑤ 点【确认】接取（照 JSON：主线任务 → 确认 → 主线进行中）
	查找点击延时("确认")
}
