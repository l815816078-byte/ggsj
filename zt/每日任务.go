// ══════════════════════════════════════════════════════════════════════════
// 每日任务（照 plugin/每日任务.go + assets/tasks/每日任务.json 搬）
//
// 老框架：主菜单 → 滑动 → 点【任务】→ 插件（【每日】【周常】两个 tab 循环接取
//	→ 点【每日】→ 【绿色战力】多个逐个点 → 打怪任务 → 自动进行 → 蓝色按钮）
//	→ 退出 → 一次都没点过蓝色按钮 = 直接完成；点过 = 进 挂机中 打怪
//
// zt 写法：每轮干一格，进度全靠标志位（第几个 tab / 滑了几次 / 第几个战力）。
// ══════════════════════════════════════════════════════════════════════════

// 是否接取无需战力任务 是否接取"无需战力"的任务（照 plugin 默认 true）
const 是否接取无需战力任务 = true

// 每日类型列表 依次切到每个 tab 处理（照 plugin 原样搬）
var 每日类型列表 = []string{"每日", "周常"}

// 每日最多滑动 每个 tab 最多滑动次数（照 plugin 的 最多滑动次数 = 5）
const 每日最多滑动 = 5

// ── 每日任务自己的状态 ────────────────────────────────────────────────────
var (
	每日菜单已点 = false // 点过【主菜单】
	每日已滑动   = false // 入口滑动做过了没
	每日面板已开 = false // 点过【任务】进面板了没

	每日第几类型 = 0      // 现在在处理 每日类型列表 的第几个
	每日已切类型 = false  // 当前 tab 切过去了没
	每日滑动次数 = 0      // 当前 tab 已经滑了几次

	每日已点每日     = false // 接取阶段结束、点过【每日】了没
	每日第几个战力   = 0     // 【绿色战力】多个里点第几个
	每日已点蓝色按钮 = false // 一次都没点过【蓝色按钮】→ 任务直接算完成（照 plugin）
	每日已接完       = false // 接取全做完 → 打阶段（调 挂机跑()）
)

// 每日任务重置 由 切下一个任务() / 重跑当前任务() 调
func 每日任务重置() {
	每日菜单已点 = false
	每日已滑动 = false
	每日面板已开 = false
	每日第几类型 = 0
	每日已切类型 = false
	每日滑动次数 = 0
	每日已点每日 = false
	每日第几个战力 = 0
	每日已点蓝色按钮 = false
	每日已接完 = false
	挂机重置()
}

// 每日任务跑 一轮干一格
func 每日任务跑() {
	// ① 打开任务面板：主菜单 → 滑动 → 点【任务】（照 JSON 三步，每轮一步）
	if !每日面板已开 {
		if !每日菜单已点 {
			if 查找点击延时("主菜单") {
				每日菜单已点 = true
			}
			return
		}
		if !每日已滑动 {
			core.LogWithTimef("[每日任务] 滑动 1027,579 → 990,127")
			core.RandomSwipe(1027, 579, 990, 127, 1000, 1000)
			每日已滑动 = true
			return
		}
		if 查找点击延时("任务") {
			每日面板已开 = true
		}
		return
	}

	// ② 接取全做完 → 打怪（照 JSON：每日任务 → StartUp → 挂机中）
	if 每日已接完 {
		挂机跑()
		return
	}

	// ③ 两个 tab 循环接取（照 plugin：切 tab → 找符合战力/无需战力 → 点蓝色按钮 → 找不到就滑）
	if 每日第几类型 < len(每日类型列表) {
		类型 := 每日类型列表[每日第几类型]
		// 先切 tab
		if !每日已切类型 {
			if 查找点击延时(类型) {
				每日已切类型 = true
				每日滑动次数 = 0
			}
			return
		}
		// 任务接取已满 → 换下一个 tab
		if _, _, ok := 识别("任务接取已满"); ok {
			core.LogWithTimef("[每日任务]【%s】任务接取已满 → 下一个类型", 类型)
			每日下一个类型()
			return
		}
		// 找到【符合战力】（或开了开关时的【无需战力】）→ 点它 → 点【蓝色按钮】
		if 查找点击延时("符合战力") || (是否接取无需战力任务 && 查找点击延时("无需战力")) {
			查找点击延时("蓝色按钮", 834, 626, 912, 705)
			return
		}
		// 都找不到 → 滑动列表（从下往上），滑满 每日最多滑动 次换下一个 tab
		if 每日滑动次数 >= 每日最多滑动 {
			core.LogWithTimef("[每日任务]【%s】滑了 %d 次仍没找到 → 下一个类型", 类型, 每日滑动次数)
			每日下一个类型()
			return
		}
		每日滑动次数++
		cx := (447 + 518) / 2
		core.LogWithTimef("[每日任务]【%s】第%d次未找到任务 → 滑动 %d,528 → %d,296",
			类型, 每日滑动次数, cx, cx)
		core.RandomSwipe(cx, 528, cx, 296, 1500, 2000)
		return
	}

	// ④ 点【每日】→ 【绿色战力】多个逐个点（照 plugin：点了战力再检测【每日打怪任务】）
	if !每日已点每日 {
		if 查找点击延时("每日") {
			每日已点每日 = true
		}
		return
	}
	战力点 := 识别多个("绿色战力", 552, 171, 834, 622)
	if 每日第几个战力 >= len(战力点) {
		// 战力都点完 → 点【退出】收尾（照 plugin 结尾的 退出 步骤）
		if 查找点击延时("退出") {
			if !每日已点蓝色按钮 {
				core.LogWithTimef("[每日任务] 一次都没点【蓝色按钮】→ 直接完成整个任务")
				切下一个任务()
				return
			}
			core.LogWithTimef("[每日任务] 点过【蓝色按钮】→ 进打怪阶段")
			每日已接完 = true
		}
		return
	}
	pt := 战力点[每日第几个战力]
	core.LogWithTimef("[每日任务] 第%d/%d 个战力 → 点击 (%d,%d)",
		每日第几个战力+1, len(战力点), pt.X, pt.Y)
	core.RandomClickInAreaWithDelay(pt.X, pt.Y, pt.X+5, pt.Y+5)
	// 点完检测【每日打怪任务】：没检测到 → 继续下一个
	if _, _, ok := 识别("每日打怪任务", 857, 142, 1231, 587); !ok {
		core.LogWithTimef("[每日任务] 第%d个战力 未检测到【每日打怪任务】→ 继续下一个", 每日第几个战力+1)
		每日第几个战力++
		return
	}
	core.LogWithTimef("[每日任务] 第%d个战力 检测到【每日打怪任务】", 每日第几个战力+1)
	// 检测到 → 点【自动进行】→ 点【蓝色按钮】（照 plugin 同一轮做完）
	查找点击延时("自动进行", 773, 657, 827, 681)
	if 查找点击延时("蓝色按钮", 955, 631, 1102, 702) {
		每日已点蓝色按钮 = true
	}
	每日第几个战力++
}

// 每日下一个类型 切到下一个 tab（清掉当前 tab 的进度）
func 每日下一个类型() {
	每日第几类型++
	每日已切类型 = false
	每日滑动次数 = 0
}
