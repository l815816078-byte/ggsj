package zt

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 加护 —— 子任务（照 plugin/加护.go + assets/tasks/加护.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	主菜单 → 加护 →
//	1. 绿色按钮 / 确认 / 点击关闭 / 自动装备（按顺序，命中的就点）
//	2. 直接点击区域 184,78,280,105
//	3. 召唤加护 / 跳过 / 绿色按钮 / 棕色按钮（按顺序，命中的就点）
//	4. 检测到【召唤用光】→ 不再点它（继续走下面的按钮 + 退出）
//	→ 退出
// ══════════════════════════════════════════════════════════════════════════

// ── 加护自己的状态 ────────────────────────────────────────────────────────
var (
	加护召唤用光 = false // 命中过【召唤用光】了没（次数用光 = 没啥可召唤了）
	加护已完成  = false // 完成：召唤用光 + 退出点了
)

// 加护重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 加护重置() {
	加护召唤用光 = false
	加护已完成 = false
}

// 加护完成 = 召唤次数用光（命中过【召唤用光】）且退出点了
func 加护完成() bool { return 加护已完成 }

// 加护跑 子任务流程（每轮由 跑子任务() 调度，每轮只点该点的）
func 加护跑() {
	// 入口：主菜单 → 加护（命中就点，不命中就过 → 下一轮再来）
	查找点击延时("主菜单")
	查找点击延时("加护")

	// 入口还没点开 → 本轮不干活
	if _, _, ok := 识别("加护"); !ok {
		return
	}

	// ④ 检测到【召唤用光】→ 次数用光：不再点召唤类按钮，直接去退出
	if !加护召唤用光 {
		if _, _, ok := 识别("召唤用光"); ok {
			core.LogWithTimef("[加护] 命中【召唤用光】→ 次数用光，走退出")
			加护召唤用光 = true
		}
	}
	if 加护召唤用光 {
		// 召唤用光了 → 跳过 ① ② ③，直接点【退出】收尾
		core.LogWithTimef("[加护] 召唤次数已用光 → 点【退出】")
		查找点击延时("退出")
		加护已完成 = true
		return
	}

	// ① 弹窗按钮（按顺序，命中的就点）
	查找点击延时("绿色按钮")
	查找点击延时("确认")
	查找点击延时("点击关闭")
	查找点击延时("自动装备")

	// ② 直接点击区域 184,78,280,105
	core.LogWithTimef("[加护] 直接点击区域 184,78,280,105")
	core.RandomClickInAreaWithDelay(184, 78, 280, 105)

	// ③ 召唤阶段按钮（按顺序，命中的就点）
	查找点击延时("召唤加护")
	查找点击延时("跳过")
	查找点击延时("绿色按钮")
	查找点击延时("棕色按钮")
}
