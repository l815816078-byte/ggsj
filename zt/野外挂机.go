// ══════════════════════════════════════════════════════════════════════════
// 野外挂机 —— 野外挂机任务（= 老脚本 `_Whereas`：一个任务内部多步）
//
// 流程（两阶段）：
//	阶段一 去地方：选地点（按战力）→ 去地图(主城, 地点, 商店类型) → 到了置 已到达
//	阶段二 挂着打：调通用模块 挂机跑()（见 挂机.go）
//
// 野外挂机是"多步任务"，内部阶段用 已到达 挡（= 老脚本 `_Whereas` 里
// `if 任务参数.代练_砖 == false` 那种标志位），**不拆成轮转环上的两个任务**。
//
// 加新任务时照这个文件抄一份，然后在 主流程.go 的 跑当前任务() 加一条 case、
// 在 切下一个任务() 加一环。
// ══════════════════════════════════════════════════════════════════════════

// 野外挂机去哪（改这三个就行）
const (
	野外挂机主城 = "英勇的清山"
	野外挂机地点 = "" // 空 = 按战力从 英勇的清山 的地点列表里选
	野外挂机类型 = "" // 不去商店类型
)

// 地点 一个地点：名称 + 战力门槛
type 地点 struct {
	名称   string
	战力门槛 int
}

// 英勇的清山下的地点 + 战力门槛（照 自动买药.go 的地图配置表）
var 野外地点列表 = []地点{
	{"倒塌的据点", 50000},
	{"废弃通道", 50000},
	{"基土小路", 38000},
	{"不详的湖", 38000},
	{"高处岔路", 25000},
}

// ── 野外挂机自己的状态 ────────────────────────────────────────────────────
var (
	已到达 = false // 到地方了没（点完地点 = 到了，之后走挂机阶段）
	已选地点 = ""   // 本轮选中的地点名（按战力选出来的）
)

// 野外挂机重置 由 主流程.go 的 切下一个任务() / 重跑当前任务() 调（切走/重跑时清）
func 野外挂机重置() {
	已到达 = false
	已选地点 = ""
	去地图重置() // 要重新去地方：标志位不清 = 原地接着挂（等于没重跑）
	挂机重置()   // 挂机模块的状态也一起清
}

// 野外挂机跑 = 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，**不 return**。
func 野外挂机跑() {
	// ── 阶段一：去地方 ─────────────────────────────────────────────────
	if !已到达 {
		// 选地点（按战力）：固定地点直接用，否则从列表里选
		地点 := 野外挂机地点
		if 地点 == "" {
			地点 = 选地点(野外地点列表)
			已选地点 = 地点
		}
		if 地点 == "" {
			return // 选不出来（读不到战力、列表也空）→ 本轮不干活
		}

		core.LogWithTimef("[野外挂机] 目标：主城【%s】→ 地点【%s】", 野外挂机主城, 地点)
		去地图(野外挂机主城, 地点, 野外挂机类型)

		// 到地方了（地点点开了）→ 进阶段二
		if 已点地点 {
			已到达 = true
			挂机重置() // 到达 = 计时的新起点：赶路/传送的时间不算"没动静"
			core.LogWithTimef("[野外挂机] 已到达【%s】→ 开始挂机", 地点)
		}
		return
	}

	// ── 阶段二：挂着打（调通用模块）──────────────────────────────────
	挂机跑()
}

// 选地点 按当前战力选最符合的地点：
//   - 门槛 ≤ 战力里取门槛最高的；同门槛有多个 → 随机一个
//   - 检测不到战力 / 一个门槛都不满足 → 取门槛最低的（同最低多个 → 随机一个）
func 选地点(列表 []地点) string {
	if len(列表) == 0 {
		return ""
	}
	战力 := 读战力()
	if 战力 <= 0 {
		core.LogWithTimef("[野外挂机] 读不到战力 → 取门槛最低的地点")
		return 最低门槛地点(列表)
	}
	core.LogWithTimef("[野外挂机] 当前战力=%d", 战力)

	最高 := -1
	for _, p := range 列表 {
		if p.战力门槛 <= 战力 && p.战力门槛 > 最高 {
			最高 = p.战力门槛
		}
	}
	if 最高 < 0 {
		core.LogWithTimef("[野外挂机] 战力 %d 不满足任何门槛 → 取门槛最低的地点", 战力)
		return 最低门槛地点(列表)
	}
	var 候选 []地点
	for _, p := range 列表 {
		if p.战力门槛 == 最高 {
			候选 = append(候选, p)
		}
	}
	return 候选[rand.Intn(len(候选))].名称
}

// 读战力 读【战斗力】（paddle 取文），从文字里抠出数字；读不到返回 0
func 读战力() int {
	文字, ok := 取文("战斗力")
	if !ok {
		return 0
	}
	core.LogWithTimef("[读战力] 战斗力原始文字=%q", 文字)
	// 取文可能带回车/单位/垃圾字符（如 "68.573" 里的点）：只留数字，其余全跳过
	n := 0
	有 := false
	for _, c := range 文字 {
		if c >= '0' && c <= '9' {
			n = n*10 + int(c-'0')
			有 = true
		}
	}
	if !有 {
		return 0
	}
	return n
}

// 最低门槛地点 门槛最低的那个（同最低有多个 → 随机一个）
func 最低门槛地点(列表 []地点) string {
	最低 := 列表[0].战力门槛
	for _, p := range 列表 {
		if p.战力门槛 < 最低 {
			最低 = p.战力门槛
		}
	}
	var 候选 []地点
	for _, p := range 列表 {
		if p.战力门槛 == 最低 {
			候选 = append(候选, p)
		}
	}
	return 候选[rand.Intn(len(候选))].名称
}
