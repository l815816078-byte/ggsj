package zt

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 气运显现 —— 子任务（照 plugin/气运显现.go + assets/tasks/气运显现.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	主菜单 → 气运显现 → 按 气运类型表 依次切换类型，每轮点一次当前类型的【气运】
//	（点击延时 600ms）→ 退出
//
// ★ 不搞 plugin 的"6 秒找不到就切下一个类型"内层循环：每轮点一下，
//   主循环每轮都会来 → 天然就是"一直点"；类型切换用 气运第几个 标志位推进，
//   一个类型点够了（连着几轮点不到）就切下一个（照 买药.go 滑动次数 的标志位做法）。
// ══════════════════════════════════════════════════════════════════════════

// 气运类型表 依次切换的类型（生命之气是默认第一个，不需要点击）
var 气运类型表 = []struct {
	名称 string
	区域 [4]int // 点击区域 x1,y1,x2,y2（空 = 不需要点击，默认选中）
}{
	{名称: "生命之气", 区域: [4]int{}}, // 默认第一个，不需要点击
	{名称: "黎明气息", 区域: [4]int{80, 275, 120, 315}},
	{名称: "梦幻气息", 区域: [4]int{80, 415, 121, 456}},
	{名称: "红炎气息", 区域: [4]int{82, 559, 117, 594}},
}

// ── 气运显现自己的状态 ──────────────────────────────────────────────────────
var (
	气运第几个 = 0      // 当前切到第几个类型（从 0 开始；点不到就往后切）
	气运空几轮 = 0      // 当前类型连续几轮点不到【气运】（够了就切下一个类型）
)

const 气运空几轮上限 = 5 // 当前类型连续这么多轮点不到 → 切下一个类型（≈ plugin 的 6 秒）

// 气运显现重置 由 跑子任务() 在【冷却到点、本趟重新开始】时调（= 各任务自己的重置）
func 气运显现重置() {
	气运第几个 = 0
	气运空几轮 = 0
}

// 气运显现跑 子任务流程（每轮由 跑子任务() 调度，每轮只点该点的）
func 气运显现跑() {
	// 入口：主菜单 → 气运显现（命中就点，不命中就过 → 下一轮再来）
	查找点击延时("主菜单")
	查找点击延时("气运显现")

	// 入口还没点开（两个都没命中）→ 本轮不干活
	if _, _, ok := 识别("气运显现"); !ok {
		return
	}

	// 类型表走完了 → 收工退出
	if 气运第几个 >= len(气运类型表) {
		core.LogWithTimef("[气运显现] 类型表已走完 → 点【退出】")
		查找点击延时("退出")
		if _, _, ok := 识别("退出"); !ok {
			气运显现重置() // 退出也没了 → 面板已关，重置等下一趟
		}
		return
	}

	类型 := 气运类型表[气运第几个]
	// 非默认类型 → 点击切换
	if 类型.区域 != [4]int{} {
		core.LogWithTimef("[气运显现] 点击气运类型【%s】(%d,%d,%d,%d)",
			类型.名称, 类型.区域[0], 类型.区域[1], 类型.区域[2], 类型.区域[3])
		core.RandomClickInAreaWithDelay(类型.区域[0], 类型.区域[1], 类型.区域[2], 类型.区域[3])
		core.RandomSleep(500, 1000)
	} else {
		core.LogWithTimef("[气运显现] 气运类型【%s】（默认第一个，无需点击）", 类型.名称)
	}

	// 每轮点一次当前类型的【气运】（点击延时 600ms）
	if x, y, ok := 识别("气运"); ok {
		core.LogWithTimef("[气运显现] 点击【气运】(%d,%d)", x, y)
		core.RandomClickInAreaWithDelay(x, y, x+3, y+3, 600)
		气运空几轮 = 0
		return
	}

	// 点不到 → 计空轮；空够了切下一个类型
	气运空几轮++
	if 气运空几轮 >= 气运空几轮上限 {
		core.LogWithTimef("[气运显现] 【%s】连续 %d 轮没找到【气运】→ 切下一个类型", 类型.名称, 气运空几轮)
		气运第几个++
		气运空几轮 = 0
	}
}
