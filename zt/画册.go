// ══════════════════════════════════════════════════════════════════════════
// 画册 —— 子任务（照 plugin/画册.go + assets/tasks/画册.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	主菜单 → 画册 → 外层红点多个(83,121,122,578) 逐个点
//	→ 每点开一个：内层红点多个(139,170,1168,633) 逐个点（点完点【确认】/【绿色按钮】→ 点【返回】）
//	→ 当前外层项没有内层红点了 → 滑动一次（从下往上），滑满 画册滑动上限 次 → 下一个外层项
//	→ 退出
//
// ★ 不搞 plugin 的"for 最多滑动5次"内层循环：滑动用 画册滑动次数 标志位推进，
//   每轮滑一次点一轮，剩下的交给主循环下一轮（照 买药.go 滑动次数 的标志位做法）。
// ══════════════════════════════════════════════════════════════════════════

// ── 画册自己的状态 ────────────────────────────────────────────────────────
var (
	画册第几个   = 0     // 外层红点点到第几个
	画册滑动次数 = 0     // 当前外层项已滑动次数（滑满 画册滑动上限 → 下一个外层项）
	画册已完成   = false // 外层全处理完 / 本来就没红点（= 完成）
)

const 画册滑动上限 = 5 // 一个外层项最多滑动这么多次（照 plugin 的 5 次）

// 画册重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 画册重置() {
	画册第几个 = 0
	画册滑动次数 = 0
	画册已完成 = false
}

// 画册完成 = 外层红点全处理完 / 本来就没红点
func 画册完成() bool { return 画册已完成 }

// 画册跑 子任务流程（每轮由 跑子任务() 调度，每轮只点该点的）
func 画册跑() {
	// 入口：主菜单 → 画册（命中就点，不命中就过 → 下一轮再来）
	查找点击延时("主菜单")
	查找点击延时("画册")

	// 入口还没点开 → 本轮不干活
	if _, _, ok := 识别("画册"); !ok {
		return
	}

	// 外层红点多个（一次取全部，点的是当前指到的那个）
	外层点 := 识别多个("红点", 83, 121, 122, 578)
	if 画册第几个 >= len(外层点) {
		// 没外层红点（点完了 / 本来就没有）→ 点【退出】→ 完成
		// ★ 有没有红点都正常退出（没有 = 没活干，也算做完）
		core.LogWithTimef("[画册] 外层红点已全部处理（共 %d 个）→ 点【退出】", len(外层点))
		查找点击延时("退出")
		画册已完成 = true
		return
	}

	点 := 外层点[画册第几个]
	core.LogWithTimef("[画册] 外层红点(%d,%d) → 点击", 点.X, 点.Y)
	core.RandomClickInAreaWithDelay(点.X, 点.Y, 点.X+5, 点.Y+5)

	// 内层红点多个(139,170,1168,633)：逐个点，每个点完点【确认】/【绿色按钮】→ 点【返回】
	内层点 := 识别多个("红点", 139, 170, 1168, 633)
	if len(内层点) == 0 {
		// 没有内层红点 → 滑动一次（从下往上）；滑满 → 下一个外层项
		if 画册滑动次数 >= 画册滑动上限 {
			core.LogWithTimef("[画册] 滑动 %d 次已满 → 下一个外层项", 画册滑动上限)
			画册滑动次数 = 0
			画册第几个++
			return
		}
		画册滑动次数++
		m := 滑动表["画册列表"]
		cx := (604 + 664) / 2
		core.LogWithTimef("[画册] 从下往上滑动 (%d,%d)→(%d,%d) 第%d次", cx, m[1], cx, m[3], 画册滑动次数)
		core.RandomSwipe(cx, m[1], cx, m[3], m[4])
		return
	}

	// 有内层红点 → 本项重新计滑动（滑到了新内容）
	画册滑动次数 = 0
	for _, 内点 := range 内层点 {
		if 已停止() {
			return
		}
		core.LogWithTimef("[画册] 内层红点(%d,%d) → 点击", 内点.X, 内点.Y)
		core.RandomClickInAreaWithDelay(内点.X, 内点.Y, 内点.X+5, 内点.Y+5)
		// 点开后：确认 / 绿色按钮（限定区域）
		扫弹窗([]string{"确认", "绿色按钮"})
		// 点【返回】（照 plugin 的 CheckLoopClick 6 秒）
		查找点击延时("返回")
	}
}
