// 落花战场跑 一轮干一格
func 落花战场跑() {
	// ① 选点位：按战力选最高的（照 plugin：不满足任何门槛 → 不干）
	if 落花目标点位 == nil {
		pt, ok := 选落花点位()
		if !ok {
			core.LogWithTimef("[落花战场] 战力不满足任何点位门槛 → 本轮不干")
			return
		}
		落花目标点位 = &pt
		core.LogWithTimef("[落花战场] 目标点位【%s】(门槛 %d)", pt.名称, pt.战力门槛)
		return
	}

	// ② 入口：主菜单 → 滑动 → 点【落花战场】（照 plugin 的三步）
	if !落花已进场 {
		if !落花菜单已点 {
			if 查找点击延时("主菜单") {
				落花菜单已点 = true
			}
			return
		}
		if !落花已滑动 {
			core.LogWithTimef("[落花战场] 滑动 1027,579 → 990,127")
			core.RandomSwipe(1027, 579, 990, 127, 1000, 1000)
			落花已滑动 = true
			return
		}
		if 查找点击延时("落花战场") {
			落花已进场 = true
		}
		return
	}

	// ③ 落花商店（照 plugin：进商店 → 逐个买 → 购买 → 回退）
	if !落花商店已做完 {
		落花商店跑()
		return
	}

	// ④ 入场：黄色按钮 → 随机频道 → 花钱入场（照 plugin 的三步）
	if !落花已入场 {
		if !落花已点黄色 {
			if 查找点击延时("黄色按钮") {
				落花已点黄色 = true
			}
			return
		}
		if !落花已点频道 {
			频道, ok := 随机开启频道()
			if !ok {
				core.LogWithTimef("[落花战场] 所有频道都未开启 → 本轮不干")
				return
			}
			core.LogWithTimef("[落花战场] 选择频道【%s】→ 点击 (%d,%d)", 频道.名称, 频道.X, 频道.Y)
			core.RandomClickInAreaWithDelay(频道.X, 频道.Y, 频道.X+5, 频道.Y+5)
			落花已点频道 = true
			return
		}
		if 查找点击延时("花钱入场") {
			落花已入场 = true
		}
		return
	}

	// ⑤ 切换战场地图 → 取消选中（照 plugin 的 6、7 步）
	if !落花已选中地图 {
		if 查找点击延时("切换战场地图") {
			落花已选中地图 = true
		}
		return
	}
	if !落花已取消选中 {
		if 查找点击延时("取消选中") {
			落花已取消选中 = true
		}
		return
	}

	// ⑥ 检测【战场地图】→ 按点位区域逐个点（检测到【寻路中】就算点对了）
	if !落花寻路中 {
		if _, _, ok := 识别("战场地图", 398, 212, 423, 234); !ok {
			core.LogWithTimef("[落花战场] 未检测到【战场地图】→ 本轮不点")
			return
		}
		if 落花第几个区域 >= len(落花目标点位.区域列表) {
			core.LogWithTimef("[落花战场] 区域都点过了还没寻路 → 从头再点一遍")
			落花第几个区域 = 0
			return
		}
		区 := 落花目标点位.区域列表[落花第几个区域]
		cx := (区[0] + 区[2]) / 2
		cy := (区[1] + 区[3]) / 2
		core.LogWithTimef("[落花战场] 点位【%s】点区域 %d,%d,%d,%d → 中心(%d,%d)",
			落花目标点位.名称, 区[0], 区[1], 区[2], 区[3], cx, cy)
		core.RandomClickInAreaWithDelay(cx, cy, cx, cy)
		落花第几个区域++
		if _, _, ok := 识别("寻路中"); ok {
			core.LogWithTimef("[落花战场] 检测到【寻路中】→ 点位点对")
			落花寻路中 = true
		}
		return
	}

	// ⑦ 检测【怪物】→ 到了战场 → 打（照 JSON：落花战场 → StartUp → 自动攻击 → 挂机中）
	if _, _, ok := 识别("怪物"); !ok {
		core.LogWithTimef("[落花战场] 未检测到【怪物】→ 继续等")
		return
	}
	挂机跑()
}

// 落花商店跑 落花商店段（每轮一格）：
//
//	点【棕色按钮】进商店 → 逐个物品（找+点 → 点【加1】补数量 → 读【购买数量】对上点【确认】）
//	→ 点【购买】→ 点【回退】
func 落花商店跑() {
	// ① 点【棕色按钮】进商店
	if !落花商店已开 {
		if 查找点击延时("棕色按钮", 12, 637, 98, 703) {
			落花商店已开 = true
		} else {
			core.LogWithTimef("[落花商店] 未识别到【棕色按钮】(区域 12,637,98,703) → 商店跳过")
			落花商店已开 = true
			落花商店第几个 = len(落花商店物品表) // 直接算买完（照 plugin：没点开就什么都不买）
		}
		return
	}

	// ② 逐个物品
	if 落花商店第几个 < len(落花商店物品表) {
		物品 := 落花商店物品表[落花商店第几个]
		// 数量 0 → 不买（照 plugin：连物品名都不识别）
		if 物品.数量 <= 0 {
			core.LogWithTimef("[落花商店]【%s】配置数量为 0 → 不买，跳过", 物品.名称)
			落花商店下一个物品()
			return
		}
		// 找并点该物品（找不到就从下往上滑，最多 3 次）
		if !落花商店已点物品 {
			if 查找点击延时(物品.名称) {
				core.LogWithTimef("[落花商店] 找到并点击【%s】", 物品.名称)
				落花商店已点物品 = true
				落花商店加1次数 = 0
				return
			}
			if 落花商店找过几次 >= 3 {
				core.LogWithTimef("[落花商店] 滑了 3 次仍未找到【%s】→ 下一个物品", 物品.名称)
				落花商店下一个物品()
				return
			}
			落花商店找过几次++
			core.LogWithTimef("[落花商店] 第%d次未找到【%s】→ 从下往上滑动 177,521 → 177,233",
				落花商店找过几次, 物品.名称)
			core.RandomSwipe(177, 521, 177, 233, 500, 2000)
			return
		}
		// 数量默认 1，配置 N → 再点 N-1 次【加1】（每轮一次）
		if 落花商店加1次数 < 物品.数量-1 {
			if !查找点击延时("加1") {
				core.LogWithTimef("[落花商店]【%s】第%d次未识别到【加1】", 物品.名称, 落花商店加1次数+1)
			}
			落花商店加1次数++
			return
		}
		// 读【购买数量】对不对 → 对上点【确认】，对不上点关闭
		文字, 读到 := 找色文字("购买数量")
		对上 := 读到 && 数字(文字) == 物品.数量
		core.LogWithTimef("[落花商店]【%s】购买数量读到=%q 配置 %d → 对上=%t", 物品.名称, 文字, 物品.数量, 对上)
		if 对上 {
			查找点击延时("确认")
		} else {
			core.LogWithTimef("[落花商店]【%s】数量对不上 → 点击关闭 760,201,807,249", 物品.名称)
			core.RandomClickInAreaWithDelay(760, 201, 807, 249)
		}
		落花商店下一个物品()
		return
	}

	// ③ 都买完 → 点【购买】→ 点【回退】（照 plugin 结尾）
	if !落花商店已点购买 {
		if 查找点击延时("购买") {
			落花商店已点购买 = true
		}
		return
	}
	if 查找点击延时("回退") {
		core.LogWithTimef("[落花商店] 全部处理完 → 点【回退】，落花商店段结束")
		落花商店已做完 = true
	}
}

// 落花商店下一个物品 换下一个物品（清掉当前物品的进度）
func 落花商店下一个物品() {
	落花商店第几个++
	落花商店找过几次 = 0
	落花商店已点物品 = false
	落花商店加1次数 = 0
}

// 选落花点位 按当前战力选符合条件的最高门槛点位（同门槛多个 → 随机）；不满足任何门槛 → ok=false
func 选落花点位() (落花点位, bool) {
	战力 := 读战力()
	if 战力 <= 0 {
		core.LogWithTimef("[落花战场] 未读到战力 → 不满足任何点位")
		return 落花点位{}, false
	}
	core.LogWithTimef("[落花战场] 当前战力=%d", 战力)

	最高 := -1
	for _, pt := range 落花战场挂机点位数组 {
		if pt.战力门槛 <= 战力 && pt.战力门槛 > 最高 {
			最高 = pt.战力门槛
		}
	}
	if 最高 < 0 {
		return 落花点位{}, false
	}
	var 候选 []落花点位
	for _, pt := range 落花战场挂机点位数组 {
		if pt.战力门槛 == 最高 {
			候选 = append(候选, pt)
		}
	}
	return 候选[rand.Intn(len(候选))], true
}

// 随机开启频道 在已开启的频道里随机选一个（照 plugin）
func 随机开启频道() (落花频道, bool) {
	var 已开启 []落花频道
	for _, c := range 落花频道列表 {
		if c.是否开启 {
			已开启 = append(已开启, c)
		}
	}
	if len(已开启) == 0 {
		return 落花频道列表[0], false
	}
	return 已开启[rand.Intn(len(已开启))], true
}
