// 落花战场（照 plugin/落花战场.go + assets/tasks/落花战场.json 搬）
//
// 老框架：刷新信息(插件) → 落花战场(插件) → StartUp → 自动攻击 → 挂机中
// 插件内部：选点位 → 主菜单 → 滑动 → 落花战场 → 落花商店 → 黄色按钮 → 频道
//	→ 花钱入场 → 切换战场地图 → 取消选中 → 按点位区域点(寻路中) → 检测怪物
//
// zt 写法：每轮干一格，全程标志位推进（点完一步就 return，下一轮接着走）。
// ══════════════════════════════════════════════════════════════════════════

// 落花点位 / 落花频道 / 落花商店物品 都配在 点库.go 的「业务配置」段
// （落花点位表、落花频道表、落花商店物品表 + 各自类型）

// ── 落花战场自己的状态 ────────────────────────────────────────────────────
var (
	落花目标点位 = (*落花点位)(nil) // 本趟选中的点位（按战力选，选一次就固化）

	落花菜单已点  = false // 点过【主菜单】
	落花已滑动   = false // 入口滑动做过了没
	落花已进场   = false // 点过【落花战场】进去了没
	落花商店已做完 = false // 落花商店整段做完了没

	落花已点黄色  = false // 点过【黄色按钮】
	落花已点频道  = false // 点过随机频道
	落花已入场   = false // 点过【花钱入场】
	落花已选中地图 = false // 点过【切换战场地图】
	落花已取消选中 = false // 点过【取消选中】

	落花第几个区域 = 0     // 点位区域列到点第几个
	落花寻路中   = false // 检测到【寻路中】= 点对了
	落花怪物出现  = false // 检测到【怪物】= 已到战场
)

// ── 落花商店的子状态 ──────────────────────────────────────────────────────
var (
	落花商店已开   = false // 点过【棕色按钮】进商店了没
	落花商店第几个  = 0     // 买到第几个物品
	落花商店找过几次 = 0     // 当前物品找了几次（3 次找不到 → 换下一个）
	落花商店已点物品 = false // 当前物品找到并点过了没
	落花商店加1次数 = 0     // 当前物品点了几次【加1】
	落花商店已点购买 = false // 点过【购买】了没
)

// 落花战场重置 由 切下一个任务() / 重跑当前任务() 调
func 落花战场重置() {
	落花目标点位 = nil
	落花菜单已点 = false
	落花已滑动 = false
	落花已进场 = false
	落花商店已做完 = false
	落花已点黄色 = false
	落花已点频道 = false
	落花已入场 = false
	落花已选中地图 = false
	落花已取消选中 = false
	落花第几个区域 = 0
	落花寻路中 = false
	落花怪物出现 = false
	落花商店重置()
	挂机重置()
}

// 落花商店重置 商店这段的状态
func 落花商店重置() {
	落花商店已开 = false
	落花商店第几个 = 0
	落花商店找过几次 = 0
	落花商店已点物品 = false
	落花商店加1次数 = 0
	落花商店已点购买 = false
}

// 落花战场跑 一轮干一格
func 落花战场跑() {
	// ① 选点位：按战力选最高的（照 plugin：不满足任何门槛 → 不干）
	if 落花目标点位 == nil {
		当前状态 = "选点位"
		pt, ok := 选落花点位()
		if !ok {
			core.LogWithTimef("[落花战场] 战力不满足任何点位门槛 → 本轮不干")
			return
		}
		落花目标点位 = &pt
		core.LogWithTimef("[落花战场] 目标点位【%s】(门槛 %d)", pt.名称, pt.战力门槛)
		return
	}

	// ② 入口：主菜单 → 滑动 → 点【落花战场】（照 plugin 的三步）
	if !落花已进场 {
		当前状态 = "进落花战场"
		if !落花菜单已点 {
			if 查找点击延时("主菜单") {
				落花菜单已点 = true
			}
			return
		}
		if !落花已滑动 {
			core.LogWithTimef("[落花战场] 滑动 1027,579 → 990,127")
			m := 滑动表["开面板"]
			core.RandomSwipe(m[0], m[1], m[2], m[3], m[4], m[5])
			落花已滑动 = true
			return
		}
		if 查找点击延时("落花战场") {
			落花已进场 = true
		}
		return
	}

	// ③ 落花商店（照 plugin：进商店 → 逐个买 → 购买 → 回退）
	if !落花商店已做完 {
		当前状态 = "落花商店"
		落花商店跑()
		return
	}

	// ④ 入场：黄色按钮 → 随机频道 → 花钱入场（照 plugin 的三步）
	if !落花已入场 {
		当前状态 = "落花入场"
		if !落花已点黄色 {
			if 查找点击延时("黄色按钮") {
				落花已点黄色 = true
			}
			return
		}
		if !落花已点频道 {
			频道, ok := 随机开启频道()
			if !ok {
				core.LogWithTimef("[落花战场] 所有频道都未开启 → 本轮不干")
				return
			}
			core.LogWithTimef("[落花战场] 选择频道【%s】→ 点击 (%d,%d)", 频道.名称, 频道.X, 频道.Y)
			core.RandomClickInAreaWithDelay(频道.X, 频道.Y, 频道.X+5, 频道.Y+5)
			落花已点频道 = true
			return
		}
		if 查找点击延时("花钱入场") {
			落花已入场 = true
		}
		return
	}

	// ⑤ 切换战场地图 → 取消选中（照 plugin 的 6、7 步）
	//  ★ 【切换战场地图】是必经（照 plugin：30 秒内没找到 → 失败）；
	//    【取消选中】是"顺手点一下，没有就算了"（照 plugin 的 CheckLoopClick：没找到继续往下走）→ 点不到不卡住
	if !落花已选中地图 {
		当前状态 = "切战场地图"
		if 查找点击延时("切换战场地图") {
			落花已选中地图 = true
		}
		return
	}
	if !落花已取消选中 {
		落花已取消选中 = true // 只试一次，成不成都不卡（照 plugin）
		查找点击延时("取消选中")
	}

	// ⑥ 检测【战场地图】→ 按点位区域逐个点（检测到【寻路中】就算点对了）
	if !落花寻路中 {
		当前状态 = "寻路中"
		if _, _, ok := 识别("战场地图"); !ok {
			core.LogWithTimef("[落花战场] 未检测到【战场地图】→ 本轮不点")
			return
		}
		if 落花第几个区域 >= len(落花目标点位.区域列表) {
			core.LogWithTimef("[落花战场] 区域都点过了还没寻路 → 从头再点一遍")
			落花第几个区域 = 0
			return
		}
		区 := 落花目标点位.区域列表[落花第几个区域]
		cx := (区[0] + 区[2]) / 2
		cy := (区[1] + 区[3]) / 2
		core.LogWithTimef("[落花战场] 点位【%s】点区域 %d,%d,%d,%d → 中心(%d,%d)",
			落花目标点位.名称, 区[0], 区[1], 区[2], 区[3], cx, cy)
		core.RandomClickInAreaWithDelay(cx, cy, cx, cy)
		落花第几个区域++
		if _, _, ok := 识别("寻路中"); ok {
			core.LogWithTimef("[落花战场] 检测到【寻路中】→ 点位点对")
			落花寻路中 = true
		}
		return
	}

	// ⑦ 检测【怪物】→ 到了战场（怪刷出来了）→ 进挂机（照 plugin 的 CheckLoop("怪物", 60秒/2秒)）
	//  ★ 用 基础.go 的 持续找色（timeout 内循环找，命中返回 true）；超时 = 这趟白跑，切走
	if !落花怪物出现 {
		当前状态 = "等怪物"
		if 持续找色("怪物", 60*time.Second) {
			core.LogWithTimef("[落花战场] 检测到【怪物】→ 已到战场，进挂机")
			落花怪物出现 = true
		} else {
			core.LogWithTimef("[落花战场] 60 秒内没【怪物】→ 这趟白跑，切下一个任务")
			切下一个任务()
		}
		return
	}

	// ⑧ 已到战场 → 挂机（照 JSON：落花战场 → StartUp → 自动攻击 → 挂机中）
	挂机跑()
}

// 落花商店跑 落花商店段（每轮一格）：
//
//	点【棕色按钮】进商店 → 逐个物品（找+点 → 点【加1】补数量 → 读【购买数量】对上点【确认】）
//	→ 点【购买】→ 点【回退】
func 落花商店跑() {
	// ① 点【棕色按钮】进商店
	if !落花商店已开 {
		core.LogWithTimef("[落花商店] ① 进商店：开始找【棕色按钮】(区域 8,629,322,707)")
		if 查找点击延时("棕色按钮", 8, 629, 322, 707) {
			core.LogWithTimef("[落花商店] ① 【棕色按钮】命中 → 已进商店")
			落花商店已开 = true
		} else {
			core.LogWithTimef("[落花商店] ① 未识别到【棕色按钮】(区域 8,629,322,707) → 商店跳过")
			落花商店已开 = true
			落花商店第几个 = len(落花商店物品表) // 直接算买完（照 plugin：没点开就什么都不买）
		}
		return
	}

	// ② 逐个物品
	if 落花商店第几个 < len(落花商店物品表) {
		物品 := 落花商店物品表[落花商店第几个]
		core.LogWithTimef("[落花商店] ② 处理第 %d/%d 个物品【%s】配置数量=%d（已点开=%t 找过%d次 加1过%d次）",
			落花商店第几个+1, len(落花商店物品表), 物品.名称, 物品.数量,
			落花商店已点物品, 落花商店找过几次, 落花商店加1次数)
		// 数量 0 → 不买（照 plugin：连物品名都不识别）
		if 物品.数量 <= 0 {
			core.LogWithTimef("[落花商店] ②【%s】配置数量为 0 → 不买，跳过", 物品.名称)
			落花商店下一个物品()
			return
		}
		// 找并点该物品（找不到就从下往上滑，最多 3 次）
		if !落花商店已点物品 {
			x, y, ok := 识别(物品.名称)
			core.LogWithTimef("[落花商店] ② 识别【%s】→ 命中=%t 坐标=(%d,%d)", 物品.名称, ok, x, y)
			if ok {
				core.LogWithTimef("[落花商店] ② 找到【%s】(%d,%d) → 点击", 物品.名称, x, y)
				core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
				落花商店已点物品 = true
				落花商店加1次数 = 0
				return
			}
			if 落花商店找过几次 >= 3 {
				core.LogWithTimef("[落花商店] ② 滑了 3 次仍未找到【%s】→ 下一个物品", 物品.名称)
				落花商店下一个物品()
				return
			}
			落花商店找过几次++
			m := 滑动表["落花商店"]
			core.LogWithTimef("[落花商店] ② 第%d次未找到【%s】→ 从下往上滑动 (%d,%d)→(%d,%d)",
				落花商店找过几次, 物品.名称, m[0], m[1], m[2], m[3])
			core.RandomSwipe(m[0], m[1], m[2], m[3], m[4], m[5])
			return
		}
		core.LogWithTimef("[落花商店] ② 已点开【%s】→ 走数量/确认流程", 物品.名称)
		// 数量默认 1，配置 N → 再点 N-1 次【加1】（每轮一次）
		// ★ 点不到【加1】（= 钱不够/买不了）→ 直接点【回退】退出商店，商店段算完
		if 落花商店加1次数 < 物品.数量-1 {
			x, y, ok := 识别("加1")
			core.LogWithTimef("[落花商店] ② 需要加1：第%d/最多%d次，识别【加1】命中=%t 坐标=(%d,%d)",
				落花商店加1次数+1, 物品.数量-1, ok, x, y)
			if !ok {
				core.LogWithTimef("[落花商店] ②【%s】点不到【加1】(钱不够?) → 点【回退】退出商店", 物品.名称)
				落花商店回退退出()
				return
			}
			core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
			落花商店加1次数++
			return
		}
		// 读【购买数量】对不对 → 对上点【确认】，对不上点关闭
		// ★ 读不到【购买数量】→ 说明买不了 → 直接点【回退】退出商店
		文字, 读到 := 找色文字("购买数量")
		if !读到 {
			core.LogWithTimef("[落花商店] ②【%s】读不到【购买数量】→ 点【回退】退出商店", 物品.名称)
			落花商店回退退出()
			return
		}
		对上 := 数字(文字) == 物品.数量
		core.LogWithTimef("[落花商店] ②【%s】读【购买数量】读到=%q 解析=%d 配置=%d → 对上=%t",
			物品.名称, 文字, 数字(文字), 物品.数量, 对上)
		if 对上 {
			x, y, ok := 识别("确认")
			core.LogWithTimef("[落花商店] ② 数量对上 → 识别【确认】命中=%t 坐标=(%d,%d)", ok, x, y)
			if ok {
				core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
			}
		} else {
			core.LogWithTimef("[落花商店] ②【%s】数量对不上 → 点击关闭 760,201,807,249", 物品.名称)
			core.RandomClickInAreaWithDelay(760, 201, 807, 249)
		}
		落花商店下一个物品()
		return
	}

	// ③ 都买完 → 点【购买】→ 点【回退】（照 plugin 结尾）
	core.LogWithTimef("[落花商店] ③ 物品都处理完 → 开始收尾（购买→回退）")
	if !落花商店已点购买 {
		x, y, ok := 识别("购买")
		core.LogWithTimef("[落花商店] ③ 识别【购买】命中=%t 坐标=(%d,%d)", ok, x, y)
		if !ok {
			// 点不到【购买】（钱不够/按钮灰了）→ 直接点【回退】退出商店
			core.LogWithTimef("[落花商店] ③ 点不到【购买】→ 直接点【回退】退出商店")
			落花商店回退退出()
			return
		}
		core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
		落花商店已点购买 = true
		return
	}
	落花商店回退退出()
}

// 落花商店回退退出 买不了（钱不够：点不到【加1】/读不到【购买数量】）→ 点【回退】退出商店，商店段算完
func 落花商店回退退出() {
	x, y, ok := 识别("回退")
	core.LogWithTimef("[落花商店] 买不了 → 识别【回退】命中=%t 坐标=(%d,%d)", ok, x, y)
	if !ok {
		return // 没识别到【回退】→ 本轮到此，下一轮再来
	}
	core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
	core.LogWithTimef("[落花商店] 已点【回退】退出商店 → 商店段结束")
	落花商店已做完 = true
}

// 落花商店下一个物品 换下一个物品（清掉当前物品的进度）
func 落花商店下一个物品() {
	落花商店第几个++
	落花商店找过几次 = 0
	落花商店已点物品 = false
	落花商店加1次数 = 0
}

// 选落花点位 按当前战力选符合条件的最高门槛点位（同门槛多个 → 随机）；不满足任何门槛 → ok=false
func 选落花点位() (落花点位, bool) {
	战力 := 读战力()
	if 战力 <= 0 {
		core.LogWithTimef("[落花战场] 未读到战力 → 不满足任何点位")
		return 落花点位{}, false
	}
	core.LogWithTimef("[落花战场] 当前战力=%d", 战力)

	最高 := -1
	for _, pt := range 落花战场挂机点位数组 {
		if pt.战力门槛 <= 战力 && pt.战力门槛 > 最高 {
			最高 = pt.战力门槛
		}
	}
	if 最高 < 0 {
		return 落花点位{}, false
	}
	var 候选 []落花点位
	for _, pt := range 落花战场挂机点位数组 {
		if pt.战力门槛 == 最高 {
			候选 = append(候选, pt)
		}
	}
	return 候选[rand.Intn(len(候选))], true
}

// 随机开启频道 在已开启的频道里随机选一个（照 plugin）
func 随机开启频道() (落花频道, bool) {
	var 已开启 []落花频道
	for _, c := range 落花频道列表 {
		if c.是否开启 {
			已开启 = append(已开启, c)
		}
	}
	if len(已开启) == 0 {
		return 落花频道列表[0], false
	}
	return 已开启[rand.Intn(len(已开启))], true
}
