// ══════════════════════════════════════════════════════════════════════════
// 挂机 —— 通用模块（不是任务，不占主流程轮转环的一格）
//
// 野外挂机 / 门派战斗 等"到地方后挂着打"的任务，内部第二阶段都调 挂机跑()：
//	zt/野外挂机.go：去地方 → 挂机跑()
//	zt/门派战斗.go：去战场 → 挂机跑()   （以后）
//
// ★★ 它是【通用模块】，被好几个任务调 → 里面的判断要按【当前任务】分叉，
//    照 plugin/挂机中.go 的 ctx.TaskName 判断（那里已有两处分叉：
//    ① "每日任务" 不判断【自动攻击开启中】，改判【任务进行中】/【省电模式】+【/】；
//    ② 只有 "野外挂机" 才跑子任务，落花战场不跑）。
//    ★ 别把某一个任务的规则写成全模块通用 —— 加新挂机类任务时先确认要不要分叉。
//
// 职责（照老脚本 `_Whereas`：平铺，命中的就点，不 return）：
//	① 死了 → 点【复活】
//	② 没开自动攻击 → 点【自动攻击】按钮
//	③ 有动静（【怪物】命中 / 【省电_金币】文字变化）→ 刷新计时
//	④ 100 秒没动静 → 本段结束，重跑当前任务（没怪了，重新去地方再挂一轮；不换任务、不清累计）
//	⑤ 累计挂够 挂机时长秒 → 任务成功，切下一个任务（收工；累计清零）
//	⑥ 挂机中 → 跑子任务（只有【野外挂机】跑；照 plugin/挂机中.go：其他任务不跑）
// ══════════════════════════════════════════════════════════════════════════

// 挂机自己的状态
var (
	上次金币文本   = ""         // 上次读到的金币文字（有变化 = 有动静）
	上次打怪时间   = time.Now() // 上次有动静的时间
	挂机无动静秒数 = 0          // 连续多少秒没动静
	挂机开始时间   = time.Now() // 本段挂机的起点（到达地点 / 重跑 时由 挂机重置() 定）
	挂机本段秒数   = 0          // 本段（从 挂机开始时间 到现在）挂了多久
	挂机累计秒数   = 0          // ★ 已完成各段的总和：挂了一半被重跑/中断也【不清零】，照样算数
)

const 挂机超时秒 = 100 // 多少秒没动静 → 重跑当前任务（= 老脚本的 100 秒）

// 挂机重置 清挂机模块自己的状态（任务切换/重跑/到达地点时由任务调）
//
// ★★ 唯一【不清】的是 挂机累计秒数：挂机"挂满 挂机时长秒 才算成功"，
//
//	中间被打断（没怪了重跑、卡死切走、回城买药）都只是分段，已挂的时间照算，
//	只在 挂机跑() 第 ⑤ 步"挂够了收工"时才清零（任务成功 → 下次重新累计）。
func 挂机重置() {
	上次金币文本 = ""
	上次打怪时间 = time.Now()
	挂机无动静秒数 = 0
	挂机开始时间 = time.Now() // ★ 本段重新计时：到达地点才算"开始挂"，赶路时间不算
	挂机本段秒数 = 0
	// 挂机累计秒数 不动（见上面说明）
}

// 挂机跑 挂机中该干的事（每轮调一次）
func 挂机跑() {
	// 本段时长（④ 记账、⑤ 判断都用它，先算出来）
	挂机本段秒数 = int(time.Since(挂机开始时间).Seconds())

	// ① 死了 → 点【复活】（= 老脚本挂机中先检测复活）
	if 查找点击延时("复活") {
		core.LogWithTimef("[挂机] 检测到【复活】→ 已点击")
		return
	}

	// ② 没开自动攻击 → 点【自动攻击】按钮
	if _, _, 已开自动 := 识别("自动攻击开启中"); !已开自动 {
		core.LogWithTimef("[挂机] 未检测到【自动攻击开启中】")
		if 查找点击延时("自动攻击") {
			core.LogWithTimef("[挂机] 未开自动攻击 → 点击【自动攻击】")
			刷新打怪计时()
			return
		}
	}

	// ③ 有动静 =【怪物】命中 或【省电_金币】文字变化（每轮都打，看得到怪和金币）
	怪物命中 := false
	if _, _, ok := 识别("怪物"); ok {
		怪物命中 = true
	}
	金币文字, 金币读到 := 找色文字("省电_金币")
	金币有变化 := false
	if 金币读到 && 金币文字 != "" {
		if 金币文字 != 上次金币文本 {
			core.LogWithTimef("[挂机] 【省电_金币】有变化(%s → %s) → 有动静", 上次金币文本, 金币文字)
			上次金币文本 = 金币文字
			金币有变化 = true
		}
	}
	有动静 := 怪物命中 || 金币有变化
	core.LogWithTimef("[挂机] 【怪物】命中=%t 【省电_金币】读到=%q 变化=%t → 有动静=%t",
		怪物命中, 金币文字, 金币有变化, 有动静)
	if 有动静 {
		刷新打怪计时()
	}

	// ④ 100 秒没动静 → 本段结束，重跑当前任务（重新去地方再挂一轮，不是换任务）
	//    ★ 结束前先把本段挂的时间【记进累计】（挂机重置() 不清累计，所以得在这里记账）
	挂机无动静秒数 = int(time.Since(上次打怪时间).Seconds())
	if 挂机无动静秒数 > 挂机超时秒 {
		挂机累计秒数 += 挂机本段秒数
		core.LogWithTimef("[挂机] %d 秒没动静 → 本段结束，重跑当前任务（本段 %d 秒已计入，累计 %d/%d）",
			挂机无动静秒数, 挂机本段秒数, 挂机累计秒数, 挂机时长秒)
		重跑当前任务()
		return
	}

	// ⑤ 累计挂够 挂机时长秒 → 成功收工（切下一个任务回买药重新查缺药）
	//    ★ 跟 ④ 的区别：④ 是"没怪了"→ 重跑当前任务（不换任务、不清累计）；
	//      ⑤ 是"挂够了"→ 任务成功，换任务 + 累计清零（下次重新挂）
	if 挂机累计秒数+挂机本段秒数 >= 挂机时长秒 {
		core.LogWithTimef("[挂机] 累计挂够 %d 秒（目标 %d）→ 成功收工",
			挂机累计秒数+挂机本段秒数, 挂机时长秒)
		挂机累计秒数 = 0 // 任务成功 → 本次清零（下一轮重新累计）
		切下一个任务()
		return
	}
	core.LogWithTimef("[挂机] 挂机中（%d 秒内有动静，本段 %d 秒，累计 %d/%d）",
		挂机超时秒-挂机无动静秒数, 挂机本段秒数, 挂机累计秒数+挂机本段秒数, 挂机时长秒)

	// ⑥ 跑子任务（领取邮件/成就/福利…冷却到了就跑一遍）
	//    ★ 只有【野外挂机】跑：照 plugin/挂机中.go:80，其他挂机类任务（落花战场等）不跑子任务
	if 当前任务 == "野外挂机" {
		跑子任务()
	}
}

// 刷新打怪计时 有动静 → 刷新"上次打怪时间"
func 刷新打怪计时() {
	上次打怪时间 = time.Now()
	挂机无动静秒数 = 0
}

// ── 子任务（照 plugin/挂机中.go 的 跑子任务 搬过来）─────────────────────────

// 子任务 一个子任务：名称 + 冷却区间（照 plugin/挂机中.go:96-110 的表原样搬）
// + 跑函数 + 重置函数（每趟开始清它自己的标志位）
type 子任务 struct {
	名     string
	冷最小 int
	冷最大 int
	跑     func()
	重置   func()
}

// 子任务表 野外挂机期间顺带跑的子任务（顺序即执行顺序：固定，不随机）
// ★ 必须在 init() 里赋值，不能写成 `var 子任务表 = []子任务{...}`：
//
//	照 主流程.go 任务表 的教训（表里放函数指针，防 Go 初始化循环）
var 子任务表 []子任务

// 子任务下次可跑 子任务冷却表（进程内）：跑完一个子任务按随机区间记下次可跑时间，没到就跳过
var 子任务下次可跑 = map[string]time.Time{}

func init() {
	子任务表 = []子任务{
		{"领取邮件", 10000, 20000, 领取邮件跑, func() {}},
		{"领取成就", 10000, 20000, 领取成就跑, func() {}},
		{"福利领取", 10000, 20000, 福利领取跑, 福利领取重置},
		{"灵力修炼", 2500, 5000, 灵力修炼跑, func() {}},
		{"气运显现", 10000, 20000, 气运显现跑, 气运显现重置},
		{"背包物品", 5000, 10000, 背包物品跑, 背包物品重置},
		{"画册", 10000, 20000, 画册跑, 画册重置},
		{"加护", 10000, 20000, 加护跑, func() {}},
		{"成长", 10000, 20000, 成长跑, 成长重置},
	}
}

// 跑子任务 每轮随机顺序执行子任务（照 plugin/挂机中.go:93-133）：
//
//	· 冷却未到 → 跳过；跑完按随机区间记下次可跑时间，然后随机 3-20 秒再跑下一个
//	· 子任务耗时不算"没打怪"时间：跑完把耗时补回 上次打怪时间
//	· 有执行过 → 主动扫一次 任务轮转弹窗（= plugin 的 ClearPopups）
//
// 每个子任务 = 一个独立的 .go 文件（照 买药.go 那样一任务一文件），流程函数名 = 名字+跑。
// ★ 每个子任务跑前先 重置() 清它自己的标志位（= 老脚本 _TaskDate 的时机）：
//
//	不清的话上一趟的进度（第几个/翻页次数）会留着，下趟直接跳过前面的内容。
func 跑子任务() {
	// 子任务期间不算"没打怪"时间：跑前记时间，跑完把耗时补回上次打怪时间
	子任务开始 := time.Now()
	顺序 := make([]子任务, len(子任务表))
	copy(顺序, 子任务表)
	rand.Shuffle(len(顺序), func(i, j int) { 顺序[i], 顺序[j] = 顺序[j], 顺序[i] })
	for _, t := range 顺序 {
		// 脚本停止 → 立刻停，不再往后跑子任务
		if 已停止() {
			break
		}
		if time.Now().Before(子任务下次可跑[t.名]) {
			continue // 冷却未到 → 跳过
		}
		core.LogWithTimef("[子任务] ═══ 跑【%s】 ═══", t.名)
		if t.重置 != nil {
			t.重置() // 每趟开始清它自己的标志位
		}
		t.跑()
		子任务下次可跑[t.名] = time.Now().Add(time.Duration(t.冷最小+rand.Intn(t.冷最大-t.冷最小+1)) * time.Second)
		core.RandomSleep(3000, 20000)
	}
	// 跑完把耗时补回上次打怪时间（子任务期间不算"没打怪"）
	上次打怪时间 = 上次打怪时间.Add(time.Since(子任务开始))

}
