package zt

import (
	"app/core"
)

// 传送延时 点完传送按钮后等多久（毫秒）。
// 传送要加载约 6 秒，期间屏幕没变、【地图】图标还悬着，不等的话主循环会误点地图
// （表现为"传送完又回到点地图"）。直接透传给 RandomClickInAreaWithDelay。
const 传送延时 = 6000

// ══════════════════════════════════════════════════════════════════════════
// 去地图 —— 通用段：地图 → 地图列表 → 主城 → 折叠开 → 地点 → 商店类型 → 传送
//
// 买药 / 买装备 / 以后任何"要跑一趟地图"的任务都调它，只是传的名字不同：
//
//	买药：   去地图("塔巴罗城", "商店", "药品商店")
//	买装备： 去地图("王城",     "铁匠铺", "")          // 空串 = 不去商店类型
//
// ★★ 写法 = 老脚本 `_Whereas`：**一轮之内把所有 if 顺序过完，命中的就点，不 return**。
//
//	只有"场景守卫"（当前界面不该干这事）才 return。
//	别改成"命中就 return"—— 那样就得搞步骤指针来推进，老脚本没有那东西。
//
// ★★ 本函数【不重置标志位】：它每轮都会被主循环调用，
//
//	自己重置的话标志位就白挡了（主城/地点会被反复点）。
//	重置由调用方在"任务开始前"做一次（= 老脚本 _TaskDate 的时机，
//	在 主流程.go 的 重置状态() 里，它清 主城已展开/折叠开点过/已点地点/滑动次数）。
//
// ══════════════════════════════════════════════════════════════════════════
func 去地图(城, 地点, 商店类型 string) {
	// ── ⓪ 守卫：点库里没配这个名字 → 【配置缺失】，不是"没找到"
	//    不守卫的话会被当成"没找到"→ 滑动 → 滑满重来 → 又找不到 → 死循环刷屏
	//    （踩过：野外挂机 的 英勇的清山/5个地点 没搬进点库，日志一直 [识别] 点库里没有【XX】）
	for _, 名 := range []string{城, 地点, 商店类型} {
		if 名 == "" {
			continue
		}
		if _, ok := 特征表[名]; !ok {
			core.LogWithTimef("[去地图] ★★ 点库里没有【%s】→ 本轮不跑（往 点库.go 的 特征表 补这条预设）", 名)
			return
		}
	}

	列表区 := 区域表["列表区"]

	// ── ① 地图 → 地图列表（点完就消失，不用标志位）──────────────────────
	查找点击延时("地图")
	查找点击延时("地图列表")

	// ── ② 主城（点完不消失 → 标志位挡）────────────────────────────────
	if 主城已展开 {
		core.LogWithTimef("[去地图] 主城已展开（跳过）")
	} else {
		if x, y, ok := 识别(城, 列表区...); ok {
			// 命中主城：先探"折叠开"判断是否已展开
			区 := 偏移表["展开偏移"]
			x1, y1 := x+区[0], y+区[1]
			if _, _, 已展开 := 识别("折叠开", x1, y1, x1+40, y1+40); 已展开 {
				core.LogWithTimef("[去地图] 主城【%s】已展开 → 不点击", 城)
				主城已展开 = true
				折叠开点过 = true // 已展开说明不必再点折叠开
			} else {
				core.LogWithTimef("[去地图] 主城【%s】未展开 → 点开 (%d,%d)", 城, x, y)
				core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
				core.RandomSleep(1000, 1000)
				主城已展开 = true
				折叠开点过 = true
			}
		} else {
			core.LogWithTimef("[去地图] 没找到主城【%s】", 城)
		}
		// 主城没找到、看到【折叠开】→ 点它展开（点过就不再点）
		if !折叠开点过 {
			if 查找点击延时("折叠开", 列表区...) {
				折叠开点过 = true
			}
		}
	}

	// ── ③ 地点（点完不消失 → 标志位挡；找不到就滑动翻列表）──────────────
	// 滑动方向：主城还没展开 → 找主城（从上往下）；主城已展开 → 找地点（从下往上）
	if 已点地点 {
		core.LogWithTimef("[去地图] 地点已点（跳过）")
	} else {
		if 查找点击延时(地点, 列表区...) {
			已点地点 = true
			滑动次数 = 0
		} else {
			// 没找到 → 滑动翻列表（滑满 最多滑动 次就重来）
			// ★ 滑动前提：检测到【地图点位】（= 地图列表确实刷出来了）。
			//   没检测到就滑 = 空滑（界面还没到位/还在加载），白耗轮次还把列表滑歪。
			if _, _, ok := 识别("地图点位"); !ok {
				core.LogWithTimef("[去地图] 没检测到【地图点位】→ 本轮不滑动（等列表刷出来）")
			} else if 滑动次数 >= 最多滑动 {
				core.LogWithTimef("[去地图] 滑动 %d 次仍找不到地点【%s】→ 重来", 最多滑动, 地点)
				滑动次数 = 0 // 只清滑动计数，从"主城"重新走（主城已展开时直接找地点）
			} else {
				滑动次数++
				if 主城已展开 {
					m := 滑动表["找地点"]
					core.LogWithTimef("[滑动] 找地点 (%d,%d) → (%d,%d)", m[0], m[1], m[2], m[3])
					core.RandomSwipe(m[0], m[1], m[2], m[3], m[4], m[5])
				} else {
					m := 滑动表["找主城"]
					core.LogWithTimef("[滑动] 找主城 (%d,%d) → (%d,%d)", m[0], m[1], m[2], m[3])
					core.RandomSwipe(m[0], m[1], m[2], m[3], m[4], m[5])
				}
			}
		}
	}

	// ── ④ 商店类型（地点点开后才有；传空串 = 这一步不去）────────────────
	if 商店类型 != "" {
		查找点击延时(商店类型)
	}

	// ── ⑤ 传送三兄弟（点完等 传送延时 加载，别让主循环误点地图）──────────
	查找点击延时("绿色按钮")
	查找点击延时("立即传送", 传送延时)
	查找点击延时("前往", 传送延时)
}

// 去地图重置 清"跑一趟地图"这四个标志位（= 老脚本 _TaskDate 里属于这部分的那几行）
//
// ★ 谁调：任何用了 去地图() 的任务，在【自己重置/重跑】时调一次
//   （买药重置 / 野外挂机重置）。不调的话标志位还留着 → 重跑等于没重跑：
//   已点地点 还是 true，下一轮阶段一当场又置 已到达=true，原地接着挂。
func 去地图重置() {
	主城已展开 = false
	折叠开点过 = false
	已点地点 = false
	滑动次数 = 0
}
