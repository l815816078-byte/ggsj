// 门派战斗（照 plugin/门派战斗.go + assets/tasks/门派战斗.json 搬）
//
// 老框架：主菜单 → 滑动 → 点【门派战斗】→ 逐个点"已启用"的战场类型 + 各自处理方法 → 退出
//
// zt 写法：入口链用标志位一步一步推进（主菜单 → 滑动 → 门派战斗），
// 战场类型每轮点一个（照 plugin 的 for，但不一次点完）。
// ══════════════════════════════════════════════════════════════════════════

// 战场类型 一个战场类型：名称 + 点击区域 + 是否启用 + 处理方法（照 plugin 原样搬）
type 战场类型 struct {
	名称     string
	区域     [4]int // 点击区域 x1,y1,x2,y2
	启用     bool   // 是否启用（未启用的跳过）
	处理方法 func() // 该类型的处理方法
}

// 战场类型表 依次点击"已启用"的类型，调用各自配好的处理方法
// ★ 表里放函数指针 → 放 init() 里填（照 主流程.go 任务表 的初始化环教训）
var 战场类型表 []战场类型

func init() {
	战场类型表 = []战场类型{
		{名称: "罚神讨伐令", 区域: [4]int{58, 145, 138, 169}, 启用: true, 处理方法: 处理注册分身},
		{名称: "边疆防御", 区域: [4]int{60, 205, 142, 231}, 启用: true, 处理方法: 处理注册分身},
		{名称: "迷雾的花园", 区域: [4]int{52, 263, 142, 293}, 启用: true, 处理方法: 处理迷雾的花园},
		{名称: "神器争夺战", 区域: [4]int{70, 333, 124, 351}, 启用: true, 处理方法: 处理神器争夺战},
	}
}

// ── 门派战斗自己的状态 ────────────────────────────────────────────────────
var (
	门派菜单已点 = false // 点过【主菜单】
	门派已滑动  = false // 入口滑动做过了没
	门派界面已开 = false // 点过【门派战斗】进去了没
	门派第几个类型 = 0  // 战场类型表点到第几个
)

// 门派战斗重置 由 切下一个任务() / 重跑当前任务() 调
func 门派战斗重置() {
	门派菜单已点 = false
	门派已滑动 = false
	门派界面已开 = false
	门派第几个类型 = 0
}

// 门派战斗跑 一轮干一格
func 门派战斗跑() {
	// ① 入口：主菜单 → 滑动 → 点【门派战斗】（照 JSON 的三步）
	if !门派界面已开 {
		if !门派菜单已点 {
			if 查找点击延时("主菜单") {
				门派菜单已点 = true
			}
			return
		}
		if !门派已滑动 {
			core.LogWithTimef("[门派战斗] 滑动 1027,579 → 990,127")
			core.RandomSwipe(1027, 579, 990, 127, 2000, 2000)
			门派已滑动 = true
			return
		}
		if 查找点击延时("门派战斗") {
			门派界面已开 = true
		}
		return
	}

	// ② 逐个战场类型：点区域 → 调它配好的处理方法（每轮一个）
	if 门派第几个类型 < len(战场类型表) {
		t := 战场类型表[门派第几个类型]
		门派第几个类型++
		if !t.启用 {
			core.LogWithTimef("[门派战斗] 战场类型【%s】未启用 → 跳过", t.名称)
			return
		}
		core.LogWithTimef("[门派战斗] 点击战场类型【%s】(%d,%d,%d,%d)",
			t.名称, t.区域[0], t.区域[1], t.区域[2], t.区域[3])
		core.RandomClickInAreaWithDelay(t.区域[0], t.区域[1], t.区域[2], t.区域[3])
		t.处理方法()
		return
	}

	// ③ 都过完 → 点【退出】收工（照 JSON：门派战斗 → 退出 → #done）
	if 查找点击延时("退出") {
		core.LogWithTimef("[门派战斗] 全部处理完 → 点【退出】，切下一个任务")
		切下一个任务()
	}
}

