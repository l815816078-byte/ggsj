package mian

import (
	"time"

	"app/core"
)

// 传送延时 点完传送按钮后等多久（毫秒）。
// 传送要加载约 6 秒，期间屏幕没变、【地图】图标还悬着，不等的话主循环会误点地图
// （表现为"传送完又回到点地图"）。直接透传给 RandomClickInAreaWithDelay。
const 传送延时 = 5000

// 去地图的上限（照老脚本 plugin/自动买药.go 的 主城最多找 / 折叠开最多滑动 / 地点最多滑动）
const (
	主城最多找   = 2 // 主城循环最多找几次 ，注意这个2次是必须的哈，比如买药默认是展开的看不到买药的主城，这是为了兼容买药
	折叠开最多滑动 = 3 // 折叠开循环里最多滑动次数
	地点最多滑动  = 5 // 找地点时最多滑动次数
)

// ══════════════════════════════════════════════════════════════════════════
// 去地图 —— 通用段：地图 → 地图列表 → 主城 → 折叠开 → 地点 → 商店类型 → 传送
//
// 买药 / 买装备 / 以后任何"要跑一趟地图"的任务都调它，只是传的名字不同：
//
//	买药：   去地图("塔巴罗城", "商店", "药品商店")
//	买装备： 去地图("王城",     "铁匠铺", "")          // 空串 = 不去商店类型
//
// ★★ 写法 = 老脚本 plugin/自动买药.go 的 去地图()/去地点()/传送那套()：
//
//	【一次调用把整段跑完】，内部全用【局部循环变量】控制次数（主城最多 2 轮 /
//	折叠开最多滑 3 次 / 地点最多滑 6 次），成功 true、失败 false。
//
// ★★ 为什么不用标志位（mian 之前那版用 主城已展开/折叠开点过/已点地点/滑动次数 跨轮推进，
//
//	已删除）：标志位是【跨轮残留】的 —— 传送失败后 已点地点 仍为 true，下一轮就
//	"地点已点（跳过）"→ 在错误界面上乱点传送按钮 → 再也回不到正常流程。
//	局部变量跑完就没了，失败就是失败，下轮从零重来，不脏。
//
// ══════════════════════════════════════════════════════════════════════════
func 去地图(城, 地点, 商店类型 string) (success bool) {
	// ★ 失败统一在【出口】清场（只写这一处）：列表被滑到底后如果不退出地图，
	//   下轮再进来会在滑到底的旧列表上继续滑，永远找不到目标。
	//   defer 会在 return 时执行：success == false（找不到主城/找不到地点/传送失败）就退出地图。
	defer func() {
		if !success {
			查找点击延时("回退")
		}
	}()

	// ── ⓪ 守卫：点库里没配这个名字 → 【配置缺失】，不是"没找到"
	//    不守卫的话会被当成"没找到"→ 滑动 → 滑满重来 → 又找不到 → 死循环刷屏
	//    （踩过：野外挂机 的 英勇的清山/5个地点 没搬进点库，日志一直 [识别] 点库里没有【XX】）
	for _, 名 := range []string{城, 地点, 商店类型} {
		if 名 == "" {
			continue
		}
		if _, ok := 特征表[名]; !ok {
			core.LogWithTimef("[去地图] ★★ 点库里没有【%s】→ 失败（往 点库.go 的 特征表 补这条预设）", 名)
			return false
		}
	}

	列表区 := 区域表["列表区"]

	// ── ① 地图 → 地图列表 ────────────────────────────────────────────
	查找点击延时("地图")
	if !查找点击延时("地图列表") {
		return false
	}

	// ── ② 主城（最多 主城最多找 轮；没找到就进【折叠开】循环滑最多 3 次）──
	找到主城 := false
	for i := 1; i <= 主城最多找; i++ {
		if 已停止() {
			return false
		}
		if x, y, ok := 识别(城, 列表区...); ok {
			// 命中主城：先探"折叠开"判断是否已展开
			// 用命中点 + 展开偏移 推出"折叠开"检测区（40×40）
			区 := 偏移表["展开偏移"]
			x1, y1 := x+区[0], y+区[1]
			if 是否存在("折叠开", x1, y1, x1+40, y1+40) {
				core.LogWithTimef("[去地图] 第%d轮找到主城【%s】(%d,%d) → 已展开，不点击", i, 城, x, y)
			} else {
				core.LogWithTimef("[去地图] 第%d轮找到主城【%s】(%d,%d) → 点开", i, 城, x, y)
				core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
			}
			找到主城 = true
			break
		}
		core.LogWithTimef("[去地图] 第%d轮未找到主城【%s】→ 进折叠开循环", i, 城)

		// 折叠开循环：找到点击；没找到滑动（滑满 自然结束，不 break）
		for j := 1; j <= 折叠开最多滑动; j++ {
			if 已停止() {
				return false
			}
			if fx, fy, ok := 识别("折叠开", 列表区...); ok {
				core.LogWithTimef("[去地图] 折叠开第%d次找到【折叠开】(%d,%d) → 点击", j, fx, fy)
				core.RandomClickInAreaWithDelay(fx, fy, fx+3, fy+3) // 不能太大范围不然点不到
				core.RandomSleep(500, 1000)
				continue
			}
			m := 滑动表["找主城"]
			core.LogWithTimef("[去地图] 折叠开第%d次未找到【折叠开】→ 滑动 %d,%d → %d,%d", j, m[0], m[1], m[2], m[3])
			core.RandomSwipe(m[0], m[1], m[2], m[3], m[4], m[5])
		}
		// 折叠开循环结束 → 回主城循环继续找主城
	}
	if !找到主城 {
		core.LogWithTimef("[去地图] %d 次都没找到主城【%s】→ 失败", 主城最多找, 城)

		return false
	}

	// ── ③ 找地点（找到点它；没找到滑动，最多 地点最多滑动 次）────────────
	return 去地点(地点, 商店类型)
}

// 去地点 找地点（找不到就滑动），点开后可选点商店类型，最后走传送那套。
// 返回 true = 成功传送；false = 没找到地点 / 没传送到
func 去地点(地点, 商店类型 string) bool {
	列表区 := 区域表["列表区"]

	找到 := false
	for i := 1; i <= 地点最多滑动; i++ {
		if 已停止() {
			return false
		}
		if x, y, ok := 识别(地点, 列表区...); ok {
			core.LogWithTimef("[去地图] 第%d次找到地点【%s】(%d,%d) → 点击", i, 地点, x, y)
			core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
			找到 = true
			break
		}
		m := 滑动表["找地点"]
		core.LogWithTimef("[去地图] 第%d次未找到地点【%s】→ 滑动 %d,%d → %d,%d", i, 地点, m[0], m[1], m[2], m[3])
		core.RandomSwipe(m[0], m[1], m[2], m[3], m[4], m[5])
	}
	if !找到 {
		core.LogWithTimef("[去地图] 未找到地点【%s】→ 失败", 地点)
		return false
	}
	core.RandomSleep(500, 1000)

	// 点开地点后：若配了商店类型 → 检测点击
	if 商店类型 != "" {
		if 查找点击延时(商店类型) {
			core.LogWithTimef("[去地图] 已点击商店类型【%s】", 商店类型)
			core.RandomSleep(500, 1000)
		}
	}

	// 正常走绿色按钮那套（绿色按钮 = 原来的【咒术传送】）
	return 传送那套()
}

// 传送那套 绿色按钮（= 原来的【咒术传送】）→ 没找到则点【前往】→ 15 秒内循环等【立即传送】。
// 返回 true = 成功传送；false = 没传送到
func 传送那套() bool {
	// 绿色按钮 = 原来的【咒术传送】
	if 查找点击延时("绿色按钮") {
		return true
	}
	core.LogWithTimef("[去地图] 未找到【绿色按钮】→ 点【前往】")
	查找点击延时("前往", 传送延时)

	deadline := time.Now().Add(15 * time.Second)
	for time.Now().Before(deadline) {
		if 已停止() {
			return false
		}
		if 查找点击延时("立即传送", 传送延时) {
			// 绿色按钮 = 原来的【咒术传送】
			查找点击延时("绿色按钮")
			return true
		}
		core.RandomSleep(1000, 1500)
	}
	core.LogWithTimef("[去地图] 15 秒内未检测到【立即传送】→ 传送失败")
	return false
}
