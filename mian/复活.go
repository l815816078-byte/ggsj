package mian

import (
	"sync/atomic"
	"time"

	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 复活 —— 照 plugin/复活.go 搬
//
// 老逻辑（插件）：识别到【复活】弹窗 → 点复活 + 累计复活次数；
//	累计满 复活重置阈值 次后：若死前 5 分钟内在打 BOSS，就给"上次打 BOSS 的那个任务"
//	压 3000 秒冷却 + 让它立即收工（死了再死磕只会空转），并把复活计数清零重新累计。
//
// ★ 依赖躲避技能记的 躲避上次打BOSS任务名 / 躲避上次打BOSS时间（躲避技能.go 里在写）。
// ★ 本函数【不切任务】只负责"点复活 + 收尾（压冷却）"；要不要接着切走由调用方决定。
// ══════════════════════════════════════════════════════════════════════════

// 复活重置阈值 复活次数达到该值后做一次"死在 BOSS 手上"的收尾（压冷却 + 结束当前任务），计数清零重新累计。
const 复活重置阈值 = 1

// 复活次数 全局复活次数（跨任务累计；每满 复活重置阈值 次后清零，重新累计）
var 复活次数 atomic.Int32

// 复活处理 点了复活之后的整套处理（= 老脚本 plugin/复活.go 的 Exec）
//
//	① 点复活入口：先认【复活】（常规弹窗），认不到再认【棕色按钮】（落花战场副本里的复活）
//	   —— 两个都认不到 = 没死/被挡着 → 返回 false，什么都不做
//	② 滑省电模式（它浮在最上层，会挡住复活的识别）
//	③ 累计复活次数
//	④ 累计满阈值 → 死前 5 分钟内在打 BOSS → 给那个任务压 3000 秒冷却 + 清零计数
//	  ★ 压完冷却【立刻调 切下一个任务()】（死了别再死磕同一个 BOSS）：
//	    调用方里有 扫弹窗 的复活特例（基础.go），那条路子没人切任务 →
//	    不在这里切的话，压完冷却当前任务还是它自己 → 一直空转不换任务。
func 复活处理() bool {
	// ① 先认【复活】判断死没死（通用判据）
	x, y, 死了 := 识别("复活")
	if !死了 {
		return false
	}
	// ② 落花战场副本点【棕色按钮】，其他任务点【复活】
	if 当前任务 == "落花战场" {
		查找点击延时("棕色按钮", 6000)
		core.LogWithTimef("[复活] 死在了落花战场 → 点【棕色按钮】")
	} else {
		core.RandomClickInAreaWithDelay(x, y, x+5, y+5, 6000)
		core.LogWithTimef("[复活] 识别到【复活】(%d,%d) → 点击", x, y)
	}

	// 先滑掉省电模式（它浮在最上层，会挡住【复活】的识别）
	if 是否存在("省电模式") {
		m := 滑动表["省电模式"]
		if m.前置验证 == "" || 是否存在(m.前置验证) {
			core.LogWithTimef("[复活] 检测到【省电模式】→ 滑动 %d,%d → %d,%d", m.起点X, m.起点Y, m.终点X, m.终点Y)
			core.RandomSwipe(m.起点X, m.起点Y, m.终点X, m.终点Y, m.时长, m.滑后延时)
		}
	}

	n := 复活次数.Add(1)
	core.LogWithTimef("[复活] 点击复活，累计复活次数 %d/%d", n, 复活重置阈值)

	if int(n) >= 复活重置阈值 {
		core.RandomSleep(3000, 3000)
		// 死前 5 分钟内在打 BOSS → 打BOSS死的，压 6000 秒；否则非打BOSS死的，压 3000 秒
		冷却 := 3000 * time.Second
		if time.Since(躲避上次打BOSS时间) < 5*time.Minute {
			冷却 = 6000 * time.Second
			core.LogWithTimef("[复活] 打BOSS死的 → 当前任务【%s】立即结束，压冷却 %d 秒", 当前任务, int(冷却.Seconds()))
		} else {
			core.LogWithTimef("[复活] 不是打BOSS死的（上次打BOSS %.0f 秒前）→ 当前任务【%s】立即结束，压冷却 %d 秒",
				time.Since(躲避上次打BOSS时间).Seconds(), 当前任务, int(冷却.Seconds()))
		}
		// ★ 压【当前任务】的冷却（死的时候在跑谁就压谁）——
		//   以前压的是 躲避上次打BOSS任务名（打 BOSS 的那个任务），死在别的任务手里时
		//   会压错人：日志说"当前任务支线立即结束"却把主线压了 6000 秒（2026-10-19 实测）
		// ★★ 例外：正在跑子任务时【不能压当前子任务】（2026-10-20 野外挂机跑子任务
		//   死在福利领取，实测 HUD 卡在 福利领取 2131/300 干等 6000 秒）：
		//   · 子任务调度只看 子任务下次可跑，压 任务下次可跑 白压；
		//   · 且当前任务变成"在冷却的子任务"→ 主循环冷却守卫 continue（在跑业务前面）→
		//     跑子任务() 的 A 分支超时切回也执行不到 → 卡死到冷却过期。
		//   正确收尾：压【挂机任务】的冷却（死的时候人在挂机）+ 子任务这趟作废
		//   （记子任务冷却 + 清本趟计时，不然冷却一到 B 分支又插它）
		压谁 := 当前任务
		if 挂机前任务 != "" && 当前任务 != 挂机前任务 {
			压谁 = 挂机前任务
			if s := 找子任务(当前任务); s != nil {
				core.LogWithTimef("[复活] 死在子任务【%s】里 → 改压挂机任务【%s】，本趟作废", 当前任务, 挂机前任务)
				记子任务冷却(s)
				delete(子任务本趟开始, s.名)
				子任务跑过标志[s.名] = false
			}
		}
		压任务冷却(压谁, 冷却)
		复活次数.Store(0) // 压了冷却才清零计数，重新累计
		切下一个任务()      // 死了别再死磕 → 压完冷却立刻换任务（调用方不要再切一次）
	}
	return true
}
