package mian

import (
	"sync/atomic"
	"time"

	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 复活 —— 照 plugin/复活.go 搬
//
// 老逻辑（插件）：识别到【复活】弹窗 → 点复活 + 累计复活次数；
//	累计满 复活重置阈值 次后：若死前 5 分钟内在打 BOSS，就给"上次打 BOSS 的那个任务"
//	压 3000 秒冷却 + 让它立即收工（死了再死磕只会空转），并把复活计数清零重新累计。
//
// ★ 依赖躲避技能记的 躲避上次打BOSS任务名 / 躲避上次打BOSS时间（躲避技能.go 里在写）。
// ★ 本函数【不切任务】只负责"点复活 + 收尾（压冷却）"；要不要接着切走由调用方决定。
// ══════════════════════════════════════════════════════════════════════════

// 复活重置阈值 复活次数达到该值后做一次"死在 BOSS 手上"的收尾（压冷却 + 结束当前任务），计数清零重新累计。
const 复活重置阈值 = 1

// 复活次数 全局复活次数（跨任务累计；每满 复活重置阈值 次后清零，重新累计）
var 复活次数 atomic.Int32

// 复活处理 点了【复活】之后的整套处理（= 老脚本 plugin/复活.go 的 Exec）
//
//	① 点【复活】（认不到直接返回 false）
//	② 滑掉省电模式（它浮在最上层，会挡住【复活】的识别）
//	③ 累计复活次数
//	④ 累计满阈值 → 死前 5 分钟内在打 BOSS → 给那个任务压 3000 秒冷却 + 清零计数
//
// 返回 true = 这次点了【复活】（调用方通常据此 return，本轮不干别的）
func 复活处理() bool {
	// 先检测【复活】（复活可能被弹窗挡着识别不到）
	if !查找点击延时("复活") {
		return false
	}

	// 先滑掉省电模式（它浮在最上层，会挡住【复活】的识别）
	if 是否存在("省电模式") {
		m := 滑动表["省电模式"]
		core.LogWithTimef("[复活] 检测到【省电模式】→ 滑动 %d,%d → %d,%d", m[0], m[1], m[2], m[3])
		core.RandomSwipe(m[0], m[1], m[2], m[3], m[4], m[5])
	}

	n := 复活次数.Add(1)
	core.LogWithTimef("[复活] 点击复活，累计复活次数 %d/%d", n, 复活重置阈值)

	if int(n) >= 复活重置阈值 {
		core.RandomSleep(3000, 3000)
		// 死前 5 分钟内在打 BOSS → 给"上次打BOSS的那个任务"压 3000 秒冷却
		if time.Since(躲避上次打BOSS时间) < 5*time.Minute {
			core.LogWithTimef("[复活] 当前任务【%s】立即结束", 当前任务)
			压任务冷却(躲避上次打BOSS任务名, 3000*time.Second)
			复活次数.Store(0) // 压了冷却才清零计数，重新累计
		} else {
			core.LogWithTimef("[复活] 上次打BOSS任务=【%s】(%.0f秒前) → 超过5分钟，不压冷却",
				躲避上次打BOSS任务名, time.Since(躲避上次打BOSS时间).Seconds())
		}
	}
	return true
}
