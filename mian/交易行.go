// ══════════════════════════════════════════════════════════════════════════
// 交易行 —— 子任务（照 背包物品.go 的格子遍历 + 加护.go 的入口结构）
//
// 流程：主菜单 → 交易行 → 认【交易行列表】→ 点【出售】→ 认【出售列表】→
//
//	① 自适应点【蓝色按钮】6 秒
//	② 逐格点格子（4列7行）：
//	   · 点之前判【出售列表】（不在 → 直接 return，本趟作废）
//	   · 点之后判【已上架数量】（a/b，a>=b = 上架满了 → 收尾完成）
//	   · 判【物品列表】（不在 = 空格子 → 空格+1，下一个）
//	   · 读【出售数量】+【当前销售金额】（任一读不到 → 下一个）
//	   · 目标金额 = 数量 × 单价 − 1；<10 → 下一个
//	   · 小键盘点出目标金额 → 验证【出售总金额】== 目标（不等 → 下一个）
//	   · 绿色按钮 → 单选框 → 蓝色按钮 → 关闭 → 下一个
//	③ 收尾：关闭
//
// ★ 连续 交易行空格上限 次空格子 → 结束（照 背包物品 的"连续2次空背包"）
// ══════════════════════════════════════════════════════════════════════════

// 交易行格子：区域 (900,182,1170,660)，格子 63x63，X/Y 步长 69，4 列 7 行 = 28 格
const (
	交易行格子起点X = 900
	交易行格子起点Y = 182
	交易行格子宽   = 63
	交易行格子高   = 63
	交易行格子步长X = 69
	交易行格子步长Y = 69
	交易行格子列数  = 4
	交易行格子行数  = 7
)

// 交易行空格上限 连续这么多格点不出东西 → 结束（一旦有物品就清零重数）
const 交易行空格上限 = 2

// ── 交易行自己的状态 ──────────────────────────────────────────────────────
var 交易行已完成 = false

// 交易行重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 交易行重置() {
	交易行已完成 = false
}

// 交易行完成
func 交易行完成() bool { return 交易行已完成 }

// 交易行跑 子任务流程
func 交易行跑() {
	查找点击延时("主菜单")
	查找点击延时("交易行")
	if !是否存在("交易行列表") {
		// 菜单开着（主菜单按钮被压住）却开不了交易行面板 = 没这功能
		if !是否存在("主菜单列表") {
			交易行已完成 = true
			core.LogWithTimef("[交易行] ✅ 完成（没这功能）")
		}
		return
	}

	查找点击延时("出售")
	if !是否存在("出售列表") {
		return
	}

	// ① 在出售列表了 → 先循环【蓝色按钮】6 秒
	ClickAdaptive(6, 500, 3, nil,
		btn("蓝色按钮"),
	)

	// ② 逐格点格子
	空格 := 0
	for 行 := 0; 行 < 交易行格子行数; 行++ {
		if 空格 >= 交易行空格上限 {
			break
		}
		for 列 := 0; 列 < 交易行格子列数; 列++ {
			if 已停止() {
				return
			}
			// ★ 每次点击之前先判【出售列表】——不在了说明界面跑了，本趟作废（return 回主流程）
			if !是否存在("出售列表") {
				core.LogWithTimef("[交易行] 不在【出售列表】→ 本趟作废，退出等下次调度")
				return
			}

			x1 := 交易行格子起点X + 列*交易行格子步长X
			y1 := 交易行格子起点Y + 行*交易行格子步长Y
			cx := x1 + 交易行格子宽/2
			cy := y1 + 交易行格子高/2
			core.LogWithTimef("[交易行] 点格子(行%d,列%d) 中心(%d,%d)", 行+1, 列+1, cx, cy)
			core.RandomClickInAreaWithDelay(cx, cy, cx, cy)

			// 已上架数量（"已上架/总数"）：满了 → 收尾完成
			if 上架文本 := 识别取文("已上架数量"); 交易行上架已满(上架文本) {
				core.LogWithTimef("[交易行] 已上架【%s】已满 → 收尾完成", 上架文本)
				查找点击延时("关闭")
				交易行已完成 = true
				core.LogWithTimef("[交易行] ✅ 完成（上架已满）")
				return
			}

			// 物品列表不在 = 空格子
			if !是否存在("物品列表") {
				空格++
				core.LogWithTimef("[交易行] 空格子，连续 %d 次", 空格)
				if 空格 >= 交易行空格上限 {
					core.LogWithTimef("[交易行] 连续 %d 次空格子 → 结束", 交易行空格上限)
					break
				}
				continue
			}

			// 读 出售数量 / 当前销售金额（纯数字）
			// ★ 下面这些"读到了东西但处理不了"的分支【不算空格子】：格子有物品，只是读数/金额不合适
			数量文本 := 识别取文("出售数量")
			数量 := 取数字(数量文本)
			if 数量 <= 0 {
				core.LogWithTimef("[交易行] 【出售数量】读不到(%q) → 下一个", 数量文本)
				continue
			}
			单价 := 取数字(识别取文("当前销售金额"))
			if 单价 <= 0 {
				core.LogWithTimef("[交易行] 【当前销售金额】读不到 → 下一个")
				continue
			}

			// 目标金额 = 数量 × 单价 − 1（便宜一块钱）
			目标 := 数量*单价 - 1
			if 目标 < 10 {
				core.LogWithTimef("[交易行] 目标金额 %d（%d×%d−1）< 10 → 下一个", 目标, 数量, 单价)
				continue
			}

			// 有物品了 → 空格清零
			空格 = 0
			core.LogWithTimef("[交易行] 数量=%d 单价=%d → 目标金额 %d", 数量, 单价, 目标)

			// 小键盘点出目标金额
			交易行输入金额(目标)

			// 验证【出售总金额】== 目标（不等 → 下一个）
			if 实收 := 取数字(识别取文("出售总金额")); 实收 != 目标 {
				core.LogWithTimef("[交易行] 【出售总金额】=%d ≠ 目标 %d → 下一个", 实收, 目标)
				continue
			}

			// 绿色按钮 → 单选框 → 蓝色按钮 → 关闭 → 继续下一个
			查找点击延时("绿色按钮")
			查找点击延时("单选框")
			查找点击延时("蓝色按钮")
			查找点击延时("关闭")
		}
	}

	// ③ 收尾：关闭
	查找点击延时("关闭")
	交易行已完成 = true
	core.LogWithTimef("[交易行] ✅ 完成")
}

// 交易行输入金额 按小键盘把金额点出来
// ★ 规则：从左往右，遇到连续两个 0 就点一次【00】（一次输入两位），否则逐位点
// ★ 0-9/00 都是点库里的找字预设，区域已配好，直接按名字点
//
//	例：100 → 点 1、点 00；1200 → 点 1、点 2、点 00；1234 → 点 1、2、3、4
func 交易行输入金额(金额 int) {
	s := strconv.Itoa(金额)
	core.LogWithTimef("[交易行] 输入金额 %d", 金额)
	for i := 0; i < len(s); {
		if i+1 < len(s) && s[i] == '0' && s[i+1] == '0' {
			查找点击延时("00")
			i += 2
			continue
		}
		查找点击延时(string(s[i]))
		i++
	}
}

// 交易行上架已满 解析"已上架/总数"（如 0/3）：已上架 >= 总数 即满
func 交易行上架已满(文本 string) bool {
	i := strings.Index(文本, "/")
	if i < 0 {
		return false
	}
	a, err1 := strconv.Atoi(strings.TrimSpace(文本[:i]))
	b, err2 := strconv.Atoi(strings.TrimSpace(文本[i+1:]))
	if err1 != nil || err2 != nil || b <= 0 {
		return false
	}
	return a >= b
}

// 取数字 从识别文本里抽数字（取文字库读到的是纯数字，可能混空格/斜杠等杂字符）
func 取数字(文本 string) int {
	var sb strings.Builder
	for _, c := range 文本 {
		if c >= '0' && c <= '9' {
			sb.WriteRune(c)
		} else if sb.Len() > 0 {
			break // 遇到第一个非数字就停（避免把 "0/3" 读成 03）
		}
	}
	if sb.Len() == 0 {
		return 0
	}
	n, err := strconv.Atoi(sb.String())
	if err != nil {
		return 0
	}
	return n
}
