// 交易行 —— 子任务（照 背包物品.go 的格子遍历 + 加护.go 的入口结构）
//
// 流程：交易行 → 认【交易行列表】→ 点【出售】→ 认【出售列表】→
//
//	① 自适应点【蓝色按钮】6 秒
//	② 逐格点格子（4列7行）：
//	   · 点之前判【出售列表】（不在 → 直接 return，本趟作废）
//	   · 点之前判【已上架数量】（a/b，a>=b = 上架满了 → 收尾；★ 列表关闭状态才读得到）
//	   · 点之后判【物品列表】（不在 = 空格子 → 空格+1，下一个）
//	   · 读【出售数量】+【当前销售金额】（任一读不到 → 关闭，下一个）
//	   · 目标金额 = 数量 × 单价（数量=1 不减）；<10 → 关闭，下一个
//	   · 小键盘点出目标金额 → 验证【出售总金额】== 目标（不等 → 关闭，下一个）
//	   · 绿色按钮 → 单选框 → 蓝色按钮 → 关闭 → 下一个
//	③ 收尾：退出 + 置完成
//
// ★ 连续 交易行空格上限 次空格子 → 结束（照 背包物品 的"连续2次空背包"）
// ★ 不点【主菜单】：交易行走别的入口进（用户 2026-10-19）
// ══════════════════════════════════════════════════════════════════════════

// 交易行格子：区域 (900,182,1170,660)，格子 63x63，X/Y 步长 69，4 列 7 行 = 28 格
const (
	交易行格子起点X = 900
	交易行格子起点Y = 182
	交易行格子宽   = 63
	交易行格子高   = 63
	交易行格子步长X = 69
	交易行格子步长Y = 69
	交易行格子列数  = 4
	交易行格子行数  = 7
)

// 交易行空格上限 连续这么多格点不出东西 → 结束（一旦有物品就清零重数）
const 交易行空格上限 = 2

// ── 交易行自己的状态 ──────────────────────────────────────────────────────
var 交易行已完成 = false

// 交易行重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 交易行重置() {
	交易行已完成 = false
}

// 交易行完成
func 交易行完成() bool { return 交易行已完成 }

// 交易行跑 子任务流程
func 交易行跑() {
	查找点击延时("交易行")
	查找点击延时("出售")
	// ★ 三个界面任一在 = 还在交易行里，放行继续干；三个都不在才 return
	//   （出售列表 = 列表态 / 交易行列表 = 主面板 / 物品列表 = 格子详情态）
	if !是否存在("出售列表") && !是否存在("交易行列表") && !是否存在("物品列表") {
		查找点击延时("关闭")
		查找点击延时("退出")
		return
	}

	// ① 在出售列表了 → 先循环【蓝色按钮】6 秒
	ClickAdaptive(6, 500, 3, nil,
		btn("蓝色按钮"),
	)

	// ② 逐格点格子
	// ★ 每处理完一个格子都要【关闭】一次（用户 2026-10-19：每进一次出来都要关闭一次）
	//   → 抽成 交易行处理一个格子()：关闭只写在它里面一次，主循环只管 空格 计数 + 结束条件
	空格 := 0
	for 行 := 0; 行 < 交易行格子行数; 行++ {
		if 空格 >= 交易行空格上限 {
			break
		}
		for 列 := 0; 列 < 交易行格子列数; 列++ {
			if 已停止() {
				return
			}
			// ★ 每次点击之前先判【出售列表】——不在了说明界面跑了，本趟作废（return 回主流程）
			if !是否存在("出售列表") {
				core.LogWithTimef("[交易行] 不在【出售列表】→ 本趟作废，退出等下次调度")
				return
			}

			x1 := 交易行格子起点X + 列*交易行格子步长X
			y1 := 交易行格子起点Y + 行*交易行格子步长Y
			cx := x1 + 交易行格子宽/2
			cy := y1 + 交易行格子高/2
			// ★ 点格子之前判【已上架数量】（用户 2026-10-19）：此时是列表关闭状态，数字才显示
			//   —— 上一格处理完已经关了详情，这里读到的是最新累计；满了就不再点下一格
			上架文本, _ := 找色文字("已上架数量")
			if 交易行上架已满(上架文本) {
				core.LogWithTimef("[交易行] 已上架【%s】已满 → 不再点格子，收尾", 上架文本)
				交易行收尾()
				return
			}
			core.LogWithTimef("[交易行] 点格子(行%d,列%d) 中心(%d,%d)", 行+1, 列+1, cx, cy)
			core.RandomClickInAreaWithDelay(cx, cy, cx, cy)

			结果 := 交易行处理一个格子()
			switch 结果 {
			case 格子已满: // 兜底：万一哪里返回了已满 → 收尾
				交易行收尾()
				return
			case 格子已上架: // 上架成功 → 这格可能还有货，下一轮还点它（照 背包物品 的 列--）
				空格 = 0
				列--
			case 格子有物品: // 有货但没上成 → 空格清零，前进下一格
				空格 = 0
			case 格子空的: // 空格子 → 累计，够了就结束
				空格++
				core.LogWithTimef("[交易行] 空格子，连续 %d 次", 空格)
				if 空格 >= 交易行空格上限 {
					core.LogWithTimef("[交易行] 连续 %d 次空格子 → 结束", 交易行空格上限)
					break
				}
			}
			// ★ 读到过东西（数字/物品列表命中）→ 给卡死检测打分（读文字命中也算有干活）。
			//   空格子什么都不算，让它累计
			if 结果 != 格子空的 {
				本轮有命中 = true
			}
		}
	}

	// ③ 收尾
	交易行收尾()
}

// 格子处理结果
type 格子结果 int

const (
	格子空的  格子结果 = iota // 格子没东西
	格子有物品             // 格子有物品，但没上成（读数/金额不合适）→ 前进下一格
	格子已上架             // 上架成功 → 这格可能还有货 → 下一轮还点它
	格子已满              // 上架数量已满 → 该收工了
)

// 交易行处理一个格子 点开格子后的完整处理：读数 → 算目标金额 → 小键盘输入 → 验证 → 上架
// ★ 不管走到哪个分支，最后都【关闭】一次再返回（用户 2026-10-19：每进一次出来都要关闭一次）
// ★ 这里【不判已上架数量】：那数字只在列表关闭状态才显示（详情面板开着时读不到），
//
//	判它在 交易行跑() 点格子之前（用户 2026-10-19）
func 交易行处理一个格子() 格子结果 {
	// 物品列表不在 = 空格子
	if !是否存在("物品列表") {
		查找点击延时("关闭")
		return 格子空的
	}

	// 读 出售数量 / 当前销售金额（纯数字）
	// ★ 下面这些"读到了东西但处理不了"的分支【不算空格子】：格子有物品，只是读数/金额不合适
	数量文本, _ := 找色文字("出售数量")
	数量 := 取数字(数量文本)
	if 数量 <= 0 {
		core.LogWithTimef("[交易行] 【出售数量】读不到(%q) → 关闭，下一个", 数量文本)
		查找点击延时("关闭")
		return 格子有物品
	}
	单价文本, _ := 找色文字("当前销售金额")
	单价 := 取数字(单价文本)
	if 单价 <= 0 {
		core.LogWithTimef("[交易行] 【当前销售金额】读不到(%q) → 关闭，下一个", 单价文本)
		查找点击延时("关闭")
		return 格子有物品
	}

	// 目标金额 = 数量 × 单价，数量只有 1 个时【不减那 1 块】（减了就变 0 了，用户 2026-10-19）
	var 目标 int
	if 数量 == 1 {
		目标 = 单价
	} else {
		目标 = 数量*单价 - 1
	}
	if 目标 < 10 {
		core.LogWithTimef("[交易行] 目标金额 %d（数量%d 单价%d）< 10 → 关闭，下一个", 目标, 数量, 单价)
		查找点击延时("关闭")
		return 格子有物品
	}

	core.LogWithTimef("[交易行] 数量=%d 单价=%d → 目标金额 %d", 数量, 单价, 目标)

	// 小键盘点出目标金额
	交易行输入金额(目标)

	// 验证【出售总金额】== 目标（不等 → 关闭，下一个）
	实收文本, _ := 找色文字("出售总金额")
	if 实收 := 取数字(实收文本); 实收 != 目标 {
		core.LogWithTimef("[交易行] 【出售总金额】=%q → %d ≠ 目标 %d → 关闭，下一个", 实收文本, 实收, 目标)
		查找点击延时("关闭")
		return 格子有物品
	}

	// 绿色按钮 = 确认上架。点中了 = 上架成功 → 这格可能还有货，下一轮还点它
	// ★ 没点中 = 哪儿不对（金额没填对/按钮没亮）→ 只算"有物品"，前进下一格
	if 查找点击延时("绿色按钮") {
		查找点击延时("单选框")
		查找点击延时("蓝色按钮")
		查找点击延时("关闭", 774, 51, 866, 137)
		return 格子已上架
	}
	查找点击延时("关闭", 774, 51, 866, 137)
	return 格子有物品
}

// 交易行收尾 收尾统一入口：点【退出】离开交易行面板 + 置完成（用户 2026-10-19：完事收尾要退出）
// ★ 三个收尾点（格子走完 / 上架已满 / 兜底已满）都调它，保证退出只写一处
// ★ 退出必须点中才算完成：点不中 = 面板还开着，下轮接着来（用户 2026-10-20）
func 交易行收尾() {
	if 查找点击延时("退出") {
		交易行已完成 = true
		core.LogWithTimef("[交易行] ✅ 完成（已退出）")
	}
}

// 交易行输入金额 按小键盘把金额点出来
// ★ 规则：从左往右，遇到连续两个 0 就点一次【00】（一次输入两位），否则逐位点
// ★ 0-9/00 都是点库里的找字预设，区域已配好，直接按名字点
//
//	例：100 → 点 1、点 00；1200 → 点 1、点 2、点 00；1234 → 点 1、2、3、4
//
// ★ 按键没点中要吼一声（不然只进去几位、不知道漏了哪个键）
func 交易行输入金额(金额 int) {
	s := strconv.Itoa(金额)
	core.LogWithTimef("[交易行] 输入金额 %d（%s）", 金额, s)
	for i := 0; i < len(s); {
		if i+1 < len(s) && s[i] == '0' && s[i+1] == '0' {
			查找点击延时("00")
			i += 2
			continue
		}
		if !查找点击延时(string(s[i])) {
			core.LogWithTimef("[交易行] ⚠️ 按键【%c】没点中", s[i])
		}
		i++
	}
}

// 交易行上架已满 解析"已上架/总数"（如 0/3）：已上架 >= 总数 即满
func 交易行上架已满(文本 string) bool {
	i := strings.Index(文本, "/")
	if i < 0 {
		return false
	}
	a, err1 := strconv.Atoi(strings.TrimSpace(文本[:i]))
	b, err2 := strconv.Atoi(strings.TrimSpace(文本[i+1:]))
	if err1 != nil || err2 != nil || b <= 0 {
		return false
	}
	return a >= b
}

// 取数字 从识别文本里抽数字（取文字库读到的是纯数字，可能混空格/斜杠等杂字符）
func 取数字(文本 string) int {
	var sb strings.Builder
	for _, c := range 文本 {
		if c >= '0' && c <= '9' {
			sb.WriteRune(c)
		} else if sb.Len() > 0 {
			break // 遇到第一个非数字就停（避免把 "0/3" 读成 03）
		}
	}
	if sb.Len() == 0 {
		return 0
	}
	n, err := strconv.Atoi(sb.String())
	if err != nil {
		return 0
	}
	return n
}
