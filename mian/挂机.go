// 跑子任务 ★ B 方案：子任务已并入 任务表（主流程.go），这里不再自己推进，
// 只负责【把 当前任务 在"挂机任务 ↔ 子任务"之间切换】，让主循环统一驱动。
//
//	· 当前跑的是子任务（挂机前任务 != "" 且 当前任务 != 挂机前任务）：
//	    · 完成了 → 记冷却 + 清状态 + 切回挂机任务（由主循环下一轮跑挂机）
//	    · 超时了（超时秒）→ 放弃本趟：记冷却 + 连续失败+1 + 切回挂机任务
//	    · 没完成也没超时 → 什么都不做（主循环继续跑它，每轮一格）
//	· 当前跑的是挂机任务 → 找下一个冷却到了、没拉黑的子任务，切过去（主循环下一轮跑它）
//	· 一圈没找到能跑的 → 指针回 0
//
// ★ 子任务状态（第几个/连续失败/本趟计时/跑过标志）由 挂机重置() 清 ——
//
//	子任务附属在当前挂机任务上，任务切走/重跑 = 这一趟结束，全部清零
//	（★ 冷却表 子任务下次可跑 【不清】—— 那是"多久做一次"的全局节奏）
func 跑子任务() {
	// ── A. 当前正在跑子任务 ──────────────────────────────────────────────
	if 挂机前任务 != "" && 当前任务 != 挂机前任务 {
		s := 找子任务(当前任务)
		if s == nil {
			// 当前任务名不在子任务表里（异常）→ 直接切回挂机任务
			当前任务 = 挂机前任务
			挂机前任务 = ""
			return
		}
		// ① 完成了 → 重置 + 记冷却 + 失败清零 + 切回挂机任务
		if s.完成 != nil && s.完成() {
			core.LogWithTimef("[子任务] ✅ 【%s】完成 → 切回挂机任务【%s】", s.名, 挂机前任务)
			if s.重置 != nil {
				s.重置()
			}
			记子任务冷却(s)
			子任务连续失败[s.名] = 0
			delete(子任务本趟开始, s.名)
			子任务跑过标志[s.名] = false
			切回挂机任务()
			return
		}
		// ② 超时 → 放弃本趟（状态不清，下次接着干）+ 连续失败+1 + 切回挂机任务
		起点, 记过 := 子任务本趟开始[s.名]
		if !记过 {
			子任务本趟开始[s.名] = time.Now()
			起点 = 子任务本趟开始[s.名]
		}
		if s.超时秒 > 0 && time.Since(起点) >= time.Duration(s.超时秒)*time.Second {
			子任务连续失败[s.名]++
			if 子任务连续失败[s.名] >= 子任务连续失败上限 {
				core.LogWithTimef("[子任务] ⛔ 【%s】连续 %d 趟超时未完成 → 本轮挂机期间拉黑",
					s.名, 子任务连续失败[s.名])
			} else {
				core.LogWithTimef("[子任务] ⚠️ 【%s】超时 %d 秒未完成 → 放弃本趟（状态保留，下次接着；连续失败 %d/%d）",
					s.名, s.超时秒, 子任务连续失败[s.名], 子任务连续失败上限)
			}
			记子任务冷却(s)
			delete(子任务本趟开始, s.名)
			子任务跑过标志[s.名] = false
			切回挂机任务()
			return
		}
		// ③ 没完成也没超时 → 什么都不做：主循环会继续调 当前任务 的 跑()（每轮一格）
		return
	}

	// ── B. 当前跑的是挂机任务 → 找下一个能跑的子任务，切过去 ──────────────
	// ★ 随机顺序：指针为 0 = 一圈刚开始 → 这里洗一次牌（一圈内顺序稳定，跨圈才换顺序）
	if 子任务第几个 == 0 {
		if 子任务随机顺序 {
			本圈顺序 = 洗牌(子任务表)
			名 := make([]string, 0, len(本圈顺序))
			for _, s := range 本圈顺序 {
				名 = append(名, s.名)
			}
			core.LogWithTimef("[子任务] 本圈顺序已打乱：%v", 名)
		} else {
			本圈顺序 = 子任务表
		}
	}
	for 子任务第几个 < len(本圈顺序) {
		s := 本圈顺序[子任务第几个]
		if time.Now().Before(子任务下次可跑[s.名]) {
			子任务第几个++ // 冷却未到 → 跳过
			continue
		}
		if 子任务连续失败[s.名] >= 子任务连续失败上限 {
			子任务第几个++ // 连续失败拉黑 → 跳过
			continue
		}
		// 找到了 → 记住挂机任务，把 当前任务 切成它（主循环下一轮就跑它）
		core.LogWithTimef("[子任务] ═══ 插入【%s】（超时 %d 秒）═══", s.名, s.超时秒)
		挂机前任务 = 当前任务
		当前任务 = s.名
		任务开始时间 = time.Now() // HUD 进度行重新计
		刷HUD()
		子任务第几个++
		return
	}
	子任务第几个 = 0 // 一圈没找到能跑的 → 回开头
}

// 切回挂机任务 子任务结束/超时 → 当前任务 切回 挂机前任务
// ★ 不清状态（plan X：状态留着，下次冷却到了接着干）
func 切回挂机任务() {
	core.LogWithTimef("[主流程] 子任务【%s】结束 → 切回挂机任务【%s】", 当前任务, 挂机前任务)
	当前任务 = 挂机前任务
	挂机前任务 = ""
	任务开始时间 = time.Now()
	刷HUD()
	扫弹窗(任务轮转弹窗, 3) // 子任务切回来前扫一次（残留弹窗会挡住挂机的下一步）
}

// 找子任务 按名字在 子任务表 里找（返回 nil = 不是子任务）
func 找子任务(名 string) *子任务 {
	for i := range 子任务表 {
		if 子任务表[i].名 == 名 {
			return &子任务表[i]
		}
	}
	return nil
}

// 记子任务冷却 跑完（完成/超时）按随机区间记下次可跑时间
func 记子任务冷却(s *子任务) {
	子任务下次可跑[s.名] = time.Now().Add(time.Duration(s.冷最小+rand.Intn(s.冷最大-s.冷最小+1)) * time.Second)
}
