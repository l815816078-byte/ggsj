// ══════════════════════════════════════════════════════════════════════════
// 挂机 —— 通用模块（不是任务，不占主流程轮转环的一格）
//
// 野外挂机 / 门派战斗 等"到地方后挂着打"的任务，内部第二阶段都调 挂机跑()：
//	mian/野外挂机.go：去地方 → 挂机跑()
//	mian/门派战斗.go：去战场 → 挂机跑()   （以后）
//
// ★★ 它是【通用模块】，被好几个任务调 → 判断差异全部配置化：
//    点库.go 的 挂机参数表（判据 / 场景 / 跑子任务 / 时长秒），
//    加新挂机类任务 = 点库加一行，这里不用改（不再写 当前任务=="xxx" 的硬编码）。
//
// 职责（照老脚本 `_Whereas`：平铺，命中的就点，不 return）：
//	① 死了 → 点【复活】
//	② 没开自动攻击 → 点【自动攻击】按钮
//	③ 有动静（【怪物】命中 / 【省电_金币】文字变化）→ 刷新计时
//	③-2【落花战场】检测【场景_落花战场】→ 刷新它自己的计时（★ 独立：跟 ③ 互不相干）
//	④ 100 秒没动静 → 本段结束，重跑当前任务（没怪了，重新去地方再挂一轮；不换任务、不清累计）
//	④-2【落花战场】100 秒检测不到场景 → 同上重跑（★ 独立计时，怪物/金币有动静也不救）
//	⑤ 累计挂够 挂机时长(当前任务) → 任务成功，切下一个任务（收工；累计清零）
//	   时长按任务配：点库.go 的 挂机时长表（没配 → 默认 挂机时长秒）
//	⑥ 挂机中 → 跑子任务（只有【野外挂机】跑；照 plugin/挂机中.go：其他任务不跑）
// ══════════════════════════════════════════════════════════════════════════

// 挂机自己的状态
var (
	上次金币文本  = ""         // 上次读到的金币文字（有变化 = 有动静）
	上次打怪时间  = time.Now() // 上次有动静的时间
	挂机无动静秒数 = 0          // 连续多少秒没动静
	挂机开始时间  = time.Now() // 本段挂机的起点（到达地点 / 重跑 时由 挂机重置() 定）
	挂机本段秒数  = 0          // 本段（从 挂机开始时间 到现在）挂了多久
	挂机累计秒数  = 0          // ★ 已完成各段的总和：挂了一半被重跑/中断也【不清零】，照样算数
	挂机中     = false      // 真的在挂机打怪（走到 挂机跑() 末尾那条"挂机中"日志才置 true，每轮开头先清）
	上次见场景时间 = time.Now() // 【落花战场】上次检测到【场景_落花战场】的时间（独立计时，见下）
	场景无秒数   = 0          // 【落花战场】连续多少秒没检测到场景
)

// ★ 挂机超时秒 / 场景超时秒 已挪到 点库.go 的「业务配置」段

// 挂机重置 清挂机模块自己的状态（任务切换/重跑/到达地点时由任务调）
//
// ★★ 唯一【不清】的是 挂机累计秒数：挂机"挂满 挂机时长秒 才算成功"，
//
//	中间被打断（没怪了重跑、卡死切走、回城买药）都只是分段，已挂的时间照算，
//	只在 挂机跑() 第 ⑤ 步"挂够了收工"时才清零（任务成功 → 下次重新累计）。
func 挂机重置() {
	上次金币文本 = ""
	上次打怪时间 = time.Now()
	挂机无动静秒数 = 0
	挂机开始时间 = time.Now() // ★ 本段重新计时：到达地点才算"开始挂"，赶路时间不算
	挂机本段秒数 = 0
	挂机中 = false // 切走/重跑时复位：否则没人再调 挂机跑()，挂机中 会一直留 true
	上次见场景时间 = time.Now()
	场景无秒数 = 0
	// 子任务状态全清：子任务附属在当前任务上，任务切走/重跑 = 这一趟结束了，
	// 连续失败次数/本趟计时/指针全部清零（不清的话拉黑的子任务永远翻不了身）
	// ★ 冷却表 子任务下次可跑 【不清】—— 那是"多久做一次"的全局节奏
	// ★ 挂机前任务 也清：B 方案下如果正挂在子任务上被切走，要把"切回"的关系断掉
	子任务第几个 = 0
	挂机前任务 = ""
	clear(子任务连续失败)
	clear(子任务本趟开始)
	clear(子任务跑过标志)
	// 挂机累计秒数 不动（见上面说明）
}

// 挂机跑 挂机中该干的事（每轮调一次）
func 挂机跑() {
	当前状态 = "挂机中" // 一进挂机跑就置：不管后面哪条分支 return，HUD 都是"挂机中"
	挂机中 = false  // 每轮先清；走到末尾那条"挂机中"日志才算真的挂机中

	// 本段时长（④ 记账、⑤ 判断都用它，先算出来）
	挂机本段秒数 = int(time.Since(挂机开始时间).Seconds())
	已挂 := 挂机累计秒数 + 挂机本段秒数 // 累计+本段（⑤ 判断、末尾日志用；③-2/④ 记账后都 return，不冲突）

	// ★ 本任务的挂机参数（点库 挂机参数表）：判据/场景/跑子任务/时长
	//   ★ 没配（任务表里没有的挂机类任务）→ 判据 nil，等于"不在挂机"（本步直接返回）
	p := 取挂机参数(当前任务)
	if p.判据 == nil {
		return
	}
	时长 := p.时长秒
	if 时长 <= 0 {
		时长 = 挂机时长秒 // 默认兜底
	}

	// ① 死了 → 点【复活】（= 老脚本 plugin/复活.go：点复活 + 滑省电 + 累计次数 + 死在BOSS上就压冷却）
	if 复活处理() {
		core.LogWithTimef("[挂机] 检测到【复活】→ 已点击")
		return
	}

	// ② 没在挂机 → 点【自动攻击】按钮（判据按任务配，见 点库 挂机参数表）
	//    ★ 没点到也不 return：继续往下走，靠主循环"连续 20 轮没命中 → 切下一个任务"兜底
	if !p.判据() {
		core.LogWithTimef("[挂机] %s：未检测到在挂机", 当前任务)
		if 查找点击延时("自动攻击") {
			core.LogWithTimef("[挂机] 未开自动攻击 → 点击【自动攻击】")
			刷新打怪计时()
		}
	} else {
		刷新打怪计时()
	}

	// ③ 有动静 =【怪物】命中 或【省电_金币】文字变化（每轮都打，看得到怪和金币）
	怪物命中 := 是否存在("怪物")
	金币文字, 金币读到 := 找色文字("省电_金币")
	金币有变化 := 金币读到 && 金币文字 != "" && 金币文字 != 上次金币文本
	if 金币有变化 {
		core.LogWithTimef("[挂机] 【省电_金币】有变化(%s → %s) → 有动静", 上次金币文本, 金币文字)
		上次金币文本 = 金币文字
	}
	有动静 := 怪物命中 || 金币有变化
	core.LogWithTimef("[挂机] 【怪物】命中=%t 【省电_金币】读到=%q 变化=%t → 有动静=%t",
		怪物命中, 金币文字, 金币有变化, 有动静)
	if 有动静 {
		刷新打怪计时()
	}

	// ③-2【落花战场】独立判据：连续 场景超时秒 检测不到【场景】→ 重跑当前任务
	//    ★ 独立计时器：跟上面③的"有动静"【互不相干】——
	//      检测到场景 → 只刷新这个计时；检测不到 → 照样算，
	//      哪怕怪物/金币有动静也不救（用户：这个 100 秒检测不到，其他的检测到也不行）
	//    ★ 场景预设按任务配（点库 挂机参数表 的 场景 字段），空 = 不判
	if p.场景 != "" {
		if 是否存在(p.场景) {
			上次见场景时间 = time.Now()
		}
		场景无秒数 = int(time.Since(上次见场景时间).Seconds())
		core.LogWithTimef("[挂机] %s：【%s】%d 秒没检测到", 当前任务, p.场景, 场景无秒数)
		if 场景无秒数 > 场景超时秒 {
			挂机累计秒数 += 挂机本段秒数
			core.LogWithTimef("[挂机] %s：%d 秒检测不到【%s】→ 重跑当前任务（本段 %d 秒已计入，累计 %d/%d）",
				当前任务, 场景无秒数, p.场景, 挂机本段秒数, 挂机累计秒数, 时长)
			重跑当前任务()
			return
		}
	}

	// ④ 100 秒没动静 → 本段结束，重跑当前任务（重新去地方再挂一轮，不是换任务）
	//    ★ 结束前先把本段挂的时间【记进累计】（挂机重置() 不清累计，所以得在这里记账）
	挂机无动静秒数 = int(time.Since(上次打怪时间).Seconds())
	if 挂机无动静秒数 > 挂机超时秒 {
		挂机累计秒数 += 挂机本段秒数
		core.LogWithTimef("[挂机] %d 秒没动静 → 本段结束，重跑当前任务（本段 %d 秒已计入，累计 %d/%d）",
			挂机无动静秒数, 挂机本段秒数, 挂机累计秒数, 时长)
		重跑当前任务()
		return
	}

	// ⑤ 累计挂够 挂机时长秒 → 成功收工（切下一个任务回买药重新查缺药）
	//    ★ 跟 ④ 的区别：④ 是"没怪了"→ 重跑当前任务（不换任务、不清累计）；
	//      ⑤ 是"挂够了"→ 任务成功，换任务 + 累计清零（下次重新挂）
	if 已挂 >= 时长 {
		core.LogWithTimef("[挂机] 累计挂够 %d 秒（目标 %d）→ 成功收工", 已挂, 时长)
		挂机累计秒数 = 0 // 任务成功 → 本次清零（下一轮重新累计）
		切下一个任务()
		return
	}
	挂机中 = true // 走到这里 = 真在挂机打怪（主流程据此不清【省电模式】弹窗）
	core.LogWithTimef("[挂机] 挂机中（%d 秒内有动静，本段 %d 秒，累计 %d/%d）",
		挂机超时秒-挂机无动静秒数, 挂机本段秒数, 已挂, 时长)
	// 睡眠不计时（照 plugin/挂机中.go:135-140 的 睡眠不计时）：
	// 10-100 秒随机延迟，睡完把耗时补回 上次打怪时间 —— 休眠期间不算"没打怪"，
	// 否则睡 100 秒会被算进无动静、误判超时。
	睡眠开始 := time.Now()
	core.RandomSleep(10000, 100000)
	上次打怪时间 = 上次打怪时间.Add(time.Since(睡眠开始))
	// ⑥ 跑子任务（领取邮件/成就/福利…冷却到了就跑一遍）
	//    ★ 两个条件都满足才跑：本任务配了 跑子任务（点库 挂机参数表）
	//      + 此刻真的在挂机中（② 判据命中）—— 没在挂机跑子任务会把挂机彻底搞断
	if p.跑子任务 && p.判据() {
		跑子任务()
	}
}

// 刷新打怪计时 有动静 → 刷新"上次打怪时间"
func 刷新打怪计时() {
	上次打怪时间 = time.Now()
	挂机无动静秒数 = 0
}

// ── 子任务（照 plugin/挂机中.go 的 跑子任务 搬过来）─────────────────────────

// 子任务 一个子任务：名称 + 冷却区间（照 plugin/挂机中.go:96-110 的表原样搬）
// + 跑函数 + 重置函数 + 完成函数
//
// ★ 完成 是 mian 相对老框架多出来的（老框架靠 RunSubTask 的引擎：
// 步骤链 #done = 完成）。mian 没引擎那层，所以在这里补：
//   - 跑     每轮干一格（= 主循环每轮调 跑当前任务() 那一格）；没成 → 内部 return，下轮再试
//   - 完成   显式判定"这个子任务做完了"（返回 true → 清状态 + 记冷却 + 下一个；false → 状态留着，下次接上）
//   - 重置   清它自己的标志位：★ 只在【完成后】调（没完成不清 → 下次回来接着干）
//
// ★ 卡死兜底靠主循环（"100 秒没动静 → 重跑当前任务"），所以这里不需要超时字段
type 子任务 struct {
	名   string
	冷最小 int
	冷最大 int
	超时秒 int
	跑   func()
	重置  func()
	完成  func() bool
}

// 子任务表 野外挂机期间顺带跑的子任务
// ★ 实际执行顺序 = 本圈顺序（见下）：子任务随机顺序 开时每圈洗牌一次，关时就是这张表的原顺序
// ★ 必须在 init() 里赋值，不能写成 `var 子任务表 = []子任务{...}`：
//
//	照 主流程.go 任务表 的教训（表里放函数指针，防 Go 初始化循环）
var 子任务表 []子任务

// 子任务下次可跑 子任务冷却表（进程内）：跑完一个子任务按随机区间记下次可跑时间，没到就跳过
var 子任务下次可跑 = map[string]time.Time{}

// 子任务第几个 当前跑到子任务表的第几个（★ 指针，跟 主流程.go 的 当前任务 一个思路：
// 每轮主循环调 跑子任务() 只推进一格，完成/跳过才后移）
var 子任务第几个 = 0

// 子任务跑过标志 某个子任务是否已经打过"开始跑"日志（每趟只打一次）
var 子任务跑过标志 = map[string]bool{}

// 子任务本趟开始 当前子任务这一趟的开始时间（第一次指向它时记）——
// ★ 用来算 超时秒：跑到超时还没完成 → 放弃本趟（记冷却 + 下一个，状态不清 → 下次接着干）
var 子任务本趟开始 = map[string]time.Time{}

// 子任务连续失败 连续多少趟超时没完成（够了就本轮挂机期间不再跑它，只跳过）
// ★ 完成一次就清零
var 子任务连续失败 = map[string]int{}

// 子任务连续失败上限 连续这么多趟超时未完成 → 本轮挂机期间拉黑它（跳过不跑）
const 子任务连续失败上限 = 3

// 本圈顺序 当前这一圈子任务的执行顺序（= 子任务随机顺序 开时是洗过的副本；关时就是 子任务表）
var 本圈顺序 []子任务

// 洗牌 复制一份并打乱顺序（★ 不动原表；给"一圈换一次顺序"用）
func 洗牌(表 []子任务) []子任务 {
	副本 := make([]子任务, len(表))
	copy(副本, 表)
	rand.Shuffle(len(副本), func(i, j int) { 副本[i], 副本[j] = 副本[j], 副本[i] })
	return 副本
}

