// ══════════════════════════════════════════════════════════════════════════
// 买药 —— 买药任务（= 老脚本 `_Whereas`：一个任务多个步骤的做法）
//
// 流程：去地图（通用段）→ 药店npc → 药水/全部/确认/购买/退出
//
// "去地图"那段（地图/主城/地点/商店类型/传送）是通用的，在 去地图.go，
// 买药只是"去哪座城、哪个地点、哪个商店类型"不同 → 在这文件里写死。
//
// ★ 写法 = 老脚本 `_Whereas`：**一轮之内把所有 if 顺序过完，命中的就点，不 return**。
//   只有"场景守卫"（不缺药）才 return。
//
// ★ 状态变量（主城已展开/折叠开点过/已点地点/已买过/滑动次数）定义在本文件，
//   由 买药重置() 清（= 老脚本 _TaskDate 一处建所有状态，按任务分文件放）。
//
// 加新任务时照这个文件抄一份（买装备.go / 野外挂机.go …），
// 然后在 主流程.go 的 跑当前任务() 里加一条 case。
// ══════════════════════════════════════════════════════════════════════════

// 买药去哪（改这三个就行）
const (
	买药主城   = "塔巴罗城"
	买药地点   = "商店"
	买药商店类型 = "药品商店"
)

// ── 买药自己的状态（= 老脚本 任务参数.代练_XX / 种植养殖 那些任务级字段）────
// ★ 原来这里有 主城已展开/折叠开点过/已点地点/滑动次数 四个标志位，已删：
//   去地图 改成"一次跑完整段 + 返回 bool"（照老脚本）后不再需要跨轮状态。

// 买药重置 任务开始/切走时调（现在没有跨轮状态要清，留空给以后加）
func 买药重置() {}

// 买药跑 = 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，**不 return**。
// 每步点完弹出的新东西，用紧跟的兜底 if 处理（= 老脚本"点完刺探敌情 → 点代练确定"）。
func 买药跑() {
	// 场景守卫：缺药才去买（不缺药时 买药场景() 里会 切下一个任务()）
	if !买药场景() {
		return
	}
	任务就绪 = true

	// ── 去地图（通用段，见 去地图.go）：一次跑完，失败就本轮到此、下轮重来 ──
	当前状态 = "去地图"
	if !去地图(买药主城, 买药地点, 买药商店类型) {
		core.LogWithTimef("[买药] 去地图失败 → 本轮到此，下轮重来")
		return
	}

	当前状态 = "买药"
	// 循环等【药店npc】出现并点它（老脚本 CheckLoopClick("药店npc", 30秒, 2秒)）
	if !CheckLoopClick("药店npc", 10*time.Second, 2*time.Second) {
		core.LogWithTimef("[买药] 10 秒内未找到药店npc → 本轮到此，下轮重来")
		return
	}
	if !是否存在("药品列表") {
		return
	}
	core.LogWithTimef("[买药] 【药品列表】已出现 → 开始买药")
	// 药店里：药水/全部/确认/购买 任一出现就点它；【退出】命中即完成、不再等扫完
	// （照老脚本 plugin/自动买药.go 的 ClickAdaptive(30000,2000,...)；
	//   mian 按"扫 N 遍"写：15 遍 × 2 秒间隔 ≈ 30 秒）
	if ClickAdaptive(2, 500, nil,
		btn("药水"),
		btn("全部"),
		btn("确认"),
		btn("购买"),
		btnStop("退出"),
	) {
		// 命中【退出】（btnStop）= 店里买完了、面板弹出退出按钮 = 买药成功 → 切下一个任务
		// （这组按钮里没有 Done，所以返回 true 只可能是 Stop 命中）
		core.LogWithTimef("[买药] 命中【退出】→ 买药成功")
		切下一个任务()
		return
	}
	core.LogWithTimef("[买药] 未命中【退出】→ 本轮没买成，下轮重试")
}

// 买药场景 场景守卫 + 成功验证（一处判断，入口和收工都用它）：
//
//	· 入口：缺药才去买
//	· 收工后：下一轮开头再读一次，不缺 → 切下一个任务
//
// 返回 true = 缺药（要继续买）；false = 不用买（里面已切走 / 本轮不干活）
func 买药场景() bool {
	// ① 能读到【药品数量】→ 直接比下限
	if 文字, ok := 找色文字("药品数量"); ok {
		数量 := 数字(文字)
		if 数量 <= 药品下限 {
			core.LogWithTimef("[买药] 药品数量 %d <= 下限 %d → 缺药", 数量, 药品下限)
			return true
		}
		core.LogWithTimef("[买药] 药品数量 %d > 下限 %d → 不缺药，本任务不用做", 数量, 药品下限)
		切下一个任务() // = 老脚本 _TaskFlow()：不用做了就跳下一个（不看"完成状态"）
		return false
	}
	// ② 读不到数字，但识别到【是否缺药】红字 → 缺药
	if 是否存在("是否缺药") {
		core.LogWithTimef("[买药] 识别到【是否缺药】→ 缺药")
		return true
	}
	// ③ 数字和红字都读不到 → 本轮不干活（= 老脚本"找不到目标"：
	//   计数满 最大适配 就 重置状态() 重来，不用继续瞎跑买药流程）
	return false
}
