// ══════════════════════════════════════════════════════════════════════════
// 买药 —— 买药任务（= 老脚本 `_Whereas`：一个任务多个步骤的做法）
//
// 流程：去地图（通用段）→ 药店npc → 药水/全部/确认/购买/退出
//
// "去地图"那段（地图/主城/地点/商店类型/传送）是通用的，在 去地图.go，
// 买药只是"去哪座城、哪个地点、哪个商店类型"不同 → 在这文件里写死。
//
// ★ 写法 = 老脚本 `_Whereas`：**一轮之内把所有 if 顺序过完，命中的就点，不 return**。
//   只有"场景守卫"（不缺药）才 return。
//
// ★ 状态变量（主城已展开/折叠开点过/已点地点/已买过/滑动次数）定义在本文件，
//   由 买药重置() 清（= 老脚本 _TaskDate 一处建所有状态，按任务分文件放）。
//
// 加新任务时照这个文件抄一份（买装备.go / 野外挂机.go …），
// 然后在 主流程.go 的 跑当前任务() 里加一条 case。
// ══════════════════════════════════════════════════════════════════════════

// 买药去哪（改这三个就行）
const (
	买药主城   = "塔巴罗城"
	买药地点   = "商店"
	买药商店类型 = "药品商店"
)

// ── 买药自己的状态（= 老脚本 任务参数.代练_XX / 种植养殖 那些任务级字段）────
// 定义 + 重置都在这文件里（= 各任务自己管自己的状态）；
// 通用状态（当前任务/任务就绪）在 主流程.go 的 重置状态() 里。
var (
	主城已展开 = false // 主城展开了没（展开前后屏幕都有主城，识别分不出来）
	折叠开点过 = false // 折叠开点过了没（列表里一直有，点了不消失）
	已点地点  = false // 地点点开了没（文字常驻，点不消失）
	已买过   = false // 药水/全部/确认/购买 命中过（防刚进药店就误判完成）
	滑动次数  = 0     // 已滑次数（滑满 最多滑动 就重来）
)

// 买药重置（= 老脚本 _TaskDate 里属于买药的那部分）
// 由 主流程.go 的 重置状态() 转调（任务开始时清一次，循环里不清）
func 买药重置() {
	去地图重置() // 主城已展开/折叠开点过/已点地点/滑动次数（去地图 那一段的）
	已买过 = false
}

// 买药跑 = 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，**不 return**。
// 每步点完弹出的新东西，用紧跟的兜底 if 处理（= 老脚本"点完刺探敌情 → 点代练确定"）。
func 买药跑() {
	// 场景守卫：缺药才去买（不缺药时 买药场景() 里会 切下一个任务()）
	if !买药场景() {
		return
	}
	任务就绪 = true

	// ── 去地图（通用段，见 去地图.go）──────────────────────────────────
	当前状态 = "去地图"
	去地图(买药主城, 买药地点, 买药商店类型)

	// ── 买药专属：到地点后 药店npc → 药水那套 ─────────────────────────
	// 传送还没走完（地点没到）就先不找药店npc，免得在传送面板上乱点
	if !已点地点 {
		return
	}
	当前状态 = "买药"
	查找点击延时("药店npc")

	// 药店里：药水/全部/确认/购买 谁在点谁（= 老脚本"条目在就点、不在就是做完了"）
	if 扫弹窗([]string{"药水", "全部", "确认", "购买"}) {
		已买过 = true
	} else if 已买过 {
		// 上一轮买过、这一轮药店按钮全都没了 → 点【退出】
		// 然后只重置，成不成交给下一轮开头的 买药场景() 判断（不缺 = 收工）
		core.LogWithTimef("[买药] 药店按钮没了 → 点【退出】")
		查找点击延时("退出")
		买药重置()
	}
}

// 买药场景 场景守卫 + 成功验证（一处判断，入口和收工都用它）：
//
//	· 入口：缺药才去买
//	· 收工后：下一轮开头再读一次，不缺 → 切下一个任务
//
// 返回 true = 缺药（要继续买）；false = 不用买（里面已切走 / 本轮不干活）
func 买药场景() bool {
	// ① 能读到【药品数量】→ 直接比下限
	if 文字, ok := 找色文字("药品数量"); ok {
		数量 := 数字(文字)
		if 数量 <= 药品下限 {
			core.LogWithTimef("[买药] 药品数量 %d <= 下限 %d → 缺药", 数量, 药品下限)
			return true
		}
		core.LogWithTimef("[买药] 药品数量 %d > 下限 %d → 不缺药，本任务不用做", 数量, 药品下限)
		买药重置()
		切下一个任务() // = 老脚本 _TaskFlow()：不用做了就跳下一个（不看"完成状态"）
		return false
	}
	// ② 读不到数字，但识别到【是否缺药】红字 → 缺药
	if 是否存在("是否缺药") {
		core.LogWithTimef("[买药] 识别到【是否缺药】→ 缺药")
		return true
	}
	// ③ 数字和红字都读不到 → 本轮不干活（= 老脚本"找不到目标"：
	//   计数满 最大适配 就 重置状态() 重来，不用继续瞎跑买药流程）
	return false
}
