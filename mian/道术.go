package mian

import "app/core"

// ══════════════════════════════════════════════════════════════════════════
// 道术 —— 子任务（照灵力修炼的结构）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	主菜单 → 道术（带红点）→ 认【道术列表】→ 循环点【确认】→ 点【退出】
// ══════════════════════════════════════════════════════════════════════════

// ── 道术自己的状态 ──────────────────────────────────────────────────────
var (
	道术已完成 = false // 完成
)

// 道术重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 道术重置() {
	道术已完成 = false
}

// 道术完成
func 道术完成() bool { return 道术已完成 }

// 道术跑 子任务流程（每轮由 跑子任务() 调度，每轮只点该点的）
// 顺序：主菜单 → 道术 → 认【道术列表】→ 循环点【确认】→ 点【退出】
func 道术跑() {
	查找点击延时("主菜单")
	查找点击延时("道术") //这里为什么这么写因为道术是带红点的。识别不到直接等于没有
	if 是否存在("道术列表") {
		// 循环点【确认】（= 老脚本的 ClickAdaptive：60 秒内反复扫，连续 3 轮空转收工）
		ClickAdaptive(10, 500, 3, nil, btn("确认"))
		core.LogWithTimef("[道术] → 点【退出】")
		查找点击延时("退出")
		道术已完成 = true
		core.LogWithTimef("[道术] ✅ 完成")
	} else if 是否存在("主菜单列表") {
		// 菜单开着（主菜单按钮被压住）却开不了道术面板 = 没红点/没这功能
		道术已完成 = true
		core.LogWithTimef("[道术] ✅ 完成（没红点/没这功能）")
	}
}
