package mian

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 领取邮件 —— 子任务（照 plugin/领取邮件.go + assets/tasks/领取邮件.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	点【邮件】开面板 → 红点多个(14,66,598,134) 逐个点
//	→ 每个点完紧跟扫一遍弹窗（完成对钩/点击关闭）→ 点【退出】收尾
// ══════════════════════════════════════════════════════════════════════════

// ── 领取邮件自己的状态 ────────────────────────────────────────────────────
var (
	领取邮件已收 = false // 完成：红点全点完 + 退出点了
)

// 领取邮件重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 领取邮件重置() {
	领取邮件已收 = false
}

// 领取邮件完成 = 红点全领完（状态走到尽头）
func 领取邮件完成() bool { return 领取邮件已收 }

// 领取邮件跑 子任务流程（每轮由 跑子任务() 调度，每轮只点该点的）
// 顺序：点【邮件】→ 认【邮件列表】→ 一次点完所有红点 → 点【退出】
func 领取邮件跑() {
	查找点击延时("邮件")
	if 是否存在("邮件列表") {
		// 红点多个：一次全部点完（点开一个就把它带出的弹窗扫掉）
		红点 := 识别多个("红点", 14, 66, 598, 134)
		core.LogWithTimef("[领取邮件] 红点区域(14,66,598,134) 识别到 %d 个", len(红点))
		for _, 点 := range 红点 {
			if 已停止() {
				return
			}
			core.LogWithTimef("[领取邮件] 点红点(%d,%d)", 点.X, 点.Y)
			core.RandomClickInAreaWithDelay(点.X, 点.Y, 点.X+5, 点.Y+5)
			// 自适应点弹窗（= 老脚本 plugin/领取邮件.go 的 ClickAdaptive）
			ClickAdaptive(3, 500, nil,
				btn("完成对钩", 3), // 连续 3 轮同位置命中（点不掉）→ 后续跳过
				btn("点击关闭"),
			)
		}

		// 红点没了（状态走到尽头 = 真干完了）→ 点退出 → 完成
		// ★ 退出不是判据（它永远都在），判据是"红点识别不到"
		core.LogWithTimef("[领取邮件] 红点已全部领取（%d 个）→ 点【退出】", len(红点))
		查找点击延时("退出")
		领取邮件已收 = true
		core.LogWithTimef("[领取邮件] ✅ 完成")
	}
}
