// 福利领取 —— 子任务（照 plugin/福利领取.go + assets/tasks/福利领取.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	点【福利】进面板 → 外层红点多个(317,116,356,647) 逐个点
//	→ 每个点完：内层红点多个(362,247,1152,637) 逐个点（点完延时 3 秒）
//	→ 天数奖励（翻页 6 次：前 3 次从下往上、后 3 次从上往下，每次翻完扫红点点掉）
//	→ 积分奖励（下拉最多 6 次，每次下拉完扫红点点掉）
//
// ★ 不搞 plugin 的"60 秒 deadline + for 6 次翻页"：翻页/下拉用 翻页次数 标志位推进，
//   每轮只翻一页点一页，剩下的交给主循环下一轮（照 买药.go 滑动次数 的标志位做法）。
// ══════════════════════════════════════════════════════════════════════════

// ── 福利领取自己的状态 ────────────────────────────────────────────────────
var (
	福利翻页次数  = 0     // 当前翻到第几页（天数奖励 6 页 / 积分奖励 6 次下拉）
	福利领取已完成 = false // 翻页/下拉都没了 → 本子任务做完
)

const 福利翻页上限 = 6 // 天数奖励共 6 页（前 3 页从下往上、后 3 页从上往下）

// 福利领取重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 福利领取重置() {
	福利翻页次数 = 0
	福利领取已完成 = false
}

// 福利领取完成 = 翻页/下拉都没了（外层红点也点完了）
func 福利领取完成() bool { return 福利领取已完成 }

// 福利领取跑 子任务流程（每轮由 跑子任务() 调度，每轮只点该点的）
// 顺序：点【福利】→ 认【福利列表】→ 做事 → 点【退出】
func 福利领取跑() {
	// 先点【福利】（点不到就跳过：面板开着时它被盖住认不到，不影响后面的识别）
	查找点击延时("福利")
	if 是否存在("福利列表") {
		// 外层红点多个：一次全部点完（点开一个就把它内层的也点掉）
		外层点 := 识别多个("红点", 317, 116, 356, 647)
		if len(外层点) == 0 {
			// 外层无红点（状态走到尽头 = 没东西领了）→ 点【退出】→ 完成
			// ★ 退出不是判据（它永远都在），判据是"外层红点没了"
			core.LogWithTimef("[福利领取] 外层无红点 → 点【退出】")
			查找点击延时("退出")
			福利领取已完成 = true
			return
		}

		for _, 点 := range 外层点 {
			if 已停止() {
				return
			}
			core.LogWithTimef("[福利领取] 外层红点(%d,%d) → 点击", 点.X, 点.Y)
			core.RandomClickInAreaWithDelay(点.X, 点.Y, 点.X+5, 点.Y+5)

			// 内层：点开这一项后扫内层红点，逐个点（点完延时 3 秒）
			内层点 := 识别多个("红点", 362, 247, 1152, 637)
			for _, 内点 := range 内层点 {
				if 已停止() {
					return
				}
				core.LogWithTimef("[福利领取] 内层红点(%d,%d) → 点击", 内点.X, 内点.Y)
				core.RandomClickInAreaWithDelay(内点.X, 内点.Y, 内点.X+3, 内点.Y+3, 3000)
			}
		}

		// 外层全点完了 → 走翻页/下拉（天数奖励 + 积分奖励）
		翻页点红点()
		return
	}
}

// 翻页点红点 外层全点完后的翻页阶段：每轮翻一页、扫一页红点点掉
// （天数奖励：是否翻页；积分奖励：是否下拉）
// ★ 退出由【翻页次数上限】控制（翻满/拉满 → 点退出完成），不需要"都没了"的兜底
func 翻页点红点() {
	// 天数奖励：还有【是否翻页】→ 翻页（前 3 页从下往上、后 3 页从上往下）
	if 是否存在("是否翻页") {
		if 福利翻页次数 >= 福利翻页上限 {
			core.LogWithTimef("[福利领取] 翻页 %d 页已满 → 点【退出】", 福利翻页上限)
			查找点击延时("退出")
			福利领取已完成 = true
			return
		}
		福利翻页次数++
		if 福利翻页次数 <= 3 {
			m := 滑动表["福利天数"]
			core.LogWithTimef("[福利领取] 从下往上翻页 %d/3", 福利翻页次数)
			core.RandomSwipe(m[0], m[1], m[2], m[3], m[4])
		} else {
			m := 滑动表["福利天数"]
			core.LogWithTimef("[福利领取] 从上往下翻页 %d/3", 福利翻页次数-3)
			core.RandomSwipe(m[3], m[2], m[1], m[0], 1000)
		}
		扫红点区域(373, 311, 950, 641)
		return
	}

	// 积分奖励：还有【是否下拉】→ 下拉（最多 6 次，照 plugin）
	if 是否存在("是否下拉") {
		if 福利翻页次数 >= 福利翻页上限 {
			core.LogWithTimef("[福利领取] 下拉 %d 次已满 → 点【退出】", 福利翻页上限)
			查找点击延时("退出")
			福利领取已完成 = true
			return
		}
		福利翻页次数++
		m := 滑动表["福利积分"]
		core.LogWithTimef("[福利领取] 从下往上翻页 %d/6", 福利翻页次数)
		core.RandomSwipe(m[0], m[1], m[2], m[3], m[4])
		扫红点区域(968, 353, 1066, 639)
		return
	}

	// 翻页/下拉都没了 → 本轮不干活（退出由上面的次数上限控制，这里不重复退出）
	core.LogWithTimef("[福利领取] 翻页/下拉都没了 → 本轮不干活")
}

// 扫红点区域 扫指定区域内的红点多个，逐个点掉（点完延时 3 秒，照 plugin）
func 扫红点区域(x1, y1, x2, y2 int) {
	for _, 点 := range 识别多个("红点", x1, y1, x2, y2) {
		if 已停止() {
			return
		}
		core.LogWithTimef("[福利领取] 翻页后红点(%d,%d) → 点击", 点.X, 点.Y)
		core.RandomClickInAreaWithDelay(点.X, 点.Y, 点.X+3, 点.Y+3, 3000)
	}
}
