package mian

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 画册 —— 子任务（照 plugin/画册.go + assets/tasks/画册.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	主菜单 → 画册 → 外层红点多个(83,121,122,578) 逐个点
//	→ 每点开一个：内层红点多个(139,170,1168,633) 逐个点（点完点【确认】/【绿色按钮】→ 点【返回】）
//	→ 当前外层项没有内层红点了 → 滑动一次（从下往上），滑满 滑动表"画册列表"配的次数 → 下一个外层项
//	→ 退出
//
// ══════════════════════════════════════════════════════════════════════════

// ── 画册自己的状态 ────────────────────────────────────────────────────────
var (
	画册已完成 = false // 外层全处理完 / 本来就没红点（= 完成）
)

// 画册重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 画册重置() {
	画册已完成 = false
}

// 画册完成 = 外层红点全处理完 / 本来就没红点
func 画册完成() bool { return 画册已完成 }

// 画册跑 子任务流程（每轮由 跑子任务() 调度）
// 顺序：主菜单 → 画册 → 认【画册列表】→ 外层红点一次全点完（每个的内层也点掉）→ 点【退出】
func 画册跑() {
	主菜单 := 查找点击延时("主菜单")
	画册 := 查找点击延时("画册")
	core.LogWithTimef("[画册] 调试：主菜单=%t 画册=%t 画册列表=%t 主菜单列表=%t",
		主菜单, 画册, 是否存在("画册列表"), 是否存在("主菜单列表"))
	if 是否存在("画册列表") {
		// 红点识别的前提：必须先在【画框列表】页签里，才去找红点(13,71,840,706)
		// 在画框页签却找不到红点 = 画框里的红点领完了 → 直接收尾，结束画册
		if 是否存在("画框列表") && !查找点击延时("红点", 168, 55, 828, 445) {
			core.LogWithTimef("[画册] 画框页签已无红点 → 点【退出】，结束画册")
			查找点击延时("退出")
			画册已完成 = true
			core.LogWithTimef("[画册] ✅ 完成（画框红点已全部处理）")
			return
		}
		// 外层红点多个：一次全部点完
		外层点 := 识别多个("红点", 83, 121, 122, 578)
		core.LogWithTimef("[画册] 外层红点识别到 %d 个", len(外层点))
		if len(外层点) == 0 {
			// 没外层红点（点完了 / 本来就没有）→ 点【退出】→ 完成
			// ★ 有没有红点都正常退出（没有 = 没活干，也算做完）
			core.LogWithTimef("[画册] 外层红点已全部处理 → 点【退出】")
			查找点击延时("退出")
			画册已完成 = true
			core.LogWithTimef("[画册] ✅ 完成（外层红点已全部处理）")
			return
		}

		for _, 点 := range 外层点 {
			if 已停止() {
				return
			}
			core.LogWithTimef("[画册] 外层红点(%d,%d) → 点击", 点.X, 点.Y)
			core.RandomClickInAreaWithDelay(点.X, 点.Y, 点.X+5, 点.Y+5)

			// 内层 for：滑满 滑动表 配的次数结束（照老脚本 plugin/画册.go 的 5 次）
			m := 滑动表["画册图案列表"]
			for 滑了 := 1; 滑了 <= m.次数; 滑了++ {
				if 已停止() {
					return
				}
				// 内层红点(139,170,1168,633)：点开后点【确认】/【绿色按钮】→ 点【返回】

				ClickAdaptive(60, 500, 3, nil,
					btn("红点", 139, 170, 1168, 633),
					btn("确认"),
					btn("绿色按钮", 978, 583, 1054, 649),
					btnNeedHit("返回", []string{"红点"}), // ★【返回】带前置：必须本次先点过【红点】才允许点它（没点红点就点返回 = 退出面板）
				)

				// 点【返回】（照 plugin 的 CheckLoopClick 6 秒）
				// 滑动 从下往上（前置验证过才滑；没配 = 直接滑）
				if m.前置验证 == "" || 是否存在(m.前置验证) {
					cx := (m.起点X + m.终点X) / 2
					core.LogWithTimef("[画册] 从下往上滑动 (%d,%d)→(%d,%d) 第%d次", cx, m.起点Y, cx, m.终点Y, 滑了)
					core.RandomSwipe(cx, m.起点Y, cx, m.终点Y, m.时长)
				}
			}
		}

		core.LogWithTimef("[画册] 外层红点全部处理完 → 点【退出】")
		查找点击延时("退出")
		画册已完成 = true
		core.LogWithTimef("[画册] ✅ 完成（外层红点全部处理完）")
	} else if 是否存在("主菜单列表") {
		// 菜单开着（主菜单按钮被压住）却进不了画册 = 没红点/没这功能
		画册已完成 = true
		core.LogWithTimef("[画册] ✅ 完成（没红点/没这功能）")
	}
}
