package mian

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 画册 —— 子任务（照 plugin/画册.go + assets/tasks/画册.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	主菜单 → 画册 → 外层红点多个(83,121,122,578) 逐个点
//	→ 每点开一个：内层红点多个(139,170,1168,633) 逐个点（点完点【确认】/【绿色按钮】→ 点【返回】）
//	→ 当前外层项没有内层红点了 → 滑动一次（从下往上），滑满 画册滑动上限 次 → 下一个外层项
//	→ 退出
//
// ══════════════════════════════════════════════════════════════════════════

// ── 画册自己的状态 ────────────────────────────────────────────────────────
var (
	画册已完成 = false // 外层全处理完 / 本来就没红点（= 完成）
)

const 画册滑动上限 = 5 // 一个外层项最多滑动这么多次（照 plugin 的 5 次）

// 画册重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 画册重置() {
	画册已完成 = false
}

// 画册完成 = 外层红点全处理完 / 本来就没红点
func 画册完成() bool { return 画册已完成 }

// 画册跑 子任务流程（每轮由 跑子任务() 调度）
// 顺序：主菜单 → 画册 → 认【画册列表】→ 外层红点一次全点完（每个的内层也点掉）→ 点【退出】
func 画册跑() {
	查找点击延时("主菜单")
	查找点击延时("画册")
	if 是否存在("画册列表") {
		// 外层红点多个：一次全部点完
		外层点 := 识别多个("红点", 168, 55, 828, 445)
		core.LogWithTimef("[画册] 外层红点识别到 %d 个", len(外层点))
		if len(外层点) == 0 {
			// 没外层红点（点完了 / 本来就没有）→ 点【退出】→ 完成
			// ★ 有没有红点都正常退出（没有 = 没活干，也算做完）
			core.LogWithTimef("[画册] 外层红点已全部处理 → 点【退出】")
			查找点击延时("退出")
			画册已完成 = true
			return
		}

		for _, 点 := range 外层点 {
			if 已停止() {
				return
			}
			core.LogWithTimef("[画册] 外层红点(%d,%d) → 点击", 点.X, 点.Y)
			core.RandomClickInAreaWithDelay(点.X, 点.Y, 点.X+5, 点.Y+5)

			// 内层 for：最多滑动 5 次结束（照老脚本 plugin/画册.go）
			for 滑了 := 1; 滑了 <= 画册滑动上限; 滑了++ {
				if 已停止() {
					return
				}
				// 内层红点(139,170,1168,633)：点开后点【确认】/【绿色按钮】→ 点【返回】
				内层点 := 识别多个("红点", 139, 170, 1168, 633)
				for _, 内点 := range 内层点 {
					if 已停止() {
						return
					}
					core.LogWithTimef("[画册] 内层红点(%d,%d) → 点击", 内点.X, 内点.Y)
					core.RandomClickInAreaWithDelay(内点.X, 内点.Y, 内点.X+5, 内点.Y+5)
					// 自适应点弹窗（= 老脚本的 ClickAdaptive）
					ClickAdaptive(3, 500, nil,
						btn("确认"),
						btn("绿色按钮", 978, 583, 1054, 649),
					)
					// 点【返回】（照 plugin 的 CheckLoopClick 6 秒）
					查找点击延时("返回")
				}
				// 滑动 从下往上
				m := 滑动表["画册列表"]
				cx := (604 + 664) / 2
				core.LogWithTimef("[画册] 从下往上滑动 (%d,%d)→(%d,%d) 第%d次", cx, m[1], cx, m[3], 滑了)
				core.RandomSwipe(cx, m[1], cx, m[3], m[4])
			}
		}

		core.LogWithTimef("[画册] 外层红点全部处理完 → 点【退出】")
		查找点击延时("退出")
		画册已完成 = true
	}
}
