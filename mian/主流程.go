// 重置状态（= 老脚本 _TaskDate）：把状态表整个重建
func 重置状态() {
	当前任务 = 任务表[0].名
	任务就绪 = false
	适配次数 = 0
	for _, t := range 任务表 {
		t.重置()
	}
}

// 找任务 按名字从任务表里找，找不到返回 nil
func 找任务(名 string) *任务 {
	for i := range 任务表 {
		if 任务表[i].名 == 名 {
			return &任务表[i]
		}
	}
	return nil
}

// ── 主任务冷却表 ──────────────────────────────────────────────────────────
// 任务下次可跑 主任务的冷却（进程内）：复活收尾会给"死在 BOSS 上的那个任务"压 3000 秒，
//
//	让 切下一个任务() 绕开它（死了别再死磕同一个 BOSS，白等 50 分钟）。
//	★ 子任务另有自己的冷却表（挂机.go 的 子任务下次可跑，10~20 秒），两者互不干扰。
var 任务下次可跑 = map[string]time.Time{}

// 压任务冷却 某任务在 d 内不被 切下一个任务() 轮转到
func 压任务冷却(名 string, d time.Duration) {
	if 名 == "" {
		return
	}
	任务下次可跑[名] = time.Now().Add(d)
	core.LogWithTimef("[主流程] 任务【%s】压冷却 %d 秒（到 %s 再轮）",
		名, int(d.Seconds()), 任务下次可跑[名].Format("15:04:05"))
}

// 任务在冷却 该任务当前是否还在冷却中
func 任务在冷却(名 string) bool {
	return time.Now().Before(任务下次可跑[名])
}

// 跑当前任务 = 老脚本 `_Task` 的分派（查表，不用 switch）
// ★ 不看任何"完成状态"：老脚本切任务从不看状态，只看下面那两种触发
func 跑当前任务() {
	if t := 找任务(当前任务); t != nil {
		t.跑()
	}
}

// 切下一个任务 = 老脚本 `_TaskFlow`：按任务表顺序往后移一格（环形，% 取余）
// ★ 两种调法（都照老脚本）：
//
//	① 任务内部"做完了/不用做了" → 任务自己直接调（= _Activity 里的 _TaskFlow("XX")）
//	② 连续 最大适配 轮没命中 → 主循环调（= _Task() 里计数满 10 → _TaskFlow()）
//
// ★ 它【移动指针换任务】；只想"同一个任务从头再来"用 重跑当前任务()
//
// ★ 切完先扫一次 任务轮转弹窗（用户要求）：上一个任务收尾时弹出的确认/关闭之类
//
//	不扫掉，会挡住新任务的第一步（如"退出"还悬在屏幕上，买药一去点地图就点歪）
func 切下一个任务() {
	适配次数 = 0
	// ★ 正在跑子任务时调用方【必须先自己 切回挂机任务()】（2026-10-20 大整理：
	//   B 方案特判已删，改"先切回再走自己的路"）—— 不然下面按表移会移到一个
	//   子任务/别的任务上，挂机任务就丢了。
	//   现有调用方都满足：普通任务自己/主循环卡死/主循环超时/挂机跑⑤/各任务内部
	//   （子任务的 跑() 里没有调 切下一个任务() 的）+ 复活.go（自己先切回）。
	// 清旧任务的状态
	if t := 找任务(当前任务); t != nil {
		t.重置()
	}
	// 环形移一格：找到当前在表里的位置，往后 +1（到头回 0）
	// ★ 跳过被压冷却的任务（复活收尾会给"死在BOSS上的那个任务"压 3000 秒）：
	//   最多绕 len(任务表) 次；全在冷却 → 不切（留在原地），下轮再试
	for i, t := range 任务表 {
		if t.名 != 当前任务 {
			continue
		}
		for k := 1; k <= len(任务表); k++ {
			下一个 := 任务表[(i+k)%len(任务表)]
			if 下一个.子任务 {
				continue // 子任务只由 跑子任务() 插入，不参与主流程轮转
			}
			if !任务在冷却(下一个.名) {
				当前任务 = 下一个.名
				break
			}
		}
		break
	}
	当前状态 = ""             // 换任务 → 状态行先清空，等新任务自己写
	任务开始时间 = time.Now() // HUD 进度行从这里开始算
	core.LogWithTimef("[主流程] 切到下一个任务：【%s】", 当前任务)
	刷HUD()
	扫弹窗(任务轮转弹窗, 3)
	// ★ 任务轮转固定一环：每轮读一次【战斗力】刷新全局缓存 当前战力
	//   （读不到就沿用上次的值 = 识别到过就永不过期）
	//   野外挂机选地点 / 落花战场选点位 都靠它：之前只在"用到时"才读，
	//   一旦那轮读不到就永远读不到 → 每轮空转（日志：未读到战力 → 本轮不干）。
	//   ★ 读不到是常态（战斗/特殊面板遮住左下角）→ 不算"没命中"，不影响卡死判定。
	读战力()
}

// 重跑当前任务 = 把当前任务的状态清掉，下一轮从它自己的第一步重新开始
// ★ 跟 切下一个任务() 的区别：【不移动指针】，还是同一个任务
//
//	（= 老脚本 _Whereas 里标志位清掉重新来一遍，而不是 _TaskFlow 换下一个）
//
// ★ 谁调：任务内部"这一步没了/要重来"，但任务本身还没做完
//
//	例：挂机 100 秒没动静（这地方没怪了）→ 重新去地方再挂一轮，不是换任务
func 重跑当前任务() {
	适配次数 = 0
	// ★ B 方案（2026-10-20 整理）：正在跑子任务 → 作废这趟 + 切回挂机任务重跑
	//   （挂机 100 秒没动静 → 重新去地方挂一轮，子任务那趟作废）
	//   ★ 只有 挂机跑() 的 ③-2/④ 会走到（挂机跑恒在挂机任务上下文）
	if 在跑子任务() {
		if s := 找子任务(当前任务); s != nil {
			作废子任务本趟(s, "挂机没动静")
		}
		切回挂机任务()
		任务开始时间 = time.Now() // 重跑 = HUD 进度重新计
	}
	// 清当前任务自己的状态（下一轮从它的阶段一开始）
	if t := 找任务(当前任务); t != nil {
		t.重置()
	}
	core.LogWithTimef("[主流程] 重跑当前任务：【%s】", 当前任务)
}

// ══════════════════════════════ 主循环（= 老脚本 _GameFlow）══════════════
// main.go 直接调 Run()，不再需要 JSON 步骤链（老脚本 main.lua 自己就是入口）。
func Run() {
	core.LogWithTimef("[主流程] ===== mian 框架启动 =====")
	// 字库必须加载：core.Exec 找字/取文字库都要，不 SetDict 直接调 C++ 端访问空字库 → 段错误
	if !imageHandler.SetDict("ziku.txt", "library") {
		core.LogWithTimef("[主流程] 字库加载失败，OCR 不可用")
		return
	}
	// 先扫一次任务轮转弹窗（= 老脚本启动先清一遍挡屏幕的弹窗，别让旧弹窗挡住第一个任务）
	扫弹窗(任务轮转弹窗, 3)
	扫弹窗(任务弹窗)
	任务开始时间 = time.Now()
	刷HUD()
	// ★ 任务轮转固定一环：每轮读一次【战斗力】刷新全局缓存 当前战力
	//   （读不到就沿用上次的值 = 识别到过就永不过期）
	//   野外挂机选地点 / 落花战场选点位 都靠它：之前只在"用到时"才读，
	//   一旦那轮读不到就永远读不到 → 每轮空转（日志：未读到战力 → 本轮不干）。
	//   ★ 读不到是常态（战斗/特殊面板遮住左下角）→ 不算"没命中"，不影响卡死判定。
	读战力()
	核心主循环()
}

// 核心主循环 = 老脚本 `_GameFlow` 的 while true
func 核心主循环() {
	重置状态()

	// ★ 进度行 1 秒定时器：主循环每轮开头才刷一次进度行的话，
	//   业务慢的时候 HUD 数字会冻住、下一轮一次性跳好几秒。
	起进度行定时器()

	// ★ 老脚本是 while (true)（main.lua:65），没有 deadline / 没有计时退出，
	//   唯一的循环出口就是"被停止"；这里照抄。
	轮次 := 0
	开始 := time.Now()
	for {
		if 已停止() {
			core.LogWithTimef("[主流程] 已停止 → 结束（共 %d 轮，总耗时 %.1f 秒）", 轮次, time.Since(开始).Seconds())
			return
		}

		轮次++
		本轮开始 := time.Now()
		本轮有命中 = false // 每轮清零，本轮识别命中过就置 true（见 基础.go 的 识别）
		core.LogWithTimef("[主流程] ═══ 第 %d 轮（当前任务：%s）═══", 轮次, 当前任务)
		刷HUD()

		// ★ 冷却守卫：当前任务被压了冷却（如支线全不可做压 1 天）→ 本轮不跑它
		//	（切下一个任务() 只在"表里有别的任务可切"时才换得走；表里没别人时它就留在原地，
		//	 没有这层守卫会每轮照跑 → 冷却形同虚设）
		// ★ 子任务没有"在冷却中"这一说：冷却表 子任务下次可跑 只被 跑子任务() B 分支查，
		//   没人给子任务压 任务下次可跑（全项目 压任务冷却 的 3 个调用点：
		//   门派战斗/支线任务压自己、复活.go 压挂机任务）→ 不需要子任务特判
		if 任务在冷却(当前任务) {
			core.LogWithTimef("[主流程] 当前任务【%s】在冷却中（到 %s）→ 本轮跳过，不跑业务",
				当前任务, 任务下次可跑[当前任务].Format("15:04:05"))
			core.RandomSleep(5000, 5000)
			continue
		}

		// = 老脚本 _GameFlow 里的平铺调用（不看返回值，函数内部自己决定行为）
		// 任务自己做完了会调 切下一个任务()（= 老脚本 _TaskFlow），主循环不判断

		业务开始 := time.Now()
		跑当前任务() // = _Task() + _Activity()
		// ★ B 方案：正跑子任务时，每轮都要推一次 跑子任务()（完成/超时 → 记冷却 + 切回挂机任务）
		//   ★ 必须放这里：当前任务被切成子任务后，挂机跑() 不再执行，
		//     它⑥里的 跑子任务() 等不到人调 → 子任务完成了也切不回去（卡死）
		//   ★ 守卫保证只在"跑子任务"时调；跑挂机任务时仍由 挂机跑() ⑥ 负责插入下一个
		if 在跑子任务() {
			跑子任务()
		}
		业务耗时 := time.Since(业务开始).Seconds()

		弹窗开始 := time.Now()
		扫弹窗(任务弹窗) // = _表找色点击(Default_t, Default_d)
		弹窗耗时 := time.Since(弹窗开始).Seconds()

		// 超时检测（= 任务表的 超时秒）：本任务跑够上限还没做完 → 判定超时，切下一个任务
		if t := 找任务(当前任务); t != nil && t.超时秒 > 0 {
			if 已运行 := int(time.Since(任务开始时间).Seconds()); 已运行 >= t.超时秒 {
				// ★ 子任务超时 → 作废 + 切回挂机任务（不能按表移：主任务会丢）
				//   ★ 正常由上面的 跑子任务() A② 先处理（它在业务后就查），
				//     这里是保险：万一某轮业务超长没走到 A②，也不能丢主任务
				if 在跑子任务() {
					core.LogWithTimef("[主流程] 子任务【%s】已运行 %d 秒 ≥ 上限 %d → 判定超时", 当前任务, 已运行, t.超时秒)
					if s := 找子任务(当前任务); s != nil {
						作废子任务本趟(s, "超时未完成")
					}
					切回挂机任务()
					continue
				}
				core.LogWithTimef("[主流程] 当前任务【%s】已运行 %d 秒 ≥ 上限 %d → 判定超时", 当前任务, 已运行, t.超时秒)
				切下一个任务()
				continue
			}
		}

		// 卡死检测（= 老脚本 _Task 的 适配次数）：连续 最大适配 轮什么都没命中
		if 本轮有命中 {
			适配次数 = 0
		} else {
			适配次数++
			if 适配次数 >= 最大适配 {
				if 在跑子任务() {
					// ★ 卡死的是子任务 → 作废 + 切回主任务（不按任务表移！）
					//   按表移会移到下一个子任务上 → 主任务就丢了
					core.LogWithTimef("[主流程] 子任务【%s】连续 %d 轮没任何命中 → 放弃该子任务，切回主任务【%s】",
						当前任务, 最大适配, 挂机前任务)
					if s := 找子任务(当前任务); s != nil {
						作废子任务本趟(s, "连续多轮没任何命中")
					}
					切回挂机任务()
				} else {
					core.LogWithTimef("[主流程] 连续 %d 轮没任何命中 → 判定卡死", 最大适配)
					切下一个任务()
				}
			}
		}

		core.LogWithTimef("[主流程] 第 %d 轮：弹窗 %.2fs + 业务 %.2fs = 共 %.2fs（空转 %d/%d）",
			轮次, 弹窗耗时, 业务耗时, time.Since(本轮开始).Seconds(), 适配次数, 最大适配)

		// 本轮结束等一会再进下一轮（= 老脚本每次 _点击 后的 mSleep）：
		// 没命中时不给等待会疯狂空转（日志刷屏 + CPU 打满）。
		core.RandomSleep(1000, 1500)
	}
}

// 数字 从字符串里抽出连续数字拼成整数（缺药检测恢复后要用，暂保留）
//
//nolint:unused
func 数字(s string) int {
	n := 0
	for _, c := range s {
		if c >= '0' && c <= '9' {
			n = n*10 + int(c-'0')
		}
	}
	return n
}
