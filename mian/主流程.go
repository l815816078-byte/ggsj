// 刷HUD 更新 HUD 顶部状态行 + 进度行（照老引擎 bot/scheduler.go:244-290）
//   - 状态行（青色）：当前任务 + 实时状态文字（状态由各任务自己往 当前状态 里写）
//   - 进度行（黄色）：(已运行/最大执行秒)
//
// ★ 进度行由 1 秒定时器单独刷（刷进度行()），这里只刷状态行 ——
//
//	不然进度行只在每轮开头刷一次，业务慢的时候数字冻住、下一轮一次性跳好几秒。
func 刷HUD() {
	// ★ 跑子任务期间（挂机前任务 != ""）同时显示主任务：野外挂机 → 领取邮件 状态
	if 在跑子任务() {
		core.SetStatusColor("#00CCFF", "当前任务: %s → %s %s", 挂机前任务, 当前任务, 当前状态)
	} else {
		core.SetStatusColor("#00CCFF", "当前任务: %s %s", 当前任务, 当前状态)
	}
}

// 刷进度行 HUD 进度行（黄色）：(已运行/最大执行秒)，1 秒一次独立刷
// time.Since(任务开始时间) 是真实经过时间，所以这里每秒调就能每秒 +1
func 刷进度行() {
	if t := 找任务(当前任务); t != nil && t.超时秒 > 0 {
		core.SetTaskProgress("", time.Since(任务开始时间), time.Duration(t.超时秒)*time.Second)
	}
}

// 起进度行定时器 开一个 1 秒定时器刷 HUD 进度行（治本：不依赖主循环轮次）
func 起进度行定时器() {
	go func() {
		for range time.Tick(time.Second) {
			刷进度行()
		}
	}()
}

