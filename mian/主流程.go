// ══════════════════════════════════════════════════════════════════════════

// ══════════════════════════════════════════════════════════════════════════
// 任务表 —— 加新任务 = 在这里加一行（不用改任何 switch / if）
//
//	名   任务名（= 当前任务 的值）
//	跑   该任务的流程函数（= 老脚本 `_Task` 里 `if 当前任务 == "XX" then ...` 那个分支）
//	重置 清该任务自己的状态（= 老脚本 _TaskDate 里属于它的那部分）
//
// 顺序 = 轮转顺序：满 最大适配 轮没进展 → 按这个顺序切下一个（环形）
type 任务 struct {
	名   string
	跑   func()
	重置 func()
	// 子任务 true = 只能被 挂机.go 的 跑子任务() 插入，切下一个任务() 轮转跳过它
	// （子任务跑完靠 跑子任务() 检测完成并切回挂机任务，被主流程轮到会无限重复执行）
	子任务 bool
	// ↓↓↓ 下面 3 个只有子任务用（完成/冷最小/冷最大，普通任务留零值，不看这些字段）↓↓↓
	// ↓↓↓ 超时秒 全员都配：普通任务在上面、子任务在下面，这是全项目唯一的超时配置点 ↓↓↓
	//
	// ★ 2026-10-19：原来子任务要同时配 任务表（本文件）和 挂机.go 的 子任务表，
	//   名/跑/重置 三个字段重复填两遍 → 现在合并到这一张表，挂机.go 从本表筛选派生。
	// ★ 2026-10-19②：原来普通任务的超时单独配在 业务配置.go 的 任务最大执行秒，
	//   跟这里的 超时秒 两套并存 → 现在合并到本字段，那张 map 已删
	完成   func() bool // 子任务"做完了吗"（返回 true → 记冷却 + 切回挂机任务）
	冷最小 int         // 跑完后随机冷却区间的下限（秒）
	冷最大 int         // 上限（秒）；★ 必须 >= 冷最小，否则 rand.Intn 会 panic
	超时秒 int         // 这一趟最多跑多少秒（子任务：超时→放弃本趟；普通任务：超时→切下一个任务）
}

