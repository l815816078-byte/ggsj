package mian

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 灵力修炼 —— 子任务（纯步骤链，照 assets/tasks/灵力修炼.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	主菜单 → 灵力修炼 → 红点(区域 18,142,1280,601) → 蓝色按钮 → 关闭 → 退出
// ══════════════════════════════════════════════════════════════════════════

// ── 灵力修炼自己的状态 ────────────────────────────────────────────────────
var (
	灵力修炼已收 = false // 完成
)

// 灵力修炼重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 灵力修炼重置() {
	灵力修炼已收 = false
}

// 灵力修炼完成
func 灵力修炼完成() bool { return 灵力修炼已收 }

// 灵力修炼跑 子任务流程（每轮由 跑子任务() 调度）
// 顺序：主菜单 → 灵力修炼 → 认【灵力列表】→ 点红点 → 蓝色按钮 → 关闭 →
//
//	认【灵力修炼中】（= 没灵气了，吸满/吸干了）→ 退出完成
func 灵力修炼跑() {
	查找点击延时("主菜单")
	查找点击延时("灵力修炼") //这里为什么这么写因为灵力修炼是带红点的。识别不到直接等于没有
	if 是否存在("灵力列表") {
		// 红点（限定区域 18,142,1280,601）→ 蓝色按钮 → 关闭
		查找点击延时("红点", 18, 142, 1280, 601)
		查找点击延时("蓝色按钮")
		查找点击延时("关闭")
		查找点击延时("点击关闭")
		// ★ 完成条件：认到【灵力修炼中】+ 退出成功 → 才算完成
		//   （用户 2026-10-20；两个条件写一个 if，不用嵌套）
		if 是否存在("灵力修炼中") && 查找点击延时("退出") {
			灵力修炼已收 = true
			core.LogWithTimef("[灵力修炼] ✅ 完成（灵力修炼中）")
		}
	} else if 是否存在("主菜单列表") {
		// 菜单开着（主菜单按钮被压住）却开不了灵力面板 = 没红点/没这功能
		灵力修炼已收 = true
		core.LogWithTimef("[灵力修炼] ✅ 完成（没红点/没这功能）")
	}
}
