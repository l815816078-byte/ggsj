// ══════════════════════════════════════════════════════════════════════════
// 支线任务（照 plugin/支线任务.go 搬）
//
//	① 点【支线任务】
//	② 点组队与任务入口() = 点【组队】+【任务入口】
//	③ 接取链：接受 / 确认 / 立即传送 / 绿色按钮 / 引导提示 / 引导手势 / 点击关闭 / 退出
//	④ 完事后调【躲避技能】（它自己一直守到没 BOSS）
//
// ★ 【任务入口】不单独建预设 —— 它认的就是"任务"两个字，用现成的"任务"预设。
//
// ★ 支线不可做（2026-10-17 用户定）：点完某条【支线任务】后马上观察 3 秒（间隔 1 秒），
//	一直是"没有【支线进行中】且【主菜单】还在" = 这条接不了 → 跳过它换下一条；
//	找到的几条全都这样 → 压冷却 1 天 + 切下一个任务。
// ══════════════════════════════════════════════════════════════════════════

var (
	// 支线强制重接 连续多轮无进展时不切走，下一轮强制走②重新接一条支线（先撤打分再置位）
	支线强制重接 = false
	// 支线重接次数 连续强制重接了多少次（够 支线重接上限 还卡 → 放弃，让主循环正常切走）
	支线重接次数 = 0
	// 支线零条次数 连续多少轮【支线任务】一条都没识别到（面板开了也没货）
	// ★ 够 支线零条上限 次 = 今天没支线可接了 → 压冷却 1 天 + 切下一个任务
	//   （用户 2026-10-20："识别到 0 条支线：连续3次 支线任务结束"）
	//   ★ 不清的话每轮空转，只能靠主循环 20 轮卡死检测才切走，太慢
	支线零条次数 = 0
)

// 支线重接上限 连续强制重接这么多次还卡死 → 不再重接，交给主循环的卡死检测切走
// （否则会无限重接：新接的任务又卡 → 又重接 → 死循环，永远切不走）
const 支线重接上限 = 3

// 支线零条上限 连续这么多轮 0 条支线 → 判定今天没支线了，压冷却 1 天 + 切走
const 支线零条上限 = 3

// 支线任务重置 由 切下一个任务() / 重跑当前任务() 调
func 支线任务重置() {
	躲避技能重置()
	支线强制重接 = false
	支线重接次数 = 0
	支线零条次数 = 0
}

// 支线任务跑
func 支线任务跑() {
	当前状态 = "支线"

	if 复活处理() {
		// ★ 不在这里切任务：复活处理() 压了冷却的那一下已经切过了（切两次会跳过一个任务）
		core.LogWithTimef("[支线任务] 检测到【复活】→ 已点击，结束支线")
		return
	}

	// ① 已经在【支线进行中】= 接上在打 → 不用再去点列表，直接走下面的接取链
	// ★ 撤掉它的命中打分（游戏 bug 会让"支线进行中"一直挂着，认到它不代表有活干 ——
	//   不撤的话卡死检测永远被它清零，支线卡死也切不走。2026-10-19）
	// ★ 支线强制重接 置位 → 无视"支线进行中"，强制走②重新接一条（同一条卡死的换下一条）
	var 已接上 bool
	if 支线强制重接 {
		core.LogWithTimef("[支线任务] 上一轮连续无进展 → 本次强制重新接取支线")
		支线强制重接 = false
		已接上 = false
	} else {
		旧 := 本轮有命中
		已接上 = 是否存在("支线进行中")
		本轮有命中 = 旧
		// ★ 正在打支线（进行中）= 有支线，打断"连续 0 条"计数
		//   （不清的话：0条→0条→打10轮→0条 会被前面两轮累计成 3 次误杀，2026-10-20）
		if 已接上 {
			支线零条次数 = 0
		}
	}
	if !已接上 {
		// ② 循环【识别多个】找支线（数量 4），一条一条试
		点列表 := 识别多个("支线任务")
		// 强制重接时：过滤掉"支线进行中"那条（Y 相差 20 以内算同一条 ——
		// ★ 屏幕上"支线进行中"和"支线任务"是同一处文字，靠位置区分，实测同一条差 <10 像素）
		if 支线强制重接 {
			_, 中Y, 有 := 识别("支线进行中")
			if 有 {
				点列表 = 过滤同一行(点列表, 中Y)
			}
		}
		坐标串 := ""
		for _, pt := range 点列表 {
			坐标串 += fmt.Sprintf(" (%d,%d)", pt.X, pt.Y)
		}
		core.LogWithTimef("[支线任务] 识别到 %d 条支线：%s", len(点列表), 坐标串)
		if len(点列表) == 0 {
			// 一条都没找到 → 点【组队】【任务入口】把面板开出来
			查找点击延时("组队")
			查找点击延时("任务")
			// ★ 连续 支线零条上限 次 0 条（面板开了也没货）= 今天没支线可接了
			//   → 压冷却 1 天 + 切下一个任务（用户 2026-10-20）
			支线零条次数++
			if 支线零条次数 >= 支线零条上限 {
				core.LogWithTimef("[支线任务] 识别到 0 条支线：连续%d次  支线任务结束", 支线零条次数)
				压任务冷却("支线任务", 24*time.Hour)
				切下一个任务()
				return
			}
			core.LogWithTimef("[支线任务] 识别到 0 条支线：连续%d/%d次", 支线零条次数, 支线零条上限)
			return
		}
		// 有货 → 零条计数清零（别把隔了很久的两次空累加上）
		支线零条次数 = 0
		for _, pt := range 点列表 {
			if 已停止() {
				return
			}
			core.LogWithTimef("[支线任务] 点支线 (%d,%d)", pt.X, pt.Y)
			core.RandomClickInAreaWithDelay(pt.X, pt.Y, pt.X+5, pt.Y+5)

			// ③ 点完马上观察 3 秒（间隔 1 秒）：一直"没有【支线进行中】且【主菜单】还在"
			//	= 这条支线接不了（不可做）→ 换下一条
			deadline := time.Now().Add(3 * time.Second)
			for time.Now().Before(deadline) {
				if 已停止() {
					return
				}
				if 是否存在("支线进行中") || !是否存在("主菜单") {
					已接上 = true
					break
				}
				core.RandomSleep(1000, 1000)
			}
			if 已接上 {
				break
			}
			core.LogWithTimef("[支线任务] (%d,%d) 3 秒没接上 → 不可做，换下一条", pt.X, pt.Y)
		}
		if !已接上 {
			core.LogWithTimef("[支线任务] %d 条全都不可做 → 压冷却 1 天 + 切下一个任务", len(点列表))
			压任务冷却("支线任务", 24*time.Hour)
			切下一个任务()
			return
		}
	}

	// ④ 接取链：从上往下扫，命中的就点
	// 表情面板开着（点中过【表情_怒】）才滑 + 点问号：没开面板乱滑会误触别的界面
	if 查找点击延时("表情_怒", 3500) {
		// 表情面板从下往上滑一下，把下面藏着的表情翻上来（滑动表 表情滑动）
		m := 滑动表["表情滑动"]
		core.LogWithTimef("[支线任务] 表情滑动 %d,%d → %d,%d", m.起点X, m.起点Y, m.终点X, m.终点Y)
		core.RandomSwipe(m.起点X, m.起点Y, m.终点X, m.终点Y, m.时长, m.滑后延时)
		查找点击延时("表情_问号")
	}
	查找点击延时("单选框")
	查找点击延时("接受")
	查找点击延时("确认")
	查找点击延时("立即传送")
	查找点击延时("绿色按钮") // 绿色按钮 = 原来的【咒术传送】
	查找点击延时("蓝色按钮") //接取新任务
	查找点击延时("引导提示")
	查找点击延时("引导手势")
	查找点击延时("点击关闭")
	查找点击延时("退出")

	// ⑤ 完事后调【躲避技能】：它自己一直守到没 BOSS / 已停止才返回
	躲避技能跑()

	// ⑥ 打怪中（【技能冷却中】命中）→ 算有干活：支线"进行中"打小怪时接取链全空、又没 BOSS，
	//   不认这一下会被卡死检测误切（2026-10-19 用户提）
	//   ★ 命中会自动置 本轮有命中 → 卡死检测计数清零
	是否存在("技能冷却中")

	// ⑦ 有进展（点到按钮/打到怪）→ 重接计数清零（别把隔了很久的两次卡死累加上）
	if 本轮有命中 {
		支线重接次数 = 0
	}

	// ⑧ 连续 适配次数 轮无进展（主循环下一轮就要判卡死切走）→ 拦一次，强制重接
	//   ★ 重接满 支线重接上限 次还卡 → 不拦了，让主循环正常切走
	//     （否则无限重接：新接的又卡 → 又重接 → 死循环，永远切不走）
	//   ★ 只在"支线进行中"状态下拦：不在进行中说明在正常点列表，卡死检测本该切走
	if 已接上 && 适配次数 >= 19 {
		if 支线重接次数 >= 支线重接上限 {
			core.LogWithTimef("[支线任务] 已强制重接 %d 次仍无进展 → 放弃重接，交给主循环切走", 支线重接次数)
			支线重接次数 = 0
		} else {
			支线重接次数++
			core.LogWithTimef("[支线任务] 连续 %d 轮无进展 → 第 %d 次强制重接（上限 %d）", 适配次数, 支线重接次数, 支线重接上限)
			支线强制重接 = true
			本轮有命中 = true
		}
	}
}

// 过滤同一行 把点列表里 Y 跟 中Y 相差 20 以内的点剔掉（同一行 = 同一条支线）
func 过滤同一行(点列表 []坐标, 中Y int) []坐标 {
	留 := make([]坐标, 0, len(点列表))
	for _, pt := range 点列表 {
		if pt.Y > 中Y-20 && pt.Y < 中Y+20 {
			core.LogWithTimef("[支线任务] 过滤掉进行中那条 (%d,%d)（跟 %d 同一行）", pt.X, pt.Y, 中Y)
			continue
		}
		留 = append(留, pt)
	}
	return 留
}
