// ══════════════════════════════════════════════════════════════════════════
// 支线任务（照 plugin/支线任务.go 搬）
//
//	① 点【支线任务】
//	② 点组队与任务入口() = 点【组队】+【任务入口】
//	③ 接取链：接受 / 确认 / 立即传送 / 绿色按钮 / 引导提示 / 引导手势 / 点击关闭 / 退出
//	④ 完事后调【躲避技能】（它自己一直守到没 BOSS）
//
// ★ 【任务入口】不单独建预设 —— 它认的就是"任务"两个字，用现成的"任务"预设。
//
// ★ 支线不可做（2026-10-17 用户定）：点完某条【支线任务】后马上观察 3 秒（间隔 1 秒），
//	一直是"没有【支线进行中】且【主菜单】还在" = 这条接不了 → 跳过它换下一条；
//	找到的几条全都这样 → 压冷却 1 天 + 切下一个任务。
// ══════════════════════════════════════════════════════════════════════════

// 支线任务重置 由 切下一个任务() / 重跑当前任务() 调
func 支线任务重置() {
	躲避技能重置()
}

// 支线任务跑
func 支线任务跑() {
	当前状态 = "支线"

	if 复活处理() {
		core.LogWithTimef("[支线任务] 检测到【复活】→ 已点击，结束支线")
		切下一个任务()
		return
	}

	// ① 已经在【支线进行中】= 接上在打 → 不用再去点列表，直接走下面的接取链
	已接上 := 是否存在("支线进行中")
	if !已接上 {
		// ② 循环【识别多个】找支线（数量 4），一条一条试
		点列表 := 识别多个("支线任务")
		坐标串 := ""
		for _, pt := range 点列表 {
			坐标串 += fmt.Sprintf(" (%d,%d)", pt.X, pt.Y)
		}
		core.LogWithTimef("[支线任务] 识别到 %d 条支线：%s", len(点列表), 坐标串)
		if len(点列表) == 0 {
			// 一条都没找到 → 点【组队】【任务入口】把面板开出来
			查找点击延时("组队")
			查找点击延时("任务")
			return
		}
		for _, pt := range 点列表 {
			if 已停止() {
				return
			}
			core.LogWithTimef("[支线任务] 点支线 (%d,%d)", pt.X, pt.Y)
			core.RandomClickInAreaWithDelay(pt.X, pt.Y, pt.X+5, pt.Y+5)

			// ③ 点完马上观察 3 秒（间隔 1 秒）：一直"没有【支线进行中】且【主菜单】还在"
			//	= 这条支线接不了（不可做）→ 换下一条
			deadline := time.Now().Add(3 * time.Second)
			for time.Now().Before(deadline) {
				if 已停止() {
					return
				}
				if 是否存在("支线进行中") || !是否存在("主菜单") {
					已接上 = true
					break
				}
				core.RandomSleep(1000, 1000)
			}
			if 已接上 {
				break
			}
			core.LogWithTimef("[支线任务] (%d,%d) 3 秒没接上 → 不可做，换下一条", pt.X, pt.Y)
		}
		if !已接上 {
			core.LogWithTimef("[支线任务] %d 条全都不可做 → 压冷却 1 天 + 切下一个任务", len(点列表))
			压任务冷却("支线任务", 24*time.Hour)
			切下一个任务()
			return
		}
	}

	// ④ 接取链：从上往下扫，命中的就点
	查找点击延时("单选框")
	查找点击延时("接受")
	查找点击延时("确认")
	查找点击延时("立即传送")
	查找点击延时("绿色按钮") // 绿色按钮 = 原来的【咒术传送】
	查找点击延时("蓝色按钮") //接取新任务
	查找点击延时("引导提示")
	查找点击延时("引导手势")
	查找点击延时("点击关闭")
	查找点击延时("退出")

	// ⑤ 完事后调【躲避技能】：它自己一直守到没 BOSS / 已停止才返回
	躲避技能跑()
}
