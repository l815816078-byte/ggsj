// ══════════════════════════════════════════════════════════════════════════
// 封印解除 子任务（照成长.go 的"带状态"结构：类型表 + 第几个 + 完成标志）
//
// 用户原话：
//	主菜单，封印解除，封印解除列表
//	封印类型 名称 方法
//		解除（62,85,132,109，直接点这个坐标）方法（全部（找没找到都不影响），单选框，解除按钮，绿色按钮，棕色按钮）
//		单角商店（234,89,292,107，直接点这个坐标）方法（模仿落花商店那套，购买按钮换成 单角购买）
//	最后退出
//	for 封印类型 { 运行对应的方法 }
//
// ★ "解除"那串按钮 = ClickAdaptive（找没找到都不影响的【全部】单独裸点，后面 4 个是连续出现的按钮链）
// ★ "单角商店" = 照抄 落花战场.go 的 落花商店跑()，只把最后的【购买】换成【单角购买】
// ══════════════════════════════════════════════════════════════════════════

// 封印類型 一个封印类型：名称 + 区域（点这个坐标切到该类型）+ 方法（在这个类型里干什么）
type 封印类型 struct {
	名称 string
	区域 [4]int
	方法 func()
}

// 封印类型表 类型表 = 执行顺序
var 封印类型表 = []封印类型{
	{
		名称: "解除",
		区域: [4]int{62, 85, 132, 109}, // 直接点这个坐标切到"解除"
		方法: 解除,
	},
	{
		名称: "单角商店",
		区域: [4]int{234, 89, 292, 107}, // 直接点这个坐标切到"单角商店"
		方法: 单角商店跑,
	},
}

// ── 状态（= 老脚本 任务参数 那部分，每轮进来接着走）─────────────────────
var (
	封印第几个 int  = 0  // 当前处理到第几个类型（跨轮保留，超时/打断回来接着干）
	封印已完成 bool = false
)

// 封印解除重置 由 挂机.go 的 跑子任务() A 分支 / 主流程.go 的 切下一个任务() 调
func 封印解除重置() {
	封印第几个 = 0
	封印已完成 = false
}

// 封印解除完成 全部类型处理完了没
func 封印解除完成() bool {
	return 封印已完成
}

// 封印解除跑 = 主循环每轮调一次
func 封印解除跑() {
	// 进门链
	查找点击延时("主菜单")
	查找点击延时("封印解除")

	// 面板锚点（不是主菜单列表，那个一开面板就被盖住）
	if !是否存在("封印解除列表") {
		查找点击延时("关闭")
		return
	}

	if 已停止() {
		return
	}

	// 类型表已走完 → 点退出，置完成标志
	if 封印第几个 >= len(封印类型表) {
		core.LogWithTimef("[封印解除] 类型表已走完（%d/%d）→ 点【退出】", 封印第几个, len(封印类型表))
		查找点击延时("退出")
		封印已完成 = true
		return
	}

	// 当前类型
	类型 := 封印类型表[封印第几个]
	core.LogWithTimef("[封印解除] 处理类型【%s】第%d/%d → 点击切换 (%d,%d,%d,%d)",
		类型.名称, 封印第几个, len(封印类型表), 类型.区域[0], 类型.区域[1], 类型.区域[2], 类型.区域[3])
	core.RandomClickInAreaWithDelay(类型.区域[0], 类型.区域[1], 类型.区域[2], 类型.区域[3])
	core.RandomSleep(300, 500)

	// 运行该类型的方法
	类型.方法()

	封印第几个++
}

// 解除 "解除"类型的方法：全部（找没找到都不影响）→ 单选框 → 解除按钮 → 绿色按钮 → 棕色按钮
func 解除() {
	// 全部 = tab 切换，找没找到都不影响
	查找点击延时("全部")
	ClickAdaptive(3, 500, nil,
		btn("单选框", 3),
		btn("解除按钮", 3),
		btn("绿色按钮", 3),
		btn("棕色按钮", 3),
	)
}

// 单角商店跑 "单角商店"类型的方法 = 照抄 落花商店跑()，只把最后的【购买】换成【单角购买】
func 单角商店跑() {
	// ① 所有物品一次买完
	for i, 物品 := range 单角商店物品表 {
		if 已停止() {
			return
		}
		core.LogWithTimef("[单角商店] 处理第 %d/%d 个物品【%s】配置数量=%d",
			i+1, len(单角商店物品表), 物品.名称, 物品.数量)
		// 数量 0 → 不买
		if 物品.数量 <= 0 {
			core.LogWithTimef("[单角商店] 【%s】配置数量为 0 → 不买，跳过", 物品.名称)
			continue
		}

		// 找并点该物品（找不到 → 下一个物品）
		x, y, ok := 识别(物品.名称)
		core.LogWithTimef("[单角商店] 识别【%s】命中=%t 坐标=(%d,%d)", 物品.名称, ok, x, y)
		if !ok {
			continue
		}
		core.RandomClickInAreaWithDelay(x, y, x+5, y+5)

		// 数量默认 1，配置 N → 再点 N-1 次【加1】
		// ★ 一次都没加到【加1】（= 买不了）→ 点【回退】退出商店
		for 加过 := 0; 加过 < 物品.数量-1; 加过++ {
			x, y, ok := 识别("加1")
			core.LogWithTimef("[单角商店] 需要加1：第%d/最多%d次，识别【加1】命中=%t 坐标=(%d,%d)",
				加过+1, 物品.数量-1, ok, x, y)
			if !ok {
				if 加过 == 0 {
					core.LogWithTimef("[单角商店] 【%s】一次都没加到【加1】(买不了) → 点【回退】退出商店", 物品.名称)
					单角商店回退退出()
					return
				}
				core.LogWithTimef("[单角商店] 【%s】已加%d次，加不到配置%d → 用当前数量买",
					物品.名称, 加过, 物品.数量)
				break
			}
			core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
		}

		// 读【购买数量】对不对 → 对上点【确认】，对不上点击关闭
		// ★ 读不到【购买数量】→ 说明买不了 → 直接点【回退】退出商店
		文字, 读到 := 找色文字("购买数量")
		if !读到 {
			core.LogWithTimef("[单角商店] 【%s】读不到【购买数量】→ 点【回退】退出商店", 物品.名称)
			单角商店回退退出()
			return
		}
		// ★ 读到的数量 ≤ 配置数量 就算"对上"（少了 = 钱只够买这么多，少买也买），且必须是正数（0 = 买不了）
		数量 := 数字(文字)
		对上 := 数量 > 0 && 数量 <= 物品.数量
		core.LogWithTimef("[单角商店] 【%s】读【购买数量】读到=%q 解析=%d 配置=%d → 对上=%t",
			物品.名称, 文字, 数量, 物品.数量, 对上)
		if 对上 {
			if x, y, ok := 识别("确认"); ok {
				core.LogWithTimef("[单角商店] 数量对上 → 识别【确认】命中=%t 坐标=(%d,%d)", ok, x, y)
				core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
			}
		} else {
			core.LogWithTimef("[单角商店] 【%s】数量对不上 → 点击关闭 760,201,807,249", 物品.名称)
			core.RandomClickInAreaWithDelay(760, 201, 807, 249)
		}
	}

	// ② 都买完 → 点【单角购买】→ 点【回退】
	core.LogWithTimef("[单角商店] 物品都处理完 → 开始收尾（单角购买→回退）")
	x, y, ok := 识别("单角购买")
	core.LogWithTimef("[单角商店] 识别【单角购买】命中=%t 坐标=(%d,%d)", ok, x, y)
	if !ok {
		// 点不到【单角购买】（钱不够/按钮灰了）→ 直接点【回退】退出商店
		core.LogWithTimef("[单角商店] 点不到【单角购买】→ 直接点【回退】退出商店")
		单角商店回退退出()
		return
	}
	core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
	单角商店回退退出()
}

// 单角商店回退退出 买不了（点不到【加1】/读不到【购买数量】）→ 点【回退】退出商店
func 单角商店回退退出() {
	x, y, ok := 识别("回退")
	core.LogWithTimef("[单角商店] 买不了 → 识别【回退】命中=%t 坐标=(%d,%d)", ok, x, y)
	if !ok {
		return // 没识别到【回退】→ 本轮到此，下一轮再来
	}
	core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
}
