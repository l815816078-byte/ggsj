// 封印解除 子任务（类型表 + 完成标志；类型一次跑完，不分轮）
//
// 用户原话：
//	主菜单，封印解除，封印解除列表
//	封印类型 名称 方法
//		解除（62,85,132,109，直接点这个坐标）方法（全部（找没找到都不影响），单选框，解除按钮，绿色按钮，棕色按钮）
//		单角商店（234,89,292,107，直接点这个坐标）方法（模仿落花商店那套，购买按钮换成 单角购买）
//	最后退出
//	for 封印类型 { 运行对应的方法 }
//
// ★ "解除"那串按钮 = ClickAdaptive（找没找到都不影响的【全部】单独裸点，后面 4 个是连续出现的按钮链）
// ★ "单角商店" = 照抄 落花战场.go 的 落花商店跑()，只把最后的【购买】换成【单角购买】
// ══════════════════════════════════════════════════════════════════════════

// 封印類型 一个封印类型：名称 + 区域（点这个坐标切到该类型）+ 方法（在这个类型里干什么）
// ★ 方法返回 false = 没进到这个类型（面板没开/没切过去）→ 封印解除跑() 整条链 return（不点退出、不置完成）
type 封印类型 struct {
	名称 string
	区域 [4]int
	方法 func() bool
}

// 封印类型表 类型表 = 执行顺序
var 封印类型表 = []封印类型{
	{
		名称: "解除",
		区域: [4]int{62, 85, 132, 109}, // 直接点这个坐标切到"解除"
		方法: 解除,
	},
	{
		名称: "单角商店",
		区域: [4]int{234, 89, 292, 107}, // 直接点这个坐标切到"单角商店"
		方法: 单角商店跑,
	},
}

// ── 状态（只留完成标志，不留"第几个"）────────────────────────────────
var 封印已完成 bool = false

// 封印解除重置 由 挂机.go 的 跑子任务() A 分支 / 主流程.go 的 切下一个任务() 调
func 封印解除重置() {
	封印已完成 = false
}

// 封印解除完成 全部类型处理完了没
func 封印解除完成() bool {
	return 封印已完成
}

// 封印解除跑 = 主循环每轮调一次
func 封印解除跑() {
	// 进门链
	查找点击延时("主菜单")
	查找点击延时("封印解除")

	// 面板锚点（不是主菜单列表，那个一开面板就被盖住）
	if !是否存在("封印解除列表") { //注意这个列表还包括了封印召唤展示的页面找色啊。不然会出大问题的
		查找点击延时("关闭")
		查找点击延时("绿色按钮")
		查找点击延时("棕色按钮")
		return
	}

	if 已停止() {
		return
	}

	// 所有类型一次跑完
	for _, 类型 := range 封印类型表 {
		if 已停止() {
			return
		}
		core.LogWithTimef("[封印解除] 处理类型【%s】→ 点击切换 (%d,%d,%d,%d)",
			类型.名称, 类型.区域[0], 类型.区域[1], 类型.区域[2], 类型.区域[3])
		core.RandomClickInAreaWithDelay(类型.区域[0], 类型.区域[1], 类型.区域[2], 类型.区域[3])
		core.RandomSleep(300, 500)

		// 运行该类型的方法（返回 false = 没进到这个类型 → 整条链 return，下轮轮转重来）
		if !类型.方法() {
			core.LogWithTimef("[封印解除] 【%s】没进去 → 本轮返回，下轮轮转重来", 类型.名称)
			return
		}
	}

	// 类型全跑完 → 点退出，置完成标志
	// ★ 退出必须点中才算完成：点不中 = 面板还开着，下轮接着来
	core.LogWithTimef("[封印解除] 类型表已走完 → 点【退出】")
	if 查找点击延时("退出") {
		封印已完成 = true
		core.LogWithTimef("[封印解除] ✅ 完成")
	}
}

// 解除 "解除"类型的方法：全部（找没找到都不影响）→ 单选框 → 解除按钮 → 绿色按钮 → 棕色按钮
// ★ 重试：60 秒内反复扫；一轮一个都没命中 = 空转，连续 3 轮空转 → 收工
func 解除() bool {
	// 全部 = tab 切换，找没找到都不影响
	查找点击延时("全部")
	查找点击延时("单选框")
	ClickAdaptive(300, 1500, 3, nil,
		btn("解除按钮"),
		btn("绿色按钮"),
		btn("棕色按钮"),
	)
	return true
}

// 单角商店跑 "单角商店"类型的方法 = 照抄 落花商店跑()，只把最后的【购买】换成【单角购买】
// ★ 扫法（全局一遍扫）：从头到尾只往一个方向翻页——每翻到一页就把【所有】物品扫一遍；
//
//	这页有买掉的 → 系统自动跳回第一页 → 滑动计数清零，从第一页重新扫；
//	这页啥都没买到 → 计数+1，再往下翻一页；连续 滑动表 配的次数（6 次）没买到 → 收尾。
//	不需要回滑，也不会停在最后一页（滑动只往一个方向走）。
func 单角商店跑() bool {
	// 切到单角商店后先检测在不在；不在 → 返回 false（封印解除跑() 整条链也 return，不点退出、不置完成）：
	// 下轮主循环会重新走整条链（主菜单 → 封印解除 → 类型切换 → 单角商店），自然轮转
	if !是否存在("单角商店列表") {
		core.LogWithTimef("[单角商店] 没检测到【单角商店列表】→ 返回，下轮轮转重来")
		return false
	}
	m := 滑动表["单角商店"]
	滑了 := 0                  // 连续多少遍什么都没买到
	买过了 := map[string]bool{} // 已经买过/动过的物品 → 不再点（不然会一直重复买）
	for {
		if 已停止() {
			return true
		}
		core.LogWithTimef("[单角商店] 扫一遍所有物品（连续没买到 %d/%d 次）", 滑了, m.次数)
		这遍买到 := false
		for _, 物品 := range 单角商店物品表 {
			if 已停止() {
				return true
			}
			// 数量 0 → 不买（照落花商店：连物品名都不识别）
			if 物品.数量 <= 0 {
				continue
			}
			// 已经买过 → 跳过（不然同一件会一直重复买）
			if 买过了[物品.名称] {
				continue
			}
			x, y, ok := 识别(物品.名称)
			core.LogWithTimef("[单角商店] 识别【%s】→ 命中=%t 坐标=(%d,%d)", 物品.名称, ok, x, y)
			if !ok {
				continue
			}
			core.LogWithTimef("[单角商店] 找到【%s】(%d,%d) → 点击", 物品.名称, x, y)
			core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
			这遍买到 = true

			// ② 这个物品：补数量 → 读【购买数量】对上点【确认】
			// ★ 配了【是否全部】= 点【全部】按钱一次买满，不走【加1】
			// ★ 一次都没加到【加1】（= 买不了）→ 点【回退】退出商店
			if 物品.是否全部 {
				x, y, ok := 识别("全部")
				core.LogWithTimef("[单角商店] 【%s】配了全部 → 识别【全部】命中=%t 坐标=(%d,%d)", 物品.名称, ok, x, y)
				if ok {
					core.RandomClickInAreaWithDelay(x, y, x+5, y+5, 500)
				}
			} else {
				for 加过 := 0; 加过 < 物品.数量-1; 加过++ {
					x, y, ok := 识别("加1")
					core.LogWithTimef("[单角商店] 需要加1：第%d/最多%d次，识别【加1】命中=%t 坐标=(%d,%d)",
						加过+1, 物品.数量-1, ok, x, y)
					if !ok {
						if 加过 == 0 {
							// 一次都没加到【加1】= 这件买不了 → 点关闭跳过，继续下一个物品
							// ★ 不是点【回退】：回退会退出整个商店，后面的物品全都扫不到
							core.LogWithTimef("[单角商店] 【%s】一次都没加到【加1】(买不了) → 点关闭跳过，继续下一个物品", 物品.名称)
							core.RandomClickInAreaWithDelay(760, 201, 807, 249)
							买过了[物品.名称] = true
							continue
						}
						core.LogWithTimef("[单角商店] 【%s】已加%d次，加不到配置%d → 用当前数量买",
							物品.名称, 加过, 物品.数量)
						break
					}
					core.RandomClickInAreaWithDelay(x, y, x+5, y+5, 500)
				}
			}

			// 读【购买数量】对不对 → 对上点【确认】，对不上点击关闭
			// ★ 读不到【购买数量】→ 这件买不了 → 点关闭跳过，继续下一个物品（不断开、不退出商店）
			文字, 读到 := 取文("购买数量")
			if !读到 {
				core.LogWithTimef("[单角商店] 【%s】读不到【购买数量】→ 点关闭跳过，继续下一个物品", 物品.名称)
				core.RandomClickInAreaWithDelay(760, 201, 807, 249)
				买过了[物品.名称] = true // 这件试过了 → 后面不再点它
				continue
			}
			// ★ 读到的数量 ≤ 配置数量 就算"对上"（少了 = 钱只够买这么多，少买也买），且必须是正数（0 = 买不了）
			// ★ 配了【全部】的：点过全部，读多少买多少，只要是正数就算对上
			数量 := 数字(文字)
			对上 := 数量 > 0 && (物品.是否全部 || 数量 <= 物品.数量)
			core.LogWithTimef("[单角商店] 【%s】读【购买数量】读到=%q 解析=%d 配置=%d → 对上=%t",
				物品.名称, 文字, 数量, 物品.数量, 对上)
			if 对上 {
				if x, y, ok := 识别("确认"); ok {
					core.LogWithTimef("[单角商店] 数量对上 → 识别【确认】命中=%t 坐标=(%d,%d)", ok, x, y)
					core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
				}
			} else {
				core.LogWithTimef("[单角商店] 【%s】数量对不上 → 点击关闭 760,201,807,249", 物品.名称)
				core.RandomClickInAreaWithDelay(760, 201, 807, 249)
			}
			买过了[物品.名称] = true // 这件动过了 → 后面不再点它
			滑了 = 0            // 点掉一个 → 系统自动回第一页 → 计数清零重新扫
		}

		// 这一遍扫完：买了东西（系统已回第一页、滑了 已清零）→ 从第一页重新扫
		//              啥都没买到 → 计数+1，滑满 滑动表 配的次数 → 收尾
		if 这遍买到 {
			continue
		}
		滑了++
		if 滑了 >= m.次数 {
			core.LogWithTimef("[单角商店] 连续 %d 遍什么都没买到 → 收尾", 滑了)
			break
		}
		// 啥都没买到 → 往下翻一页（前置验证过才滑；只往一个方向滑，不需要回滑）
		if m.前置验证 == "" || 是否存在(m.前置验证) {
			core.LogWithTimef("[单角商店] 本页扫完啥都没买到 → 从下往上滑动 (%d,%d)→(%d,%d)（第%d次）",
				m.起点X, m.起点Y, m.终点X, m.终点Y, 滑了)
			core.RandomSwipe(m.起点X, m.起点Y, m.终点X, m.终点Y, m.时长, m.滑后延时)
		}
	}

	// ② 都买完 → 点【单角购买】→ 点【回退】
	core.LogWithTimef("[单角商店] 物品都处理完 → 开始收尾（单角购买→回退）")
	x, y, ok := 识别("单角购买")
	core.LogWithTimef("[单角商店] 识别【单角购买】命中=%t 坐标=(%d,%d)", ok, x, y)
	if !ok {
		// 点不到【单角购买】（钱不够/按钮灰了）→ 直接点【回退】退出商店
		core.LogWithTimef("[单角商店] 点不到【单角购买】→ 直接点【回退】退出商店")
		单角商店回退退出()
		return true
	}
	core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
	单角商店回退退出()
	return true
}

// 单角商店回退退出 买不了（点不到【加1】/读不到【购买数量】）→ 点【回退】退出商店
func 单角商店回退退出() {
	x, y, ok := 识别("回退")
	core.LogWithTimef("[单角商店] 买不了 → 识别【回退】命中=%t 坐标=(%d,%d)", ok, x, y)
	if !ok {
		return // 没识别到【回退】→ 本轮到此，下一轮再来
	}
	core.RandomClickInAreaWithDelay(x, y, x+5, y+5)
}
