// ══════════════════════════════════════════════════════════════════════════
// 背包物品 —— 子任务（照 plugin/物品使用.go + assets/tasks/背包物品.json）
//
// 流程：背包 → 背包分类on → 按分类逐个点背包格子（28 格）
//
//	→ 每点开一个格子：走一遍自适应点弹窗（照老脚本 ClickAdaptive）——
//	  硬超时 2000ms 内反复按序扫名单（使用/打开/选蓝色装备/选黄色武功/生命的精华/
//	  狙击强化书/铁矿/全部/确认/盒子列表/关闭/点击关闭），命中就点、继续往后找，
//	  一轮全没命中就歇一下再进下一轮
//	→ 连续 3 格点不出东西 → 下一个分类 → 自动装备 → 关闭
//
// ★ 背包会重排（用了的物品后面往前补位）：所以点中过物品就【不往后走】，还点这一格；
//   只有空格子（没弹任何东西 / 只弹了结束按钮）才往后走一格。
// ★ 关闭/盒子列表/全部 是"结束按钮"，只收尾、不算"点中过"（照老脚本）。
// ══════════════════════════════════════════════════════════════════════════

// 背包分类 需要遍历点击的分类（顺序即处理顺序）
var 背包分类 = []string{"消耗品"}

// 背包格子：区域起点 (933,175)，格子 63x62，左右间隔 6（X 步长 69），上下间隔 7（Y 步长 69），
// 一行 4 格，共 7 行 = 28 格。
const (
	格子起点X = 933
	格子起点Y = 175
	格子宽    = 63
	格子高    = 62
	格子步长X = 69
	格子步长Y = 69
	格子列数  = 4
	格子行数  = 7
)

// 连续空格子上限 连续这么多次格子都点不出东西 → 结束当前分类的循环（一旦有物品就清零重数）
const 连续空格子上限 = 3

// 背包结束按钮 = 只收尾、不代表该格子有物品（照老脚本 Done：不算"点中过"）
func 背包结束按钮(名 string) bool {
	return 名 == "关闭" || 名 == "盒子列表" || 名 == "全部" || 名 == "点击关闭"
}

// ── 背包物品自己的状态 ────────────────────────────────────────────────────
// ★ 分类/行/列/空格 都是 背包物品跑() 循环内的局部变量，不留包级状态
var 背包已完成 = false // 分类全走完 + 面板已关（= 完成）

// 背包物品重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 背包物品重置() {
	背包已完成 = false
}

// 背包物品完成 = 分类全走完且面板已关（背包识别不到）
func 背包物品完成() bool { return 背包已完成 }

// 背包物品跑 子任务流程（每轮由 跑子任务() 调度）
// 顺序：点【背包】→ 认【背包列表】→ 所有分类一次跑完 → 自动装备 → 关闭
func 背包物品跑() {
	查找点击延时("背包")
	if !是否存在("背包列表") {
		查找点击延时("关闭")
		return
	}

	// 所有分类一次跑完
	for _, 分类 := range 背包分类 {
		if 已停止() {
			return
		}
		// 切到当前分类（分类 tab 的识别引用就是分类名）
		查找点击延时("背包分类on")
		查找点击延时(分类)

		// 这一分类的格子：逐格点；连续 连续空格子上限 次点不出东西 → 该分类结束
		空格 := 0
		for 行 := 0; 行 < 格子行数; 行++ {
			for 列 := 0; 列 < 格子列数; 列++ {
				if 已停止() {
					return
				}
				x1 := 格子起点X + 列*格子步长X
				y1 := 格子起点Y + 行*格子步长Y
				cx := x1 + 格子宽/2
				cy := y1 + 格子高/2
				core.LogWithTimef("[背包物品] 分类【%s】点格子(行%d,列%d) 中心(%d,%d)", 分类, 行+1, 列+1, cx, cy)
				core.RandomClickInAreaWithDelay(cx, cy, cx, cy)

				// 点开后：自适应点弹窗（= 老脚本 plugin/物品使用.go 的 ClickAdaptive）
				点中过 := false
				ClickAdaptive(3, 500, func(name string) {
					// 结束按钮（关闭/点击关闭）只是收尾，不代表该格子有物品，不算"点中过"
					if name == "关闭" || name == "盒子列表" || name == "全部" {
						return
					}
					点中过 = true
				},
					btn("使用"),
					btn("打开"),
					btn("选蓝色装备"),
					btn("选黄色武功"),
					btn("生命的精华"),
					btn("狙击强化书"),
					btn("山贼的戒指图案"),
					btn("铁矿"),
					btn("加号"),
					//btn("全部"),//有bug我草
					btn("确认"),
					btn("盒子列表"),
					// 结束按钮（限定区域，避免误点）
					// 前置：得先点过下面这些按钮之一，才允许关面板（空格子只认到关闭 → 不会误关）
					btn("关闭", 731, 51, 825, 146, true),
					// 结束按钮
					btn("点击关闭", true),
				)

				// 点中过物品（有使用/打开/确认这类按钮）→ 计数清零；【不往后走】
				if 点中过 {
					空格 = 0
					列-- // 照老脚本 col--：for 末尾的 列++ 抵消 → 下一轮还是这一格
				} else {
					// 空格子（只有结束按钮/什么都没有）→ 往后走一格
					空格++
					core.LogWithTimef("[背包物品] 空格子，连续 %d 次", 空格)
					if 空格 >= 连续空格子上限 {
						core.LogWithTimef("[背包物品] 连续 %d 次空格子 → 结束当前分类【%s】", 连续空格子上限, 分类)
						break
					}
				}
			}
			if 空格 >= 连续空格子上限 {
				break
			}
		}
	}

	// 分类全走完 → 收尾：自动装备 → 关闭
	core.LogWithTimef("[背包物品] 分类已全部处理 → 收尾（自动装备 → 关闭）")
	查找点击延时("自动装备")
	查找点击延时("关闭")
	if !是否存在("背包") {
		背包已完成 = true // 背包面板已关 → 本子任务做完
	}
}
