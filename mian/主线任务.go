// ══════════════════════════════════════════════════════════════════════════
// 主线任务（照 assets/tasks/主线任务.json 的步骤链搬）
//
// 老框架步骤链：StartUp → 引导手势 / 引导提示 / 躲避技能 / 主线进行中 / 主线任务 / 确认
//	主线任务(点击) → 确认(点击) → 主线进行中(检测) → 回 StartUp
//	躲避技能(插件) → 主线进行中
//	检测复活(点击【复活】) → #done
//
// mian 写法：一轮之内把 if 顺序过完，命中的就点 + return（下一轮再来）。
// 顺序照 JSON 的优先级：引导 → 复活 → 进行中(躲技能) → 接任务。
// ══════════════════════════════════════════════════════════════════════════

// 主线已点任务 本条主线点过【主线任务】了没（它点完不消失 → 标志位挡，否则每轮重复点）
//
//	★ 清的时机 = ③ 检测到【主线进行中】（这条真接上了）→ 清掉，
//	  这条打完（进行中消失）后下一轮才能进 ④ 接下一条主线（一直做主线）
var 主线已点任务 = false

// 主线任务重置 由 切下一个任务() / 重跑当前任务() 调
func 主线任务重置() {
	主线已点任务 = false
	躲避技能重置()
}

// 主线任务跑 一轮干一格
func 主线任务跑() {
	// ② 死了 → 点【复活】（照 JSON 的"检测复活"步骤：命中 → #done = 结束本任务）
	//   ★ 复活处理() 里还会滑省电 + 累计次数 + 死在BOSS上给那个任务压冷却（照 plugin/复活.go）
	当前状态 = "主线"
	if 复活处理() {
		// ★ 不在这里切任务：复活处理() 压了冷却的那一下已经切过了（切两次会跳过一个任务）
		core.LogWithTimef("[主线任务] 检测到【复活】→ 已点击，结束主线")
		return
	}

	// ③ 主线进行中 → 打 BOSS 时躲技能（照 JSON 的"躲避技能"插件步骤）
	//    躲避技能跑() 自己会先检 BOSS：没 BOSS 直接返回，不影响正常跑主线
	//    ★ 清【主线已点任务】：【主线进行中】= 这条真接上了并在打，
	//      清掉后这条打完（进行中消失）→ 下一轮能进 ④ 接下一条主线（一直做主线）
	//      ★ 不用【确认】清（它可能是别的弹窗的确认，会误清）
	if 是否存在("主线进行中") || 是否存在("支线进行中") {
		主线已点任务 = false
		躲避技能跑()
		core.RandomSleep(3000, 6000)
		return
	}

	// ④ 没在进行中 → 接主线：找多个（数量 3，见点库的 寻找个数），循环找"对的"才点
	//    ★ 判定（用户定）：每个命中点偏移 24,0 → 该点作左上角扩展 16x16 → 单点找色 #69DD72
	//      【没找到】= 是主线任务 → 点它；【找到】= 不是 → 试下一个（相似度 1）
	if !主线已点任务 {
		点列表 := 识别多个("主线任务")
		if len(点列表) == 0 {
			// 主线一个都没找到 → 切换一下（照支线任务那套：支线任务 → 组队 → 任务）
			core.LogWithTimef("[主线任务] 没找到【主线任务】→ 切换一下（组队 → 任务）")
			查找点击延时("组队")
			// 【任务入口】= 右上角"任务"两个字 → 用"任务"预设
			查找点击延时("任务")
			return
		}
		for _, pt := range 点列表 {
			gx, gy := pt.X+24, pt.Y
			if _, _, 找到 := core.FindColor(gx, gy, gx+16, gy+16, "#69DD72-0x101010", 1, 1, 1); 找到 {
				core.LogWithTimef("[主线任务] 候选(%d,%d) 偏移24,0 区域 %d,%d,%d,%d 找到 #69DD72 → 不是，试下一个",
					pt.X, pt.Y, gx, gy, gx+16, gy+16)
				continue
			}
			core.LogWithTimef("[主线任务] 候选(%d,%d) 未找到 #69DD72 → 是主线任务 → 点击", pt.X, pt.Y)
			core.RandomClickInAreaWithDelay(pt.X, pt.Y, pt.X+5, pt.Y+5)
			主线已点任务 = true
			return
		}
		// 有候选但都不是主线 → 也切换一下
		core.LogWithTimef("[主线任务] %d 个候选都不是主线任务 → 切换一下（组队 → 任务）", len(点列表))
		查找点击延时("组队")
		// 【任务入口】= 右上角"任务"两个字 → 用"任务"预设
		查找点击延时("任务")
		return
	}

	// ⑤ 点【确认】接取（照 JSON：主线任务 → 确认 → 主线进行中）
	//    ★ 这里不清【主线已点任务】：【确认】是通用弹窗，不一定是接主线点出来的，
	//      靠它清会误清 → 导致 ④ 重复点主线任务。清的时机在 ③（检测到【主线进行中】= 真接上了）
	查找点击延时("确认")
	查找点击延时("表情_笑")
}
