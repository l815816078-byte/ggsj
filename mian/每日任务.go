// 每日任务（照 plugin/每日任务.go + plugin/挂机中.go:35-49 + assets/tasks/每日任务.json 搬）
//
// 老框架：主菜单 → 滑动 → 点【任务】→ 插件（【每日】【周常】两个 tab 循环接取
//	→ 点【每日】→ 【绿色战力】多个逐个点 → 打怪任务 → 自动进行 → 蓝色按钮）
//	→ 退出 → 一次都没点过蓝色按钮 = 直接完成；点过 = 进 挂机中 打怪
//
// ★ 打怪阶段调通用 挂机跑()（跟 野外挂机/落花战场 一样）。
//   每日任务的特例（照 plugin/挂机中.go:35-49）已经分叉在 挂机.go 的 ② 和 ⑥ 里：
//	· ② 不判断【自动攻击开启中】：改判【任务进行中】；或 先【省电模式】再【/】
//	· ⑥ 挂机中也跑子任务（跟"只有野外挂机才跑"那条并列，照 plugin:47）
//   ★ 别在任务自己的文件里另写挂机函数 —— 分叉一律放通用模块里按 当前任务 判。
//
// ★ 写法 = 老脚本 _Whereas：一轮之内把 if 顺序过完，**命中才 return**（点了屏幕变了，
//   再识别没意义）；没命中就继续往下走，不 return。点完不消失的用标志位挡。
// ══════════════════════════════════════════════════════════════════════════

// 是否接取无需战力任务 / 每日类型列表 / 每日最多滑动 都配在 点库.go 的「业务配置」段

// ── 每日任务自己的状态 ────────────────────────────────────────────────────
var (
	每日菜单已点 = false // 点过【主菜单】（点完不消失 → 标志位挡）
	每日已滑动  = false // 入口滑动做过了没
	每日面板已开 = false // 点过【任务】进面板了没

	每日第几类型 = 0     // 现在在处理 每日类型列表 的第几个
	每日已切类型 = false // 当前 tab 切过去了没
	每日滑动次数 = 0     // 当前 tab 已经滑了几次

	每日已点每日 = false // 接取阶段结束、点过【每日】了没
	开始挂机   = false // 点过 ⑤ 位置的【蓝色按钮】= 接到打怪任务 → 进挂机打怪
	每日已接完  = false // 接取全做完 → 进打怪阶段
)

// 每日任务重置 由 切下一个任务() / 重跑当前任务() 调
func 每日任务重置() {
	每日菜单已点 = false
	每日已滑动 = false
	每日面板已开 = false
	每日第几类型 = 0
	每日已切类型 = false
	每日滑动次数 = 0
	每日已点每日 = false
	开始挂机 = false
	每日已接完 = false
	挂机重置()
}

// 每日任务跑 平铺：顺序过完，命中才 return
func 每日任务跑() {
	// ── ① 打怪阶段（接取已做完）：通用挂机模块（照 plugin/挂机中.go:35-49，
	//    它里面已经按"是不是每日任务"分好了叉：不判断自动攻击、挂机中也跑子任务）
	if 开始挂机 {
		挂机跑()
		return
	}

	// ── ② 打开任务面板：主菜单 → 滑动 → 点【任务】───────────────────────
	//    面板没开 = 后面全都干不了，这一步按链推进（三步有先后依赖）
	if !每日面板已开 {
		当前状态 = "开任务面板"
		if !每日菜单已点 {
			if 查找点击延时("主菜单") {
				每日菜单已点 = true
			}
			return
		}
		if !每日已滑动 {
			core.LogWithTimef("[每日任务] 滑动 1027,579 → 990,127")
			m := 滑动表["开面板"]
			core.RandomSwipe(m[0], m[1], m[2], m[3], m[4], m[5])
			每日已滑动 = true
			return
		}
		if 查找点击延时("任务") {
			每日面板已开 = true
		}
		return
	}

	// ── ③ 两个 tab 循环接取（照 plugin）─────────────────────────────────
	if 每日第几类型 < len(每日类型列表) {
		当前状态 = "接取每日"
		类型 := 每日类型列表[每日第几类型]
		// 没切过 tab → 先切（切完等列表刷新，下轮再找任务）
		if !每日已切类型 {
			if !查找点击延时(类型) {
				return
			}
			每日已切类型 = true
			每日滑动次数 = 0
			core.LogWithTimef("[每日任务] 已切到任务类型【%s】", 类型)
			return
		}
		// 已切过 → 后续动作平铺：接取已满 / 找到任务 / 滑动，谁先命中就走谁
		if 是否存在("任务接取已满") {
			core.LogWithTimef("[每日任务]【%s】任务接取已满 → 下一个类型", 类型)
			每日下一个类型()
			return
		}
		if 查找点击延时("符合战力") || (是否接取无需战力任务 && 查找点击延时("无需战力")) {
			// 找到任务 → 同一轮把【蓝色按钮】也点了（照 plugin：点完任务紧接着接取）
			查找点击延时("蓝色按钮", 834, 626, 912, 705)
			return
		}
		// 都没找到 → 滑动列表（从下往上）；滑满换下一个 tab
		if 每日滑动次数 >= 每日最多滑动 {
			core.LogWithTimef("[每日任务]【%s】滑了 %d 次仍没找到 → 下一个类型", 类型, 每日滑动次数)
			每日下一个类型()
			return
		}
		每日滑动次数++
		cx := (447 + 518) / 2
		core.LogWithTimef("[每日任务]【%s】第%d次未找到任务 → 滑动 %d,528 → %d,296",
			类型, 每日滑动次数, cx, cx)
		m := 滑动表["每日列表"]
		core.RandomSwipe(cx, m[1], cx, m[3], m[4], m[5])
		return
	}

	// ── ④ 点【每日】（照 plugin 结尾回到"每日"页签）─────────────────────
	if !每日已点每日 {
		当前状态 = "回每日页签"
		if 查找点击延时("每日") {
			每日已点每日 = true
		}
		return
	}

	// ── ⑤ 【绿色战力】多个一次全点完（点一个 → 检测打怪任务 → 自动进行 → 蓝色按钮）
	当前状态 = "点绿色战力"
	战力点 := 识别多个("绿色战力", 552, 171, 834, 622)
	core.LogWithTimef("[每日任务] 识别到 %d 个【绿色战力】", len(战力点))
	for _, pt := range 战力点 {
		if 已停止() {
			return
		}
		core.LogWithTimef("[每日任务] 战力 → 点击 (%d,%d)", pt.X, pt.Y)
		core.RandomClickInAreaWithDelay(pt.X, pt.Y, pt.X+5, pt.Y+5)
		// 点完检测【每日打怪任务】：没检测到 → 继续下一个（照 plugin 的 continue）
		if !是否存在("每日打怪任务", 857, 142, 1231, 587) {
			core.LogWithTimef("[每日任务] 战力(%d,%d) 未检测到【每日打怪任务】→ 继续下一个", pt.X, pt.Y)
			continue
		}
		core.LogWithTimef("[每日任务] 战力(%d,%d) 检测到【每日打怪任务】", pt.X, pt.Y)
		// 检测到 → 点【自动进行】→ 点【蓝色按钮】（照 plugin 同一轮做完）
		查找点击延时("自动进行", 773, 657, 827, 681)
		if 查找点击延时("蓝色按钮", 955, 631, 1102, 702) {
			开始挂机 = true
		}
	}

	// 都点完 → 点【退出】收尾（照 plugin 结尾的 退出 步骤）
	if 查找点击延时("退出") {
		if !开始挂机 {
			core.LogWithTimef("[每日任务] 一次都没点【蓝色按钮】→ 直接完成整个任务")
			切下一个任务()
			return
		}
		core.LogWithTimef("[每日任务] 点过【蓝色按钮】→ 进打怪阶段")
		每日已接完 = true
	}
}

// 每日下一个类型 切到下一个 tab（清掉当前 tab 的进度）
func 每日下一个类型() {
	每日第几类型++
	每日已切类型 = false
	每日滑动次数 = 0
}
