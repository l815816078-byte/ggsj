// 每日任务（照 plugin/每日任务.go + plugin/挂机中.go:35-49 + assets/tasks/每日任务.json 搬）
//
// 老框架：主菜单 → 滑动 → 点【任务】→ 插件（【每日】【周常】两个 tab 循环接取
//	→ 点【每日】→ 【绿色战力】多个逐个点 → 打怪任务 → 自动进行 → 蓝色按钮）
//	→ 退出 → 一次都没点过蓝色按钮 = 直接完成；点过 = 进 挂机中 打怪
//
// ★ 打怪阶段调通用 挂机跑()（跟 野外挂机/落花战场 一样）。
//   每日任务的特例（照 plugin/挂机中.go:35-49）已经分叉在 挂机.go 的 ② 和 ⑥ 里：
//	· ② 不判断【自动攻击开启中】：改判【任务进行中】；或 先【省电模式】再【/】
//	· ⑥ 挂机中也跑子任务（跟"只有野外挂机才跑"那条并列，照 plugin:47）
//   ★ 别在任务自己的文件里另写挂机函数 —— 分叉一律放通用模块里按 当前任务 判。
//
// ★ 写法 = 老脚本 _Whereas：一轮之内把顺序过完，**命中才 return**（点了屏幕变了，
//   再识别没意义）；没命中就继续往下走，不 return。点完不消失的用标志位挡。
//
// ★ 2026-10-18 重构：原来 9 个状态变量（每日菜单已点/每日已滑动/每日面板已开/
//   每日第几类型/每日已切类型/每日滑动次数/每日已点每日/开始挂机/每日已接完）
//   砍到只剩 开始挂机 —— 开门链改链式调用、两个 tab 改一轮跑完（用户："搞这么多状态 没用啊"）。
// ══════════════════════════════════════════════════════════════════════════

// 是否接取无需战力任务 / 每日类型列表 / 每日最多滑动 都配在 点库.go 的「业务配置」段

// 开始挂机 点过 ⑤ 位置的【蓝色按钮】= 接到打怪任务 → 下轮进打怪阶段（跨轮状态）
var 开始挂机 = false

// 每日任务重置 由 切下一个任务() / 重跑当前任务() 调
func 每日任务重置() {
	开始挂机 = false
	挂机重置()
}

// 每日任务跑 一轮跑完：打怪 → 开门链 → 两个 tab → 点【每日】→ 绿色战力 → 退出
func 每日任务跑() {
	// ── ① 打怪阶段（接取已做完）：通用挂机模块（照 plugin/挂机中.go:35-49，
	//    它里面已经按"是不是每日任务"分好了叉：不判断自动攻击、挂机中也跑子任务）
	if 开始挂机 {
		挂机跑()
		return
	}

	// ── ② 打开任务面板：主菜单 → 滑动 → 点【任务】（点到 = 面板开了）─────
	当前状态 = "开任务面板"
	if !查找点击延时("主菜单") {
		return
	}
	m := 滑动表["开面板"]
	if m.前置验证 == "" || 是否存在(m.前置验证) {
		core.LogWithTimef("[每日任务] 滑动 %d,%d → %d,%d", m.起点X, m.起点Y, m.终点X, m.终点Y)
		core.RandomSwipe(m.起点X, m.起点Y, m.终点X, m.终点Y, m.时长, m.滑后延时)
	}
	if !查找点击延时("任务") {
		return
	}

	// ── ③ 两个 tab 一次跑完（每个 tab：切过去 → 接取已满/找到任务/滑满换下个）─
	当前状态 = "接取每日"
	for _, 类型 := range 每日类型列表 {
		if 已停止() {
			return
		}
		if !查找点击延时(类型) {
			return
		}
		core.LogWithTimef("[每日任务] 已切到任务类型【%s】", 类型)
		// ★ 接取之前先从下往上滑到底（滑到出现【不符合战力】= 到底了）
		// 因为已经提前滑到底部，所以循环里 73-93 的滑动是【从上往下】往回接
		m := 滑动表["每日列表"]
		for i := 1; i <= m.次数; i++ {
			if 已停止() || 是否存在("不符合战力", 552, 171, 834, 622) {
				break
			}
			cx := (m.起点X + m.终点X) / 2
			core.LogWithTimef("[每日任务]【%s】滑到底 第%d次 (从下往上) → 滑动 (%d,%d)→(%d,%d)",
				类型, i, cx, m.起点Y, cx, m.终点Y)
			core.RandomSwipe(cx, m.起点Y, cx, m.终点Y, m.时长, m.滑后延时)
		}

		cx := (m.起点X + m.终点X) / 2
	滑动:
		for j := 1; j <= 3; j++ {
			if 已停止() {
				return
			}
			// 循环接取：60 秒超时，每轮之间歇 1 秒（接取已满 / 接到任务 → 换下一个类型）
			deadline := time.Now().Add(60 * time.Second)
			for time.Now().Before(deadline) {
				if 已停止() {
					return
				}
				if 是否存在("任务接取已满") {
					core.LogWithTimef("[每日任务]【%s】任务接取已满 → 下一个类型", 类型)
					break 滑动 // 连外层滑动循环一起跳出去，直接换下一个类型
				}
				if 查找点击延时("符合战力") || (是否接取无需战力任务 && 查找点击延时("无需战力")) {
					// 找到任务 → 同一轮把【蓝色按钮】也点了（照 plugin：点完任务紧接着接取）
					if !查找点击延时("蓝色按钮", 834, 626, 912, 705) {
						break
					}
				}
			}
			core.LogWithTimef("[每日任务]【%s】从上往下滑 第%d次 (%d,%d)→(%d,%d)",
				类型, j, cx, m.终点Y, cx, m.起点Y)
			core.RandomSwipe(cx, m.终点Y, cx, m.起点Y, m.时长, m.滑后延时)
		}
	}

	// ── ④ 点【每日】（照 plugin 结尾回到"每日"页签）─────────────────────
	当前状态 = "回每日页签"
	查找点击延时("每日")

	// ── ⑤ 【绿色战力】多个一次全点完（点一个 → 检测打怪任务 → 自动进行 → 蓝色按钮）
	当前状态 = "点绿色战力"
	战力点 := 识别多个("绿色战力", 552, 171, 834, 622)
	core.LogWithTimef("[每日任务] 识别到 %d 个【绿色战力】", len(战力点))
	for _, pt := range 战力点 {
		if 已停止() {
			return
		}
		core.LogWithTimef("[每日任务] 战力 → 点击 (%d,%d)", pt.X, pt.Y)
		core.RandomClickInAreaWithDelay(pt.X, pt.Y, pt.X+5, pt.Y+5)
		// 点完检测【每日打怪任务】：没检测到 → 继续下一个（照 plugin 的 continue）
		if !是否存在("每日打怪任务", 857, 142, 1231, 587) {
			core.LogWithTimef("[每日任务] 战力(%d,%d) 未检测到【每日打怪任务】→ 继续下一个", pt.X, pt.Y)
			continue
		}
		core.LogWithTimef("[每日任务] 战力(%d,%d) 检测到【每日打怪任务】", pt.X, pt.Y)
		// 检测到 → 点【自动进行】→ 点【蓝色按钮】（照 plugin 同一轮做完）
		查找点击延时("自动进行", 773, 657, 827, 681)
		if 查找点击延时("蓝色按钮", 955, 631, 1102, 702) {
			开始挂机 = true
		}
	}

	// ── ⑥ 点【退出】收尾：一次都没接到打怪任务 = 直接完成；接到了 = 下轮进打怪
	if 查找点击延时("退出") {
		if !开始挂机 {
			core.LogWithTimef("[每日任务] 一次都没点【蓝色按钮】→ 直接完成整个任务")
			切下一个任务()
			return
		}
		core.LogWithTimef("[每日任务] 点过【蓝色按钮】→ 进打怪阶段")
	}
}
