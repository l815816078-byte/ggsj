// ══════════════════════════════════════════════════════════════════════════
// 秘境探索 —— 普通任务（照 门派战斗/封印解除 的"一遍走完"写法）
//
// 用户原话：
//	主菜单，秘境探险
//	秘境列表（面板锚点）
//	分类 tab → 门 → 按战力选难度 → 点
//	点完难度 → 黄色按钮 → 检测【秘境时间不足】（认到 = 这扇门时间不够 → 换下一扇门）
//	→ 确认（点击后等 6 秒）= 入场 → 整个分类循环停
//	→ 30 秒内检测【场景_秘境探索】：认到 → 走挂机那套（副本配置，见 挂机参数表）；
//	  认不到 → 错误处理（不进挂机）
//	最后退出
//
// 配置全在 业务配置.go 的「秘境探索」段（秘境分类表 + 两张通用难度表），
// 挂机参数（判据/场景/副本/跑子任务/时长）在 挂机参数表 的 "秘境探索" 一行。
// ══════════════════════════════════════════════════════════════════════════

// ── 状态（完成标志 + 挂机标志）─────────────────────────────────────────
// ★ 命名规范（用户 2026-10-20）：跨轮状态叫「XXX已挂机」不叫「XXX已入场」——
//   表达"现在处于挂机阶段"而不是"进过场的历史"：挂机出问题（没动静重跑/场景掉了）
//   时 秘境探索重置() 一清就能重新入场，不会被永久钉死（照 落花战场 的 落花已挂机）
var (
	秘境探索已完成 = false
	秘境已挂机     = false // 认到【场景_秘境探索】→ 人在副本里挂着，下轮直接挂机
)

// 秘境探索重置 由 切下一个任务() / 重跑当前任务() 调
func 秘境探索重置() {
	秘境探索已完成 = false
	秘境已挂机 = false
}

// 秘境探索跑 = 主循环每轮调一次
func 秘境探索跑() {
	战力 := 读战力()
	// ⓿ 跑完了 → 切下一个任务（普通任务没有 跑子任务() 帮它查完成，必须自检）
	if 秘境探索已完成 {
		切下一个任务()
		return
	}
	// ⓵ 已挂机（上轮认到过场景）→ 每轮直接挂机，别再走前面入口链
	//   ★ 没这道的话：副本里每轮都从入口链重走（点主菜单→秘境探险→tab→门→难度→确认），
	//     人在副本里这些点击全是瞎点，挂机永远进不了（照 落花战场 的 落花已挂机）
	//   ★ 叫"已挂机"不叫"已入场"（用户 2026-10-20）：挂机出问题被重跑/重置时，
	//     这个标志一清就重新走入场，不会因为"进过场"被永久挡住
	if 秘境已挂机 {
		挂机跑()
		return
	}

	// 进门链
	查找点击延时("主菜单")
	查找点击延时("秘境探险")

	// 面板锚点（秘境列表）
	if !是否存在("秘境列表") {
		// ★ 判据是【主菜单列表】还在（= 菜单展开、点秘境探险没反应 = 没这功能）→ 置完成；
		//   主菜单列表认不到 = 菜单已收起/面板加载中 → 收尾等下轮（不能置完成，会误杀）
		//   ★ 不能用 !是否存在：菜单开着时主菜单列表恒可见，取反永远进不来 → 死循环
		if 是否存在("主菜单列表") {
			秘境探索已完成 = true
			core.LogWithTimef("[秘境探索] ✅ 完成（没有秘境功能）")
			return
		}
		查找点击延时("关闭")
		return
	}

	if 已停止() {
		return
	}

	// 所有分类一次走完；任一扇门入场成功 → break 两层（后面的分类/门不试了）
	入场了 := false
	for _, 分类 := range 秘境分类表 {
		if 已停止() {
			return
		}
		core.LogWithTimef("[秘境探索] 分类【%s】→ 点击 tab (%d,%d,%d,%d)",
			分类.名称, 分类.区域[0], 分类.区域[1], 分类.区域[2], 分类.区域[3])
		core.RandomClickInAreaWithDelay(分类.区域[0], 分类.区域[1], 分类.区域[2], 分类.区域[3])
		core.RandomSleep(300, 500)

		for _, 门 := range 分类.门列表 {
			if 已停止() {
				return
			}
			// 门区域零值 = 点开分类直接可见，不用点
			if 门.区域 != [4]int{} {
				core.LogWithTimef("[秘境探索] 【%s·%s】→ 点击门 (%d,%d,%d,%d)",
					分类.名称, 门.名称, 门.区域[0], 门.区域[1], 门.区域[2], 门.区域[3])
				core.RandomClickInAreaWithDelay(门.区域[0], 门.区域[1], 门.区域[2], 门.区域[3])
				core.RandomSleep(300, 500)
			}
			难度, ok := 选秘境难度(分类.难度表, 战力)
			if !ok {
				core.LogWithTimef("[秘境探索] 【%s·%s】战力 %d 不满足任何难度门槛 → 跳过", 分类.名称, 门.名称, 战力)
				continue
			}
			core.LogWithTimef("[秘境探索] 【%s·%s】选难度（门槛 %d）→ 点击 (%d,%d,%d,%d)",
				分类.名称, 门.名称, 难度.战力门槛, 难度.区域[0], 难度.区域[1], 难度.区域[2], 难度.区域[3])
			core.RandomClickInAreaWithDelay(难度.区域[0], 难度.区域[1], 难度.区域[2], 难度.区域[3])

			// ① 黄色按钮（确认入场的那个）
			查找点击延时("黄色按钮")

			// ② 时间不足 → 这扇门打不了，断开内层，找下一扇门（用户 2026-10-20）
			if 是否存在("秘境时间不足") {
				core.LogWithTimef("[秘境探索] 【%s·%s】检测到【秘境时间不足】→ 断开，找下一扇门", 分类.名称, 门.名称)
				continue
			}

			// ③ 确认（点击后等 6 秒）= 入场 → 整个分类循环停（用户 2026-10-20）
			查找点击延时("确认", 6000)
			入场了 = true
			break
		}
		// 入场了 → 外层分类循环也停
		if 入场了 {
			break
		}
	}

	// 一扇门都没进（全时间不足/全跳过）→ 收尾退出
	if !入场了 {
		core.LogWithTimef("[秘境探索] 没有可入场的门 → 点【退出】")
		if 查找点击延时("退出") {
			秘境探索已完成 = true
			core.LogWithTimef("[秘境探索] ✅ 完成")
		}
		return
	}

	// ④ 入场了 → 30 秒内检测【场景_秘境探索】（倒计时里的"0"）
	//    认到 = 真进副本了 → 走挂机那套；认不到 = 错误处理，不进挂机（用户 2026-10-20）
	if !持续找色("场景_秘境探索", 30*time.Second) {
		core.LogWithTimef("[秘境探索] ⚠️ 30 秒没检测到【场景_秘境探索】→ 没进副本，错误处理（不挂机）")
		return
	}
	core.LogWithTimef("[秘境探索] 检测到【场景_秘境探索】→ 已进副本，置挂机标志（下轮起直接挂机）")
	秘境已挂机 = true
	挂机跑()
}

// 选秘境难度 门槛 ≤ 战力里取最高的；同门槛多个 → 随机；一个都不满足 → ok=false（跳过）
func 选秘境难度(表 []秘境难度, 战力 int) (秘境难度, bool) {
	最高 := -1
	for _, 难度 := range 表 {
		if 难度.战力门槛 <= 战力 && 难度.战力门槛 > 最高 {
			最高 = 难度.战力门槛
		}
	}
	if 最高 < 0 {
		return 秘境难度{}, false
	}
	var 候选 []秘境难度
	for _, 难度 := range 表 {
		if 难度.战力门槛 == 最高 {
			候选 = append(候选, 难度)
		}
	}
	return 候选[rand.Intn(len(候选))], true
}
