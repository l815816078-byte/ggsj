// 门派战斗（照 plugin/门派战斗.go + assets/tasks/门派战斗.json 搬）
//
// 老框架：主菜单 → 滑动 → 点【门派战斗】→ 逐个点"已启用"的战场类型 + 各自处理方法 → 退出
//
// mian 写法：入口链用标志位一步一步推进（主菜单 → 滑动 → 门派战斗），
// 战场类型每轮点一个（照 plugin 的 for，但不一次点完）。
// ══════════════════════════════════════════════════════════════════════════

// 门派战场类型表配在 点库.go 的「业务配置」段（门派战场类型表 / 门派战场类型）

// ── 门派战斗自己的状态 ────────────────────────────────────────────────────
var (
	门派菜单已点 = false // 点过【主菜单】
	门派已滑动  = false // 入口滑动做过了没
	门派界面已开 = false // 点过【门派战斗】进去了没
)

// 门派战斗重置 由 切下一个任务() / 重跑当前任务() 调
func 门派战斗重置() {
	门派菜单已点 = false
	门派已滑动 = false
	门派界面已开 = false
}

// 门派战斗跑 一轮干一格
func 门派战斗跑() {
	// ① 入口：主菜单 → 滑动 → 点【门派战斗】（照 JSON 的三步）
	if !门派界面已开 {
		当前状态 = "进门派战斗"
		if !门派菜单已点 {
			if 查找点击延时("主菜单") {
				门派菜单已点 = true
			}
			return
		}
		if !门派已滑动 {
			m := 滑动表["门派面板"]
			if m.前置验证 == "" || 是否存在(m.前置验证) {
				core.LogWithTimef("[门派战斗] 滑动 %d,%d → %d,%d", m.起点X, m.起点Y, m.终点X, m.终点Y)
				core.RandomSwipe(m.起点X, m.起点Y, m.终点X, m.终点Y, m.时长, m.滑后延时)
				门派已滑动 = true
			}
			return
		}
		if 查找点击延时("门派战斗") {
			门派界面已开 = true
		}
		return
	}

	// ② 逐个战场类型：点区域 → 调它配好的处理方法（一次全部过完）
	当前状态 = "门派战场"
	for _, t := range 门派战场类型表 {
		if 已停止() {
			return
		}
		if !t.启用 {
			core.LogWithTimef("[门派战斗] 战场类型【%s】未启用 → 跳过", t.名称)
			continue
		}
		core.LogWithTimef("[门派战斗] 点击战场类型【%s】(%d,%d,%d,%d)",
			t.名称, t.区域[0], t.区域[1], t.区域[2], t.区域[3])
		core.RandomClickInAreaWithDelay(t.区域[0], t.区域[1], t.区域[2], t.区域[3])
		t.处理方法()
	}

	// ③ 都过完 → 点【退出】收工（照 JSON：门派战斗 → 退出 → #done）
	if 查找点击延时("退出") {
		core.LogWithTimef("[门派战斗] 全部处理完 → 点【退出】，切下一个任务")
		切下一个任务()
	}
}

