// 门派战斗跑 一轮跑完：进门链 → 逐个战场类型 → 退出 → 切走
func 门派战斗跑() {
	// ① 入口链一轮走完：主菜单 → 滑动 → 门派战斗（照 每日任务/落花战场 的开门链）
	//   ★ 最后认一下【门派列表】：没开成功就 return 等下一轮，不硬闯战场类型
	//     （认不到 = 面板没开，点战场类型会点空）
	当前状态 = "进门派战斗"
	查找点击延时("主菜单")
	m := 滑动表["门派面板"]
	if m.前置验证 == "" || 是否存在(m.前置验证) {
		core.LogWithTimef("[门派战斗] 滑动 %d,%d → %d,%d", m.起点X, m.起点Y, m.终点X, m.终点Y)
		core.RandomSwipe(m.起点X, m.起点Y, m.终点X, m.终点Y, m.时长, m.滑后延时)
	}
	查找点击延时("门派战斗")
	if !是否存在("门派列表") {
		查找点击延时("关闭")
		return
	}

	// ② 逐个战场类型：点区域 → 调它配好的处理方法（一次全部过完）
	当前状态 = "门派战场"
	for _, t := range 门派战场类型表 {
		if 已停止() {
			return
		}
		if !t.启用 {
			core.LogWithTimef("[门派战斗] 战场类型【%s】未启用 → 跳过", t.名称)
			continue
		}
		core.LogWithTimef("[门派战斗] 点击战场类型【%s】(%d,%d,%d,%d)",
			t.名称, t.区域[0], t.区域[1], t.区域[2], t.区域[3])
		core.RandomClickInAreaWithDelay(t.区域[0], t.区域[1], t.区域[2], t.区域[3])
		t.处理方法()
	}

	// ③ 点【退出】收工（点不到也切走，不卡在原地反复重跑）
	core.LogWithTimef("[门派战斗] 全部处理完 → 点【退出】，切下一个任务")
	查找点击延时("退出")
	// ★ 压冷却 30000~60000 秒（约 8~17 小时）：门派战斗一天最多跑一两轮（用户 2026-10-20）
	//   —— 任务表的 冷最小/冷最大 只有子任务用，普通任务走 压任务冷却()
	冷却秒 := 30000 + rand.Intn(30001)
	压任务冷却("门派战斗", time.Duration(冷却秒)*time.Second)
	切下一个任务()
}

