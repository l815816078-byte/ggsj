package mian

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 气运显现 —— 子任务（照 plugin/气运显现.go + assets/tasks/气运显现.json）
//
// 流程：主菜单 → 气运显现 → 认【气运列表】→ 按 气运类型表 依次切换类型，
//	每个类型的【气运】一次全部点完（点不到 = 这个类型没了，下一个）→ 点【退出】
// ══════════════════════════════════════════════════════════════════════════

// 气运类型表 依次切换的类型（生命之气是默认第一个，不需要点击）
var 气运类型表 = []struct {
	名称 string
	区域 [4]int // 点击区域 x1,y1,x2,y2（空 = 不需要点击，默认选中）
}{
	{名称: "生命之气", 区域: [4]int{}}, // 默认第一个，不需要点击
	{名称: "黎明气息", 区域: [4]int{80, 275, 120, 315}},
	{名称: "梦幻气息", 区域: [4]int{80, 415, 121, 456}},
	{名称: "红炎气息", 区域: [4]int{82, 559, 117, 594}},
}

// ── 气运显现自己的状态 ──────────────────────────────────────────────────────
var (
	气运已完成 = false // 类型表走完 + 退出点了（= 完成）
)

// 气运显现重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 气运显现重置() {
	气运已完成 = false
}

// 气运显现完成 = 类型表走完且面板已关（退出识别不到）
func 气运显现完成() bool { return 气运已完成 }

// 气运显现跑 子任务流程（每轮由 跑子任务() 调度，每轮只点该点的）
// 顺序：主菜单 → 气运显现 → 认【气运列表】→ 做事 → 点【退出】
func 气运显现跑() {
	查找点击延时("主菜单")
	查找点击延时("气运显现")
	if !是否存在("气运列表") {
		查找点击延时("关闭")
		return
	}

	// 类型表走完了（状态走到尽头）→ 点【退出】→ 完成
	// ★ 退出不是判据（它永远都在），判据是"类型表走完了"
	for _, 类型 := range 气运类型表 {
		if 已停止() {
			return
		}
		// 非默认类型 → 点击切换
		if 类型.区域 != [4]int{} {
			core.LogWithTimef("[气运显现] 点击气运类型【%s】(%d,%d,%d,%d)",
				类型.名称, 类型.区域[0], 类型.区域[1], 类型.区域[2], 类型.区域[3])
			core.RandomClickInAreaWithDelay(类型.区域[0], 类型.区域[1], 类型.区域[2], 类型.区域[3])
			core.RandomSleep(500, 1000)
		} else {
			core.LogWithTimef("[气运显现] 气运类型【%s】（默认第一个，无需点击）", 类型.名称)
		}

		// 当前类型的【气运】一次全部点完（点延时 600ms；点不到 = 这个类型没了的，下一个）
		for {
			if 已停止() {
				return
			}
			x, y, ok := 识别("气运")
			if !ok {
				core.LogWithTimef("[气运显现] 【%s】没有【气运】了 → 下一个类型", 类型.名称)
				break
			}
			core.LogWithTimef("[气运显现] 点击【气运】(%d,%d)", x, y)
			core.RandomClickInAreaWithDelay(x, y, x+3, y+3, 500)
		}
	}

	core.LogWithTimef("[气运显现] 类型表已走完 → 点【退出】")
	查找点击延时("退出")
	气运已完成 = true
}
