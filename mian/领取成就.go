package mian

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 领取成就 —— 子任务（纯步骤链，照 assets/tasks/领取成就.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	主菜单 → 成就 → 绿色按钮（等 6 秒）→ 退出
// ══════════════════════════════════════════════════════════════════════════

// ── 领取成就自己的状态 ────────────────────────────────────────────────────
var (
	领取成就已收 = false // 完成
)

// 领取成就重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 领取成就重置() {
	领取成就已收 = false
}

// 领取成就完成
func 领取成就完成() bool { return 领取成就已收 }

// 领取成就跑 子任务流程（每轮由 跑子任务() 调度，每轮只点该点的）
// 顺序：主菜单 → 成就 → 认【成就列表】→ 做事 → 点【退出】
func 领取成就跑() {
	查找点击延时("主菜单")
	查找点击延时("成就")
	if 是否存在("成就列表") {
		// 绿色按钮 → 等 6 秒（照 JSON 的 等待秒:6）
		查找点击延时("绿色按钮")
		查找点击延时("点击关闭")
		// 有绿色按钮就点、没也正常退出（没活干 = 也算做完）
		// ★ 退出必须点中才算完成：点不中 = 面板还开着，下轮接着来
		core.LogWithTimef("[领取成就] → 点【退出】")
		if 查找点击延时("退出") {
			领取成就已收 = true
			core.LogWithTimef("[领取成就] ✅ 完成")
		}
	} else if 是否存在("主菜单列表") {
		// 菜单开着（主菜单按钮被压住）却开不了成就面板 = 没红点/没这功能
		领取成就已收 = true
		core.LogWithTimef("[领取成就] ✅ 完成（没红点/没这功能）")
	}
}
