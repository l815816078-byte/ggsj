package mian

import (
	"app/core"
)

// ══════════════════════════════════════════════════════════════════════════
// 加护 —— 子任务（照 plugin/加护.go + assets/tasks/加护.json）
//
// 流程（= 老脚本 `_Whereas`：一轮之内把所有 if 顺序过完，命中的就点，不 return）：
//
//	主菜单 → 加护 →
//	1. 绿色按钮 / 确认 / 点击关闭 / 自动装备（按顺序，命中的就点）
//	2. 直接点击区域 184,78,280,105
//	3. 召唤阶段：先判【召唤用光】，命中即停 → 点【退出】完成
//	   否则按顺序点：召唤加护 / 跳过 / 绿色按钮 / 棕色按钮
// ══════════════════════════════════════════════════════════════════════════

// ── 加护自己的状态 ────────────────────────────────────────────────────────
var (
	加护已完成 = false // 完成：召唤用光 + 退出点了
)

// 加护重置 由 跑子任务() 在【完成后】调（超时不清 → 下次回来接着干）
func 加护重置() {
	加护已完成 = false
}

// 加护完成 = 召唤次数用光（命中过【召唤用光】）且退出点了
func 加护完成() bool { return 加护已完成 }

// 加护跑 子任务流程（每轮由 跑子任务() 调度，每轮只点该点的）
// 顺序：主菜单 → 加护 → 认【加护列表】→ 做事 → 点【退出】
func 加护跑() {
	查找点击延时("主菜单")
	查找点击延时("加护")
	if !是否存在("加护列表") {
		查找点击延时("关闭")
		return
	}

	// ① 弹窗按钮（= 老脚本 plugin/加护.go 的 ClickAdaptive）
	ClickAdaptive(60, 500, 3, nil,
		btn("绿色按钮"),
		btn("确认"),
		btn("点击关闭"),
		btn("自动装备"),
	)
	// ② 直接点击区域 184,78,280,105
	core.LogWithTimef("[加护] 直接点击区域 184,78,280,105")
	core.RandomClickInAreaWithDelay(184, 78, 280, 105)

	// ③ 召唤阶段：召唤加护 / 跳过 / 绿色按钮 / 棕色按钮；【召唤用光】命中即停（不点击）
	if ClickAdaptive(60, 500, 3, nil,
		btnStop("召唤用光"),
		btn("召唤加护"),
		btn("跳过"),
		btn("绿色按钮"),
		btn("棕色按钮"),
	) {
		core.LogWithTimef("[加护] 命中【召唤用光】→ 召唤次数用光，直接完成")
		查找点击延时("退出")
		加护已完成 = true
		core.LogWithTimef("[加护] ✅ 完成")
		return
	}
}
