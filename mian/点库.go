// 预设 一条识别配置（= recogs.json 的一条预设，Go 原生结构）
//
// 识别方式由"填了哪些字段"决定，顺序和 core.ExecWithConfig 一致：
//
//	多点找色   非空 → 多点找色
//	模板图片   非空 → 找图
//	透明图    非空 → 半透明找图
//	识别文字分类 "取文" → paddle 取文（读区域全部文字）；"取文字库" → 字库识字读文；空 → 找字
//	识别文字   非空 → 找字（= 识别文字分类 空时的默认）
//	颜色数组   非空 → 单色比色
//	多点找色Ex 非空 → 多点找色扩展（= 多点找色，但底层调 FindMultiColorEx）
//
// ★ 2026-10-21：取文/取文字库 两个 bool 合并成 识别文字分类 string（照 core.Exec 的
//   "识别文字分类"字段）——原来两个 bool 拆着配，找色文字()/取文() 各读一个，
//   "省电_金币"配 取文 却被 找色文字()（只认 取文字库）读 → 恒 false 死判断。
//   现在一个字段、一个分发器（基础.go 的 执行识别），两个出口：
//	识别(名) → 坐标（判在不在/点击用）；取文(名) → 文字（读数用）
type 预设 struct {
	多点找色   []string // 多点找色组合（每项一条，任一命中即算）
	多点找色Ex []string // 多点找色扩展（底层调 FindMultiColorEx，支持带绝对坐标首点）
	模板图片   []string  // 模板图文件名（assets/scene_*.png）
	透明图     []string  // 半透明模板图
	严格模式   bool      // 模板图用
	// 识别文字分类 文字类识别怎么读："取文"（paddle OCR）/ "取文字库"（字库识字）/ 空（= 找字，配 识别文字）
	识别文字分类 string
	识别文字   string   // 要找的文字（识别文字分类 空时生效）
	颜色数组   []string // 单色比色（#RRGGBB）
	找色方向   int      // 单色比色方向（0 = 1）

	颜色信息 string   // 取文/取文字库的颜色过滤（如 "#ECECEC-0x131313"）
	字库名   string   // 字库名，空 = "library"
	相似度   float64  // 阈值
	寻找个数 int      // 要找几个（0 = 1）
	中坐标   bool     // true = 返回目标中心
	偏移     [2]int   // 命中后坐标偏移 [dx,dy]
	区域     [][4]int // 截图区域（多区域：逐个试，第一个命中就返回）

	// 点击用截图区域 true = 命中后【不点命中点】，改用区域当点击范围随机点
	// （= plugin/wait.go:78-84 的优先级 2；调用处传了区域就优先用传入的，
	//  否则用上面"区域"的第一个）。recogs.json 原字段名就叫"点击用截图区域"。
	点击用截图区域 bool
}

